import { ReactNode } from 'react';

import { SHIP_KIND_LABELS, ShipField, ShipNotice, ShipTitle } from '@shared/types/channel';

/**
 * Строчка канала о корабле: вошёл, переоснастился, снялся с рейда.
 *
 * Фраза складывается здесь, а не на бэкенде: оттуда приходят только данные — каким корабль
 * был, каким стал и что именно в нём поменялось (см. `ShipNotice`). Зашитая в хранилище фраза
 * означала бы, что поправить формулировку можно только правкой уже записанного.
 */

/**
 * Как корабль зовут в строчке о входе и уходе: одним силуэтом, с большой буквы — фраза
 * с этого и начинается. Ни позывного, ни номера здесь нет: позывной написан над самой
 * строчкой, номер стоит на аватарке рядом с ней и на борту в кадре, и повторять их в фразе
 * значило бы называть корабль трижды подряд.
 */
function Title({ ship }: { ship: ShipTitle }) {
    return <>{SHIP_KIND_LABELS[ship.shipKind]}</>;
}

/**
 * Переоснащение: одна перемена — одна строчка, и в ней сказано только, что именно сменилось.
 *
 * Ни старого значения, ни нового. Раньше строчка их показывала — «042 теперь 782», «Теперь
 * тральщик», — и это было лишним трижды: новое и так стоит над строчкой позывным и на
 * аватарке номером, старое стоит выше в той же ленте, а сам корабль виден в кадре. Оставалась
 * пара почти одинаковых чисел, которую человек послушно сравнивал глазами, ничего из этого
 * не узнавая.
 *
 * Корабль в строчке не назван: она стоит в его же цепочке, с его аватаркой и позывным над ней.
 */
const REFIT_LINES: Record<ShipField, string> = {
    shipKind: 'Сменил корабль',
    name: 'Сменил позывной',
    hullNumber: 'Сменил бортовой номер',
};

interface ShipNoticeLineProps {
    notice: ShipNotice;
}

export default function ShipNoticeLine({ notice }: ShipNoticeLineProps): ReactNode {
    const who = <Title ship={notice.before} />;
    switch (notice.event) {
        case 'refit':
            // Без `changed` переоснащения не бывает, но тип этого не обещает, а выдумывать,
            // что именно сменилось, нельзя.
            return notice.changed ? REFIT_LINES[notice.changed] : null;
        case 'moved':
            // Перемена места — той же формой, что и переоснащение: подлежащего нет, строчка
            // стоит в цепочке самого корабля, и о ком речь, видно по аватарке и позывному
            // над ней. Куда именно он пошёл, не сказано: место на рейде называется
            // координатами, а не словами, а сам переход человек и так видит в кадре.
            return <>Сменил место стоянки</>;
        case 'left':
            // Уходящий говорит, куда пошёл, и его слова — главное в строчке: корабль
            // не пропадает с рейда молча. Корабль в ней не назван вовсе — она стоит в его же
            // цепочке, с его аватаркой и позывным над ней, — и потому речь идёт от него.
            //
            // Без курса остаётся прежняя фраза: так уходили до того, как курс стали
            // спрашивать, и придумывать за те корабли курс задним числом нельзя.
            // «Сняться с рейда» — это и значит покинуть якорную стоянку: подняли якорь
            // и пошли. Ровно то, что происходит в кадре, и ровно так об этом и говорят.
            return notice.course ? <>Уходит с рейда. Новый курс: {notice.course}</> : <>{who} снялся с рейда</>;
        case 'kicked':
            // «Снят с рейда», а не «выдворен»: рейд — не двор, и с него снимают, как снимают
            // с якоря. Слово при этом остаётся страдательным — в отличие от снявшегося сам,
            // корабль тут не решал ничего.
            return <>{who} снят с рейда</>;
        case 'joined':
        default:
            return <>{who} встал на рейд</>;
    }
}
