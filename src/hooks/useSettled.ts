import { RefObject, useEffect, useState } from 'react';

import { stillness } from '@/utils/motion';

/**
 * Признак «места не хватает», включение которого ждёт, пока блок доедет.
 *
 * Раскладка решает про блок сразу и целиком: свайп кончился — и разговор уже знает, что стоит
 * на полу, хотя коробка ещё едет туда полсекунды. Убрать по такому решению содержимое сразу —
 * значит показать, как из ещё полной коробки пропало всё, что в ней было, а сминаться она
 * только начала. Поэтому включение придерживают до конца движения (см. `stillness`
 * в utils/motion).
 *
 * Выключение — сразу, без всякого ожидания. Коробка едет уже открытая, и держать её пустой
 * до конца дороги не за чем: место под содержимое там появляется с первого же кадра, а ждать
 * полсекунды перед пустой коробкой человек будет как ответа на своё нажатие.
 *
 * Блок, которому ехать нечем — не нарисован, движение выключено в системе, размер меняют
 * пальцем без всякого перехода, — отвечает тем же кадром и на включение.
 */
export const useSettled = (value: boolean, node: RefObject<HTMLElement | null>): boolean => {
    const [drawn, setDrawn] = useState(value);

    useEffect(() => {
        const element = node.current;
        if (!value || !element) {
            setDrawn(value);
            return undefined;
        }
        // Пока ждали, решение могло перемениться обратно: тогда это ожидание ни при чём,
        // и ответит уже следующее.
        let stale = false;
        void stillness(element, () => stale).then((still) => {
            if (still) {
                setDrawn(true);
            }
        });
        return () => {
            stale = true;
        };
    }, [value, node]);

    return drawn;
};
