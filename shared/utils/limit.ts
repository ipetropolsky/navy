/**
 * Предел длины набранного — один на все поля приложения.
 *
 * Правило взято у поля ввода в ленте, где оно и появилось первым: набранное сверх предела
 * не обрезается, а поле краснеет, и по нажатию говорится, насколько именно перебрали.
 * Обрезать чужой текст нельзя — человек не заметит потери, а заметит уже отправленным, —
 * и молчать тоже нельзя: недоступная кнопка без объяснения выглядит поломкой.
 *
 * Поэтому и `maxLength` у полей мягкий: атрибут до разметки не доходит вовсе (см. ui/Input),
 * а меркой служит вот эта пара — «перебрал ли» и «как об этом сказать».
 *
 * Меряется набранное без крайних пробелов: и отправляется, и сохраняется тоже оно,
 * и отказывать за пробел в конце значило бы мерить не то, что уйдёт.
 */

export const overLimit = (value: string, max: number): boolean => value.trim().length > max;

/**
 * Насколько перебрали. Одна фраза на все поля и на бэкенд: правило одно, и слова у него одни.
 *
 * Каталог общий (`shared/`) именно поэтому: длину курса при уходе меряет уже не браузер,
 * а серверная функция (`functions/src/raid.ts`), и мерить она обязана тем же и теми же словами.
 * Своей копии в функциях быть не должно — разойдись они, и человек увидел бы в форме один
 * предел, а в отказе сервера другой.
 */
export const limitMessage = (value: string, max: number): string =>
    `Максимум ${max} символов, у вас ${value.trim().length}`;
