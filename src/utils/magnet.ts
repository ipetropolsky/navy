/**
 * Магнитные точки шторки: где ей позволено остановиться и куда она уедет, когда её отпустят.
 *
 * Положений у шторки ровно столько, сколько ей задано точек, и между ними она не стоит никогда:
 * точка — это положение, в котором на шторку смотрят, а промежуток между двумя точками —
 * дорога, а не место. Отпущенная в дороге шторка доезжает до ближайшего места сама.
 *
 * Механика одна на все шторки приложения — и на карточку корабля, у которой положений всего
 * два, и на разговор, который выдвигается на треть, на две трети и во весь рост. Разница между
 * ними целиком в точках, а не в коде.
 *
 * Считается всё в «открытости»: 0 — шторка закрыта, максимальная точка — раскрыта до предела.
 * Не в сдвиге вниз, которым шторка едет по экрану: сдвиг — это то, как её показывают, а точки
 * задаёт тот, кто шторку заводит, и думает он про «на треть», а не «сдвинуть на две трети».
 * Перевод одного в другое — дело самой шторки, и он в одну строчку.
 */

/**
 * Точка остановки: число — пиксели, строка с процентом — доля хода.
 *
 * Проценты нужны потому, что ход у шторки не свой: он зависит от окна, от шапки над ней
 * и от того, сколько места осталось сцене. Пиксели — потому, что «не мельче трёхсот точек»
 * так и меряется, в точках, и в процентах на разных экранах означало бы разное.
 */
export type MagnetPoint = number | `${number}%`;

/**
 * Насколько две точки должны разойтись, чтобы остаться обеими, px.
 *
 * Точки ближе этого человек не различает: попасть между ними нельзя, а перескок с одной
 * на другую читается дрожанием, а не выбором. Сотня — расстояние, на котором два положения
 * шторки видно как два разных положения.
 */
export const MAGNET_GAP = 100;

/**
 * Какую долю пути до соседней точки надо пройти, чтобы шторка на ней не удержалась.
 *
 * Не половину: точка, на которой шторка стоит, держит её — уйти с неё должно быть решением,
 * а не случайностью, — но и держит не намертво. Треть с небольшим ровно тем и хороша:
 * короткий уверенный свайп уводит шторку к соседу, а дрогнувшая рука возвращает на место.
 */
export const MAGNET_ESCAPE = 0.35;

/**
 * Сколько шторка летит по инерции после того, как её отпустили, мс.
 *
 * Отсюда берётся «усилие»: точка приземления считается не там, где палец отпустил шторку,
 * а там, куда она долетела бы за это время с набранной скоростью. Сильный короткий рывок
 * от этого проскакивает сразу несколько точек и не цепляется за них — а именно так и закрывают
 * шторку одним движением, не отводя палец до самого низа.
 *
 * Полторы десятых секунды — не длительность полёта на экране (шторка приезжает к цели своим
 * обычным переходом), а мерка усилия: рывок в полтора экрана в секунду уносит шторку
 * на две с лишним сотни точек дальше места, где её отпустили.
 */
export const MAGNET_THROW_MS = 150;

/**
 * Насколько шторку удаётся утянуть за крайнюю точку, px.
 *
 * Ниже нижней точки шторке стоять негде: у формы своего корабля там полоска ручки, в которую
 * форма сминается мусором, — и предел этот жёсткий. Но жёсткий предел, отработанный молча,
 * читается заеданием: палец идёт, а шторка стоит, и непонятно, упёрлась она или сломалась.
 * Эта дюжина точек и есть ответ — шторка подаётся ровно настолько, чтобы упор был виден,
 * и отпущенная возвращается на место.
 *
 * Подаётся она с затуханием (см. `rubberBand`): первые пиксели идут почти как под пальцем,
 * дальше всё туже, и за эту дюжину не выходит, сколько ни тяни.
 */
export const MAGNET_GIVE = 12;

/**
 * Упор с оттяжкой: значение, зажатое пределами, но подающееся за них на `give` с затуханием.
 *
 * За пределом ход не обрывается, а вязнет: ушедший на `give` палец сдвигает шторку на половину
 * этого, ушедший вдвое дальше — на две трети, и так до самой оттяжки, которой ход и кончается.
 * Отсюда и ощущение упора вместо заедания: шторка отзывается на движение, но всё слабее,
 * и видно, что дальше её не пустят.
 */
export const rubberBand = (value: number, low: number, high: number, give = MAGNET_GIVE): number => {
    const strain = (over: number) => give * (1 - give / (over + give));
    if (value < low) {
        return low - strain(low - value);
    }
    if (value > high) {
        return high + strain(value - high);
    }
    return value;
};

/** Настройки магнита. Все со значениями по умолчанию: шторке хватает и одних точек. */
export interface MagnetSettings {
    /**
     * Точки остановки — все положения шторки без остатка. Не заданы — их две: закрыта
     * и раскрыта по содержимому (см. `normalizeMagnets`).
     */
    points?: MagnetPoint[];
    /** Насколько две точки должны разойтись, чтобы остаться обеими, px. */
    gap?: number;
}

/**
 * За какое время до отпускания меряется скорость, мс.
 *
 * Не за весь путь пальца: медленно подведённая и в последний миг брошенная шторка обязана
 * улететь, а долго тянутая и остановленная перед отпусканием — остаться. Считается поэтому
 * только последний отрезок, и если палец простоял на месте дольше него, скорости нет вовсе.
 */
export const FLING_MS = 80;

/** Сколько отметок пальца держим: на отрезок в FLING_MS их хватает с запасом при любой частоте
 *  событий, а больше — только память о том, что давно проехали. */
const FLING_MARKS = 5;

/** Мерка усилия: чем кончилось движение пальца, которым тянули шторку. */
export interface Fling {
    /** Отметить, куда палец увёл шторку (px открытости) и когда (timeStamp события). */
    mark: (open: number, at: number) => void;
    /** Скорость в момент отпускания, px/мс открытости: положительная — шторку раскрывали. */
    speed: (at: number) => number;
}

/**
 * Скорость в момент отпускания — по последним отметкам пальца.
 *
 * Живёт рядом с `settleMagnet`, потому что и нужна только ему: усилие — это второе, из чего
 * считается точка приземления, наравне с самим местом. Тянут шторки за разные ручки, и мерка
 * усилия у всех обязана быть одна: разойдись они, один и тот же бросок пальца закрывал бы одну
 * шторку и не закрывал другую.
 *
 * Меряется всё в открытости: сколько шторки видно, а не где на экране палец. Так знак скорости
 * означает одно и то же везде — «раскрывали» или «убирали», — хотя раскрывают шторки движением
 * в разные стороны.
 */
export const trackFling = (): Fling => {
    const marks: { open: number; at: number }[] = [];
    return {
        mark: (open, at) => {
            marks.push({ open, at });
            if (marks.length > FLING_MARKS) {
                marks.shift();
            }
        },
        speed: (at) => {
            const last = marks[marks.length - 1];
            // Палец стоял дольше отрезка: шторку подвели и поставили, а не бросили.
            if (!last || at - last.at > FLING_MS) {
                return 0;
            }
            const first = marks.find((mark) => last.at - mark.at <= FLING_MS) ?? marks[0];
            const spent = last.at - first.at;
            return spent > 0 ? (last.open - first.open) / spent : 0;
        },
    };
};

const clamp = (value: number, min: number, max: number): number => Math.min(Math.max(value, min), max);

/**
 * Которую из двух сошедшихся точек убрать: возвращается её место в списке.
 *
 * Остаётся та, у которой расстояния до соседей ровнее — считая соседей уже без выбывшей.
 * Пример из жизни: 300, 375, 400, 550. Сошлись 375 и 400; убери 400 — у 375 останутся
 * соседи в 75 и 175, убери 375 — у 400 в 100 и 150. Второе ровнее, и уходит 375.
 *
 * У крайней пары сравнивать нечего: соседа с одной стороны нет, и «ровнее» не определено.
 * Тогда остаётся дальняя от единственного соседа — то есть сам край: 300, 400, 500, 550
 * оставляет 550. Крайние точки и есть смысл всей шкалы — закрыто и раскрыто до предела, —
 * и подвинуть их внутрь означало бы отнять у шторки её же пределы.
 */
const crowdedOut = (points: number[], index: number): number => {
    const low = points[index];
    const high = points[index + 1];
    const left = points[index - 1];
    const right = points[index + 2];

    if (left !== undefined && right !== undefined) {
        const balance = (point: number) => Math.abs(point - left - (right - point));
        return balance(low) <= balance(high) ? index + 1 : index;
    }
    // Сверху соседа нет: дальше от левого стоит верхняя, она и остаётся.
    if (left !== undefined) {
        return index;
    }
    // Снизу соседа нет — либо его нет ни с одной стороны, и точек всего две. И там, и там
    // остаётся нижняя: она дальше от правого соседа, а в паре без соседей это закрытое
    // положение, без которого шторку нечем убрать.
    return index + 1;
};

/**
 * Точки шторки, которой их не задали: закрыта или раскрыта по содержимому.
 *
 * Ход шторки и есть её рост, а рост ей задаёт содержимое, — так что «во весь ход» это
 * и значит «по содержимому». Двух положений хватает всему, что показывают целиком: карточке
 * корабля, прощанию с рейдом, списку. Показывать их наполовину незачем — в них читают
 * и нажимают, а не подглядывают.
 */
const PLAIN_POINTS: MagnetPoint[] = [0, '100%'];

/**
 * Привести точки к пикселям и выкинуть сошедшиеся.
 *
 * `full` — весь ход шторки в пикселях: от него считаются проценты, им же ограничены пиксельные
 * точки. Точка за пределом хода не выбрасывается, а прижимается к нему: «не мельче трёхсот»
 * на экране в двести означает «во весь рост», а не «такого положения нет».
 *
 * Пустой список — не «магнита нет», а «точки обычные»: закрыто и по содержимому. Шторки без
 * положений в приложении не бывает — такую нечем ни убрать, ни достать.
 *
 * Порядок на выходе — от закрытого к раскрытому, повторов нет.
 */
export const normalizeMagnets = (points: MagnetPoint[], full: number, gap = MAGNET_GAP): number[] => {
    const pixels = (points.length ? points : PLAIN_POINTS).map((point) =>
        Math.round(clamp(typeof point === 'number' ? point : (parseFloat(point) / 100) * full, 0, Math.max(full, 0)))
    );
    const settled = [...new Set(pixels)].sort((first, second) => first - second);

    // Разбираем по одной сошедшейся паре за проход, начиная с самой тесной: убрав точку,
    // соседей приходится считать заново — выбывшая была соседом и для тех, кто рядом.
    //
    // Ниже двух не опускаемся ни при какой тесноте. Шторка с единственной точкой — это шторка,
    // которую нечем ни убрать, ни достать; а тесно двум последним бывает на маленьком экране,
    // где ход и сам меньше мерки, — и это как раз тот случай, когда шторка нужнее всего.
    while (settled.length > 2) {
        let tightest = -1;
        let least = Infinity;
        for (let index = 0; index < settled.length - 1; index += 1) {
            const span = settled[index + 1] - settled[index];
            if (span < gap && span < least) {
                least = span;
                tightest = index;
            }
        }
        if (tightest < 0) {
            break;
        }
        settled.splice(crowdedOut(settled, tightest), 1);
    }

    return settled;
};

interface SettleArgs {
    /** Где шторка стояла, когда её взяли, px открытости. */
    from: number;
    /** Где её отпустили, px открытости. */
    to: number;
    /** Скорость в момент, когда отпустили, px/мс. Положительная — шторка раскрывалась. */
    velocity: number;
    /** Точки в пикселях и по порядку — то, что вернул `normalizeMagnets`. */
    points: number[];
}

/** Ближайшая к `value` точка. Список не пустой и отсортирован. */
const nearest = (points: number[], value: number): number =>
    points.reduce((best, point) => (Math.abs(point - value) < Math.abs(best - value) ? point : best), points[0]);

/**
 * Соседняя точка в сторону движения: `step` +1 — раскрыть, −1 — прикрыть.
 *
 * Так шторку двигают не пальцем по ней самой, а со стороны: свайпом по кадру и стрелками
 * с клавиатуры. Оба говорят «дальше в эту сторону», а не «вот на столько-то», — и это
 * единственное, что им и нужно сказать: положений у шторки счётное число.
 *
 * С крайней точки шаг никуда не ведёт: шторка на пределе и на нём остаётся.
 */
export const stepMagnet = (points: number[], from: number, step: 1 | -1): number => {
    if (points.length === 0) {
        return from;
    }
    const index = points.indexOf(nearest(points, from));
    return points[clamp(index + step, 0, points.length - 1)];
};

/**
 * Куда шторка приедет, когда её отпустили.
 *
 * Считается не от места, где палец остановился, а от того, куда шторка долетела бы по инерции:
 * в этом и состоит учёт усилия.
 *
 * Точку выбирает не «какая ближе»: та, на которой шторка стояла, держит её, пока не пройдена
 * доля пути до соседа (`MAGNET_ESCAPE`), — а пройдя, шторка идёт дальше по точкам, пока хватает
 * инерции. Отсюда и «чем сильнее рывок, тем больше точек проскочит»: точки перебираются
 * по порядку, и остановит шторку та, до следующей от которой она не дотянула.
 */
export const settleMagnet = ({ from, to, velocity, points }: SettleArgs): number => {
    // Точек нет — держать нечем: где отпустили, там и осталась. В приложении такой шторки
    // не бывает (см. `normalizeMagnets`), но расчёт обязан вернуть число при любом списке.
    if (points.length === 0) {
        return to;
    }
    const first = points[0];
    const last = points[points.length - 1];
    const thrown = clamp(to + velocity * MAGNET_THROW_MS, first, last);

    // Откуда считаем: точка, на которой шторка стояла. Обычно она на ней и стоит — больше
    // ей негде, — но если ход успел измениться под ней, берём ближайшую.
    let index = points.indexOf(nearest(points, from));
    const step = Math.sign(thrown - points[index]);
    if (step === 0) {
        return points[index];
    }
    // Шаг за шагом в сторону движения, пока от очередной точки пройдена доля пути к следующей.
    // Пройденное считается со знаком: перелетев точку, шторка оказывается позади неё, и мерить
    // это как «прошла ещё столько же» значило бы гнать её обратно тем же движением.
    for (let next = index + step; next >= 0 && next < points.length; next += step) {
        const span = Math.abs(points[next] - points[index]);
        const covered = (thrown - points[index]) * step;
        if (covered < span * MAGNET_ESCAPE) {
            break;
        }
        index = next;
    }
    return points[index];
};
