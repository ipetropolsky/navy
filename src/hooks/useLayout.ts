import { flushSync } from 'react-dom';

import { CHAT_POINTS, CHAT_SHARE, SCENE_MIN_WIDTH, SHEET_TOP_GAP, SIDE_MIN_WIDTH } from '@/config/layout';
import { MagnetPoint, normalizeMagnets } from '@/utils/magnet';
import { sessionStore } from '@/utils/storage';

/**
 * Раскладка приложения и то, что о ней помнит вкладка.
 *
 * Раскладок две, и выбирает между ними форма окна, а не человек: окно выше своей ширины —
 * разговор стоит под кадром и меряется высотой; окно шире своей высоты — разговор стоит сбоку
 * и меряется шириной. Третьего положения нет, кнопки переключения тоже: повернул телефон —
 * раскладка сменилась сама, и спрашивать тут не о чем.
 *
 * Выбирает человек другое — **размер** разговора, и у каждой раскладки он свой: высота под
 * кадром и ширина сбоку помнятся раздельно. Иначе треть высоты, выбранная на телефоне,
 * оказывалась бы третью ширины после поворота — числом то же, местом совсем другое.
 *
 * Держится это разделением на два: **выбор** — то, что человек попросил, и **раскладка** —
 * то, что из этого выбора помещается в нынешнее окно. Выбор пишется в sessionStorage и меняется
 * только явными действиями: потянул за кромку, убрал разговор кнопкой. Окно, ставшее тесным,
 * выбора не трогает — оно лишь урезает то, что из него выходит, и стоит окну раздаться обратно,
 * разговор возвращается к выбранному размеру. Иначе одно случайное сужение стирало бы выбор
 * насовсем, а восстановить его было бы неоткуда.
 */

/** Где стоит разговор: под кадром (вертикальное окно) или сбоку от него (горизонтальное). */
export type LayoutMode = 'under' | 'side';

/** Размер разговора в одной раскладке. */
export interface ChatWish {
    /**
     * Какую долю хода занимает разговор, 0..1. Ноль значит «разговора на экране нет».
     *
     * Долей, а не пикселями: окно у одного человека меняется от монитора к ноутбуку и обратно,
     * и разговор в 400px на этих окнах — то треть экрана, то узкая щель. Доля переносится
     * между окнами сама, а пиксели пришлось бы каждый раз доводить руками.
     */
    share: number;
    /**
     * К какой доле разговор возвращается, когда его зовут обратно. Больше нуля всегда: убранный
     * разговор обязан помнить, каким он был, — иначе кнопка возврата открывала бы его каждый раз
     * умолчанием, стирая выбранный размер.
     */
    back: number;
}

/** Что человек выбрал: свой размер разговора на каждую из двух раскладок. */
export interface LayoutWish {
    under: ChatWish;
    side: ChatWish;
}

/** Окно, по которому всё считается. Обе мерки сразу: раскладку выбирает их отношение. */
export interface WindowShape {
    width: number;
    height: number;
}

/** Раскладка вместе с пределами, в которых её можно менять прямо сейчас. */
export interface Layout {
    mode: LayoutMode;
    /** Есть ли разговор на экране хоть чем-нибудь — хотя бы свёрнутой полоской. */
    shown: boolean;
    /**
     * Свёрнут ли разговор до своего пола (`floor`).
     *
     * Это не «убран»: под кадром на экране остаётся ручка с полем ввода, и в свёрнутый разговор
     * можно писать, не разворачивая его. Но и не «показан»: ленты в нём не видно ни строчки,
     * и всё, что спрашивает «есть ли куда показать разговор» — выезжающий в него список
     * кораблей, — про свёрнутый отвечает так же, как про убранный.
     */
    folded: boolean;
    /** Сколько разговор занимает сейчас, px: высоту под кадром, ширину сбоку. */
    size: number;
    /**
     * Самое малое, чем разговор стоит на экране, px.
     *
     * Под кадром это ручка с полем ввода под ней: разговор там незакрываемый, и свайп до упора
     * его сворачивает, а не уносит. Меряет пол не раскладка, а App — высота поля ввода меняется
     * от плашки ответа и от выреза экрана, — и приходит он сюда готовым числом.
     *
     * Сбоку пол нулевой: панель у правой кромки сворачивается уходом за неё целиком, и полоска
     * шириной в ручку там ничего бы не показывала — ни ленты, ни поля.
     */
    floor: number;
    /**
     * Сколько он занял бы, будь он на экране, px. Всегда больше нуля: это тот размер, в который
     * его вернёт кнопка.
     *
     * Нужен он не только ей. В ту же коробку открывают слои — форму своего корабля и список
     * кораблей, — и открыть их в убранную или свёрнутую панель нельзя: форма встала бы в ничто
     * или в полоску ручки с полем ввода. Панель поэтому сперва возвращается на экран (см.
     * `openLayer` в App.tsx), и возвращается ровно сюда — в тот размер, в каком её оставили.
     */
    back: number;
    /** Весь ход разговора, px: от «нет вовсе» до «во весь рост». Из него считаются доли. */
    full: number;
    /** Каким мелким разговор соглашается быть, оставаясь на экране, px. */
    min: number;
    /** Куда упирается свайп, px. */
    max: number;
}

/** Ключ в sessionStorage. Именно session: раскладка — про эту вкладку, а не про человека. */
const STORAGE_KEY = 'navy:layout';

const clamp = (value: number, min: number, max: number): number => Math.min(Math.max(value, min), max);

/**
 * Какая раскладка у окна такой формы. Единственное правило на весь выбор: окно шире своей
 * высоты — разговор становится сбоку.
 *
 * Ни ширины в пикселях, ни телефона с десктопом здесь нет нарочно. Место разговору ищут там,
 * где его больше: в лежачем окне остаётся ширина, в стоячем — высота. Порог по ширине отвечал
 * бы на другой вопрос — «большой ли экран», — и на планшете в портрете уводил бы разговор
 * в узкую колонку сбоку при полном экране свободной высоты.
 */
export const chatMode = (view: WindowShape): LayoutMode => (view.width > view.height ? 'side' : 'under');

/**
 * Весь ход разговора в этой раскладке, px.
 *
 * Сбоку это вся ширина окна. Под кадром — высота окна без полоски, на которую смотрит шапка:
 * «во весь рост» у разговора значит «до низа шапки», а не «до верха окна», — кнопками из шапки
 * он и убирается. От этого же числа считаются и доли: треть — это треть того, что под шапкой.
 */
export const chatRoom = (mode: LayoutMode, view: WindowShape): number =>
    mode === 'side' ? view.width : Math.max(view.height - SHEET_TOP_GAP, 0);

/**
 * Пол раскладки, px: самое малое, чем разговор стоит на экране.
 *
 * Под кадром это ручка с полем ввода — число меряется на месте и приходит снаружи. Сбоку пола
 * нет: панель уходит за кромку целиком, и полоска шириной в ручку не показывала бы ничего.
 */
const chatFloor = (mode: LayoutMode, floor: number): number => (mode === 'side' ? 0 : Math.max(floor, 0));

/**
 * Пределы размера в этой раскладке, px.
 *
 * Под кадром снизу — тот самый пол: ниже ручки с полем ввода разговор не сжимается, а кадр
 * над ним не сжимается ниже своего наименьшего роста — он просто уходит под разговор
 * (см. .appUnder в стилях). Сверху — весь ход.
 *
 * Сбоку пределы другие. Снизу — мерка самого разговора: уже 300px в нём перестаёт помещаться
 * лента. Сверху — мерка кадра: рейд про ширину, и отдавать ему меньше 600px незачем. В тесном
 * окне потолок оказывается ниже пола, и пол сильнее: разговор уже своего минимума не бывает.
 */
export const chatLimits = (mode: LayoutMode, view: WindowShape, floor = 0): { min: number; max: number } =>
    mode === 'side'
        ? { min: SIDE_MIN_WIDTH, max: Math.max(SIDE_MIN_WIDTH, view.width - SCENE_MIN_WIDTH) }
        : { min: chatFloor(mode, floor), max: chatRoom('under', view) };

/**
 * Размер, зажатый пределами раскладки, px.
 *
 * Пределы — про разговор, в котором есть что читать: уже трёхсот точек сбоку в нём перестаёт
 * помещаться лента. К свёрнутому они не относятся: пол (`floor`) — это не мелкий разговор,
 * а его отсутствие, полное или почти, и «уже своего минимума не бывает» про него ничего
 * не говорит. Без этого исключения свайп сбоку упирался бы в те же триста точек, и убрать
 * панель с экрана было бы нечем.
 *
 * Под кадром пол и есть минимум, и оба условия сходятся в одно: разговор там не бывает ниже
 * ручки с полем ввода ни при каком свайпе.
 */
const fitSize = (size: number, floor: number, min: number, max: number): number =>
    size <= floor ? floor : clamp(size, min, max);

/**
 * Настоящий ли это размер разговора — не пол и не ноль.
 *
 * Спрашивают об этом там, где размер запоминают местом возврата: возвращать разговор в ту же
 * полоску, из которой его позвали, значит не возвращать вовсе. Свёрнутый разговор помнит
 * прежний свой размер и в него же и раскрывается.
 */
const isRealSize = (size: number, floor: number): boolean => size > floor;

/** Точка `CHAT_POINTS` в пикселях этого хода: они записаны долями, но тип допускает и пиксели. */
const pointPixels = (point: MagnetPoint, full: number): number =>
    typeof point === 'number' ? point : (parseFloat(point) / 100) * full;

/**
 * Точки, к которым разговор притягивается, когда его отпустили, px.
 *
 * Точек четыре: пол раскладки и три доли хода (`CHAT_POINTS`) — треть, две трети, весь рост.
 * Сбоку у размера есть настоящие пределы, и доля, вышедшая за них, не выбрасывается,
 * а прижимается к упору: «две трети ширины» на окне в 1200 значит «до упора», то есть 600, —
 * а не «такого положения нет». Разошедшись меньше чем на `MAGNET_GAP`, сошедшиеся так точки
 * убирает сам `normalizeMagnets`, и сбоку их обычно остаётся три: убрать, треть, упор.
 *
 * Нижняя точка — пол, и пределами она не зажимается ни в одной раскладке (см. `fitSize`):
 * сбоку это ноль, и `SIDE_MIN_WIDTH` про него ничего не говорит — в 300px не помещается лента,
 * а там её нет вовсе. Без этой точки панель нечем было бы убрать свайпом, а разговор под кадром
 * — свернуть.
 *
 * `layered` — стоит ли поверх разговора слой: форма своего корабля или список кораблей.
 * Под кадром пол тогда из точек уходит. Пол там — это разговор, свёрнутый до ручки с плашкой
 * ввода, и держится он на этой плашке: она и есть то, ради чего свёрнутый разговор остаётся
 * на экране. У слоя плашки ввода нет, и в ту же полоску он сминается мусором — ручка, под ней
 * крестик, а полоса кнопок за кромкой окна. Нижним положением коробки со слоем служит поэтому
 * наименьшая настоящая доля, а закрывают слой крестиком и «Отменой».
 *
 * Сбоку пол значит совсем другое — «убрать панель за кромку», — и он остаётся при любом слое:
 * панель убирают вместе с тем, что в ней стоит, и это законное положение, а не смятое.
 */
export const chatMagnets = ({ mode, floor, full, min, max }: Layout, layered = false): number[] =>
    normalizeMagnets(
        [
            ...(layered && mode === 'under' ? [] : [floor]),
            ...CHAT_POINTS.map((point) => fitSize(pointPixels(point, full), floor, min, max)),
        ],
        full
    );

/**
 * С чем приложение открывается, когда вкладке нечего вспомнить: треть на обе раскладки.
 *
 * Треть — и не мелочь, в которой ничего не разобрать, и не то, что накрывает собой рейд.
 * От окна она не зависит вовсе: доля на то и доля.
 */
export const defaultWish = (): LayoutWish => ({
    under: { share: CHAT_SHARE, back: CHAT_SHARE },
    side: { share: CHAT_SHARE, back: CHAT_SHARE },
});

/**
 * Что из выбранного помещается в окно такой формы. Единственное место, где раскладка
 * встречается с геометрией, — и делается в нём три вещи: выбирается раскладка по форме окна,
 * доля переводится в пиксели по ходу этой раскладки, и результат зажимается её пределами.
 *
 * Убранная панель (доля в нуле) остаётся убранной при любом окне, а свёрнутый разговор —
 * свёрнутым: до минимума раскладки они не растягиваются (см. `fitSize`), иначе окно само
 * возвращало бы на экран то, что с него убрали.
 *
 * Под кадром ноль при этом означает не «нет на экране», а «свёрнут до пола»: убрать разговор
 * оттуда нечем и незачем — кнопки на телефоне нет, а полем ввода он остаётся под рукой.
 * Убранная кнопкой панель, застигнутая поворотом, тем же правилом и раскладывается в пол.
 *
 * Функция чистая: ни окна, ни хранилища она не знает — их знает хук ниже. Так её и проверяют.
 */
export const allowedLayout = (wish: LayoutWish, view: WindowShape, floor = 0): Layout => {
    const mode = chatMode(view);
    const full = chatRoom(mode, view);
    const { min, max } = chatLimits(mode, view, floor);
    const ground = chatFloor(mode, floor);
    const { share } = wish[mode];
    // Округляем до пикселя: дробный размер разговора даёт дробный кадр, а кадр рисует корабли
    // и подписи — половина пикселя там видна размытой кромкой.
    const size = fitSize(Math.round(share * full), ground, min, max);
    // Размер возврата считается по тем же правилам, только из другой доли: это тот же разговор,
    // просто в том виде, в каком он был бы на экране. Настоящим размером он остаётся всегда —
    // свёрнутое и убранное местом возврата не запоминаются (см. `isRealSize`).
    const back = clamp(Math.round(wish[mode].back * full), min, max);
    return {
        mode,
        shown: size > 0,
        folded: size > 0 && !isRealSize(size, ground),
        size,
        floor: ground,
        back,
        full,
        min,
        max,
    };
};

/** Годная ли это доля: число от нуля до единицы. Чужая запись и запись прошлой версии — нет. */
const isShare = (value: unknown): value is number => typeof value === 'number' && value >= 0 && value <= 1;

/** Разобрать записанный размер одной раскладки. Испорченное поле заменяется умолчанием. */
const readSize = (saved: unknown, fallback: ChatWish): ChatWish => {
    if (!saved || typeof saved !== 'object') {
        return fallback;
    }
    const { share, back } = saved as Partial<ChatWish>;
    return {
        share: isShare(share) ? share : fallback.share,
        // Возврат в ноль — это не возврат: разговор, которому некуда возвращаться, кнопкой
        // не открылся бы вовсе.
        back: isShare(back) && back > 0 ? back : fallback.back,
    };
};

/**
 * Что записано во вкладке. Испорченную запись молча заменяем умолчанием: раскладка — не те
 * данные, ради которых стоит показывать человеку ошибку, а чужая вкладка могла записать сюда
 * что угодно и в прошлой версии приложения.
 */
const readWish = (): LayoutWish => {
    const fallback = defaultWish();
    try {
        const saved: unknown = JSON.parse(sessionStore.read(STORAGE_KEY) ?? 'null');
        if (!saved || typeof saved !== 'object') {
            return fallback;
        }
        const { under, side } = saved as Partial<LayoutWish>;
        return { under: readSize(under, fallback.under), side: readSize(side, fallback.side) };
    } catch {
        return fallback;
    }
};

/** Записать выбор. Запрещённое хранилище — приватный режим, кончившаяся квота — молча пропускаем:
 *  за это отвечает сама дверь в хранилище (см. utils/storage). */
const writeWish = (wish: LayoutWish): void => sessionStore.write(STORAGE_KEY, JSON.stringify(wish));

/**
 * Отметка «окно прямо сейчас меняет размер». Висит на самом `<html>`, а правило по ней —
 * в App.module.less: пока отметка стоит, все переходы раскладки сняты (`--chat-move: 0s`).
 *
 * Зачем она. Высота сцены считается от `100dvh` и переходит во времени, а `100dvh` меняет
 * не разговор, а само окно — и меняет разом. Переход же ведёт кадр к новому росту полсекунды,
 * и всё это время кадр отмерен по окну, которого уже нет: на повороте телефона это было видно
 * отдельным движением поверх переезда разговора (замер: сцена шла 604 → 700 после того,
 * как окно уже стало 700 высотой). Переход нужен там, где высоту меняет разговор, и не нужен
 * там, где её меняет окно, — вот отметка и разводит эти два случая.
 *
 * Смена раскладки под отметку не попадает: окно там меняется на пиксель, а разговор переезжает
 * с одной кромки на другую — и это движение разговора, а не окна (см. `turns` в `look` ниже).
 *
 * На `<html>`, а не на самом приложении, нарочно: ставится она **синхронно**, прямо в обработчике
 * resize, — только так она успевает к пересчёту стилей того же кадра, в котором сменился `dvh`.
 * Опоздай она хоть на кадр, толку от неё не было бы вовсе: переход, уже пущенный браузером,
 * сменой секунд не останавливается. А className приложения пишет React, и ближайшая же его
 * отрисовка стёрла бы класс, поставленный руками, — на повороте она случается сразу же.
 */
const RESIZING_MARK = 'window-resizing';

/** Форма окна. Меняется она и без ведома человека — повернули телефон, вытащили ноутбук
 *  из док-станции, — и раскладка обязана это заметить. */
const useWindowShape = (): WindowShape => {
    const [shape, setShape] = useState<WindowShape>(() => ({ width: window.innerWidth, height: window.innerHeight }));
    // То же окно, но доступное обработчику без пересоздания подписки. Отметка ставится только
    // на настоящую перемену: resize приходит и от появившейся полосы прокрутки, и от клавиатуры
    // на телефоне, а снимать переходы там, где ничего не сдвинулось, незачем.
    const seen = useRef(shape);
    useEffect(() => {
        /**
         * Окно стало другим — раскладка обязана стать другой в том же кадре.
         *
         * Отсюда `flushSync`: обычная отрисовка встала бы в очередь и дошла бы до разметки
         * только следующим кадром, а `100dvh` браузер меняет прямо сейчас. Один кадр между ними
         * — это кадр, в котором высота окна уже новая, а размер разговора ещё старый, и кадр
         * в нём отмерен наполовину по одному окну, наполовину по другому. Событие resize
         * приходит до того, как браузер пересчитает стили, — успевает и то, и другое.
         *
         * `now` отделяет живое событие от единственного захода при подписке: там отрисовка
         * и так идёт, и `flushSync` посреди неё React справедливо не даёт.
         */
        const look = (now: boolean) => {
            if (seen.current.width === window.innerWidth && seen.current.height === window.innerHeight) {
                return;
            }
            const next = { width: window.innerWidth, height: window.innerHeight };
            // Сменилась ли раскладка. Отметка снимается ровно на этот случай: она говорит
            // «двигается окно, а не разговор», а тут разговор двигается как раз — он переезжает
            // с одной кромки на другую, и переезд этот и есть то самое движение, ради которого
            // переходы существуют. Пока отметка стояла и здесь, разговор с кадром вставали
            // на новые места первым же кадром: тянущий за угол окна человек видел не переезд,
            // а подмену.
            //
            // Снимается, а не просто не ставится: тянущий указатель шлёт resize подряд, и отметку
            // от предыдущего шага, до которой ещё не дошла очередь, надо убрать.
            const turns = chatMode(next) !== chatMode(seen.current);
            seen.current = next;
            if (!now) {
                setShape(next);
                return;
            }
            document.documentElement.classList.toggle(RESIZING_MARK, !turns);
            flushSync(() => setShape(next));
        };
        const onResize = () => look(true);
        window.addEventListener('resize', onResize);
        // Между первой отрисовкой и подпиской окно могло измениться — например, пока
        // догружались шрифты и появилась полоса прокрутки.
        look(false);
        return () => {
            window.removeEventListener('resize', onResize);
            document.documentElement.classList.remove(RESIZING_MARK);
        };
    }, []);

    // Снимается отметка через два кадра после того, как новое окно дошло до разметки.
    //
    // Два, а не один: первый заход случается ещё в том самом кадре, где сменилось окно, —
    // кадровые заявки выполняются после события resize, а стили в этом кадре ещё не считаны,
    // и снятая тут отметка пустила бы переход ровно на те перемены, ради которых её ставили.
    // Второй заход — уже после того, как этот кадр нарисован, и трогаться в нём нечему:
    // всё стоит на новых местах.
    //
    // Отсчёт заводится заново на каждую перемену окна, так что тянущий за угол окна указатель
    // отметку не теряет: она держится всё время, пока окно едет, и снимается, когда оно встало.
    useEffect(() => {
        let after = 0;
        const first = requestAnimationFrame(() => {
            after = requestAnimationFrame(() => document.documentElement.classList.remove(RESIZING_MARK));
        });
        return () => {
            cancelAnimationFrame(first);
            cancelAnimationFrame(after);
        };
    }, [shape]);

    return shape;
};

export interface LayoutControls {
    /** Раскладка, в которой приложение стоит прямо сейчас. */
    layout: Layout;
    /**
     * Новый размер разговора в пикселях: сразу зажатый по нынешнему окну. Записывать его
     * на каждый шаг свайпа незачем — по умолчанию не записывается, и запоминает натянутое
     * `keep` в конце.
     */
    resize: (size: number, remember?: boolean) => void;
    /** Запомнить то, что натянули. */
    keep: () => void;
    /**
     * Убрать разговор с экрана и не забыть размера, в котором он стоял.
     *
     * Убирается он сбоку, где он панель, — там для этого и есть кнопка в шапке. Под кадром
     * убирать его нечем: доля уходит в ноль в обеих раскладках разом (человек убирает
     * не «разговор сбоку», а разговор вообще), но вертикальная раскладка кладёт его в пол
     * (см. `allowedLayout`), и на экране остаётся ручка с полем ввода.
     */
    hide: () => void;
    /** Вернуть разговор туда, где его оставили: в каждой раскладке — в свой размер. */
    show: () => void;
}

/**
 * Раскладка приложения.
 *
 * `floor` — пол вертикальной раскладки в пикселях: ручка с полем ввода под ней. Меряет его
 * App по живой разметке и передаёт сюда: высота поля ввода зависит и от плашки ответа над ним,
 * и от выреза экрана снизу, и постоянным числом её не запишешь.
 */
export function useLayout(floor = 0): LayoutControls {
    const view = useWindowShape();
    const [wish, setWish] = useState(readWish);
    const mode = chatMode(view);

    // Меняется всегда размер нынешней раскладки, второй не касается никто: у высоты и ширины
    // своя память, и правка одной из них не должна значить правку обеих.
    const apply = useCallback(
        (patch: (was: ChatWish) => ChatWish, remember: boolean) =>
            setWish((was) => {
                const next = { ...was, [mode]: patch(was[mode]) };
                if (remember) {
                    writeWish(next);
                }
                return next;
            }),
        [mode]
    );

    // Тянут разговор в пикселях — за кромку, — а запоминается он долей: указатель говорит
    // «вот сюда», и это «сюда» переводится в долю нынешнего хода.
    //
    // Зажимается размер прямо здесь, а не только при отрисовке: свайп за кромку иначе копил бы
    // ход за пределом — увёл указатель на две сотни дальше упора, и обратно разговор тронулся бы
    // только через те же две сотни.
    //
    // Свёрнутый до пола разговор памяти о себе не стирает: `back` остаётся тем, чем был,
    // и раскроется разговор ровно в тот размер, в каком его свернули. То же и с убранным.
    //
    // Место возврата меняет только запоминаемый размер — тот, на котором разговор встал,
    // и только если это настоящий размер. Кадры свайпа его не трогают: палец, сворачивающий
    // разговор, проходит по дороге через все размеры подряд, и последний из них — не выбор,
    // а случайная отметка на пути. Прежде запоминался именно он: брошенный от трети разговор
    // возвращался куда-нибудь в сотню пикселей, мимо которой палец пролетел на полном ходу.
    const resize = useCallback<LayoutControls['resize']>(
        (size, remember = false) => {
            const full = chatRoom(mode, view);
            const { min, max } = chatLimits(mode, view, floor);
            const ground = chatFloor(mode, floor);
            const fitted = full <= 0 ? 0 : fitSize(size, ground, min, max);
            const share = full <= 0 ? 0 : fitted / full;
            apply((was) => ({ share, back: remember && isRealSize(fitted, ground) ? share : was.back }), remember);
        },
        [apply, floor, mode, view]
    );

    // Записывается сам выбор, а не то, во что его урезало окно: раздастся окно — разговор
    // вернётся к выбранному размеру. Натянутый размер становится и местом возврата: человек
    // тянул кромку сюда — сюда разговор и вернётся, когда его позовут обратно. Сюда — но
    // не в пол и не в ноль: возвращать разговор в ту же полоску, из которой его позвали,
    // значит не возвращать вовсе.
    const keep = useCallback(
        () =>
            setWish((was) => {
                const here = was[mode];
                const real = isRealSize(here.share * chatRoom(mode, view), chatFloor(mode, floor));
                const next = { ...was, [mode]: { ...here, back: real ? here.share : here.back } };
                writeWish(next);
                return next;
            }),
        [floor, mode, view]
    );

    // Убран разговор или нет — общее на обе раскладки, в отличие от размера. Человек убирает
    // не «разговор сбоку», а разговор вообще: если бы поворот телефона возвращал его на экран,
    // кнопка отменялась бы сама собой. А `back` при этом у каждой раскладки свой и не трогается
    // — вернётся разговор в тот размер, какой был выбран именно здесь.
    //
    // Показывает ноль всё равно только боковая раскладка: под кадром он читается полом, и там
    // от разговора остаётся ручка с полем ввода (см. `allowedLayout`).
    const both = useCallback(
        (patch: (was: ChatWish) => ChatWish) =>
            setWish((was) => {
                const next = { under: patch(was.under), side: patch(was.side) };
                writeWish(next);
                return next;
            }),
        []
    );

    const hide = useCallback(() => both((was) => ({ ...was, share: 0 })), [both]);
    const show = useCallback(() => both((was) => ({ ...was, share: was.back })), [both]);

    return { layout: allowedLayout(wish, view, floor), resize, keep, hide, show };
}
