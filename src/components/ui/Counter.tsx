import styles from './Counter.module.less';

/**
 * Счётчик у кнопки: сколько всего накопилось того, ради чего по ней нажимают. Сейчас такой
 * один — непрочитанные реплики на кнопке панели, — и живёт он здесь, а не по месту: цифра
 * в пилюле у кнопки одинаково выглядит везде, где бы её ни завели, и второй набор чисел
 * для второго такого счётчика разошёлся бы с первым на первой же правке.
 *
 * Где счётчик сидит, говорит хозяин: пилюля не знает ни про угол кнопки, ни про её размер.
 *
 * Читалке он не достаётся вовсе (`aria-hidden`): счётчик — это картинка того, что кнопка
 * и так обязана сказать своей подписью. Иначе она читалась бы дважды — «вернуть панель,
 * три новых сообщения» и следом голое «3».
 */

/** Дальше этого числа счётчик не растёт: цифры пошире растянули бы пилюлю через всю кнопку. */
export const COUNTER_MAX = 99;

export default function Counter({ value }: { value: number }) {
    return (
        <span className={styles.counter} aria-hidden="true">
            {value > COUNTER_MAX ? `${COUNTER_MAX}+` : value}
        </span>
    );
}
