import { RefObject, useEffect, useState } from 'react';

import { stillness } from '@/utils/motion';

/**
 * Признак, который ждёт, пока блок доедет.
 *
 * Раскладка решает про блок сразу и целиком: свайп кончился — и разговор уже знает, что стоит
 * на полу, хотя коробка ещё едет туда полсекунды. Всё, что нарисовано по такому решению,
 * случается посреди дороги: лента гаснет в коробке, которая только начала складываться,
 * и вместо сворачивания видно, как из полной коробки пропало содержимое.
 *
 * Здесь решение придерживают до конца движения (см. `stillness` в utils/motion) — и в обе
 * стороны, а не только на убывание. Растущая коробка иначе получала бы ленту первым же кадром,
 * когда роста в ней ещё на полстроки: поля ленты не сжимаются, и они отняли бы своё
 * у плашки ввода.
 *
 * Блок, которому ехать нечем — не нарисован, движение выключено в системе, размер меняют
 * пальцем без всякого перехода, — отвечает тем же кадром, и придержанного тут нет ничего.
 */
export const useSettled = <T>(value: T, node: RefObject<HTMLElement | null>): T => {
    const [drawn, setDrawn] = useState(value);

    useEffect(() => {
        const element = node.current;
        if (!element) {
            setDrawn(value);
            return undefined;
        }
        // Пока ждали, решение могло перемениться обратно: тогда это ожидание ни при чём,
        // и ответит уже следующее.
        let stale = false;
        void stillness(element, () => stale).then((still) => {
            if (still) {
                setDrawn(value);
            }
        });
        return () => {
            stale = true;
        };
    }, [value, node]);

    return drawn;
};
