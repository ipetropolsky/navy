/**
 * Мерки разговора с сервером: сколько ждать ответа и какими кусками брать ленту.
 *
 * Числа собраны здесь по той же причине, по которой в `config/layout` собраны мерки экрана:
 * их видно разом, и спорить с ними приходится в одном месте, а не в пяти.
 */

/**
 * Сколько ждём ответа на чтение, мс. Столько человек готов смотреть на пустой экран,
 * прежде чем решит, что сломалось.
 */
export const READ_TIMEOUT = 8_000;

/**
 * Сколько ждём подтверждения записи, мс. Больше, чем у чтения: записи дороже, и в этот срок
 * укладывается холодный старт серверной функции — первый вызов после простоя идёт секунду
 * с лишним, и обрывать его раньше времени значит терять то, что вот-вот дойдёт.
 *
 * Таймаут здесь — не отмена запроса, а решение «пора сказать человеку»: очередь записей
 * Firestore живёт своей жизнью и может дослать отправленное позже (см. docs/FIREBASE.md).
 */
export const WRITE_TIMEOUT = 10_000;

/** Сколько сообщений в странице ленты. */
export const MESSAGE_PAGE = 100;

/**
 * Какая доля загруженной ленты должна остаться выше окна, чтобы пойти за следующей страницей.
 * Не «домотал до самого верха»: к тому мгновению, когда человек упрётся в край, следующая
 * сотня должна уже лежать. Считается по прокрутке, а не по числу реплик — строчки разной
 * высоты, и треть ленты меряется экранами.
 */
export const PRELOAD_ABOVE = 0.3;

/**
 * Не чаще какого срока пишем отметку прочитанного, мс (см. `ChannelBackend.markSeen`,
 * `hooks/useUnread`). Отметке хватает поспевать за тем, как человек убирает канал с глаз, —
 * не за каждой пришедшей репликой, пока он в канале и просто читает: иначе запись документа
 * шла бы на каждую строчку подряд.
 */
export const MARK_SEEN_THROTTLE = 4_000;
