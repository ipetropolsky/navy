/**
 * Тычок или выделение — одно правило на всё приложение.
 *
 * Нажимаемых плашек с текстом внутри в приложении две: реплика в ленте (тычок — ответить)
 * и корабль в форме (тычок — выбрать). Обе состоят из текста, который человек имеет полное
 * право выделить и скопировать, — и обе поэтому обязаны отличать тычок от протяжки. Правило
 * это тонкое и его легко переписать в двух местах по-разному, поэтому оно живёт здесь одно.
 *
 * Настоящей кнопкой такая плашка быть не может: из `button` браузер не даёт выделить текст
 * вовсе, даже при `user-select: text`, — и нажатие по ней не сбрасывает уже набранное
 * выделение. Отсюда `div` с `role="button"`, а вместе с ним и обязанность отработать
 * клавиатуру самой: пробелом и вводом, как отработала бы кнопка.
 */

/**
 * Насколько далеко можно увести курсор или палец между нажатием и отпусканием, чтобы это
 * всё ещё считалось тычком, px. Дальше — уже протяжка: человек выделяет текст, а не нажимает.
 *
 * Порог нужен, потому что одним выделением не обойтись: протянуть можно и по пустому месту
 * плашки, и тогда выделять окажется нечего, а нажатие бы сработало. Восемь пикселей — обычный
 * запас на дрожь: палец на телефоне уезжает на два-три даже при честном тычке.
 */
export const TAP_SLOP = 8;

/** Что выделено в окне прямо сейчас. Пусто — не выделено ничего. */
export const selectedText = (): string => window.getSelection()?.toString().trim() ?? '';

/**
 * С чего началось нажатие: откуда и при каком выделении. У самого `click` этого не спросишь —
 * он приходит уже по отпусканию и про дорогу между ними молчит.
 */
export interface Press {
    x: number;
    y: number;
    selected: string;
}

export const startPress = (point: { clientX: number; clientY: number }): Press => ({
    x: point.clientX,
    y: point.clientY,
    selected: selectedText(),
});

/** Ушли ли от места нажатия дальше, чем позволено тычку. */
export const drifted = (press: Press | null, point: { clientX: number; clientY: number }): boolean =>
    press !== null && Math.hypot(point.clientX - press.x, point.clientY - press.y) > TAP_SLOP;

/**
 * Появилось ли выделение, которого до нажатия не было.
 *
 * Сравниваем именно с тем, что было выделено в начале нажатия, а не просто смотрим, есть ли
 * выделение вообще. Нажатие внутрь уже выделенного браузер схлопывает не сразу, и правило
 * «есть выделение — не срабатывать» отняло бы нажатие у следующего же тычка по той самой
 * плашке, которую человек только что выделял.
 */
export const selectedSince = (press: Press | null): boolean => {
    const selected = selectedText();
    return selected !== '' && selected !== press?.selected;
};

/** Было ли это нажатие тычком, а не протяжкой по тексту. */
export const isTap = (press: Press | null, point: { clientX: number; clientY: number }): boolean =>
    !drifted(press, point) && !selectedSince(press);
