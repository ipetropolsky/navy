/**
 * Правило одной очереди: пока свой корабль доигрывает манёвр, второй манёвр поверх него
 * не начинается — ждёт, пока первый закончится, и только тогда идёт следующий (issue про
 * рывок после «Уйти с рейда» → сразу «Встать на рейд»: без этого второй манёвр стартовал
 * поверх ещё не доигранного ухода, и сцена путала недоигранный старый ход с новым, — корабль
 * дёргался назад на прежнее место и оттуда мчался на новое быстрее хода).
 *
 * Правило чисто счётное — «сейчас раньше готового момента или нет» — и вся его суть в том,
 * чтобы не уйти в минус: манёвр, который уже кончился, ждать себя больше не просит. Проверять
 * такое в браузере, поднимая сцену и следя за кадрами, было бы работой для юнита куда дороже
 * самого правила.
 */

/** Момент (мс эпохи), когда закончится манёвр длиной `seconds`, начавшийся в `startedAt`. */
export const manoeuvreEndsAt = (startedAt: number, seconds: number): number => startedAt + seconds * 1000;

/**
 * Сколько ещё ждать (мс) до `readyAt`, если сейчас `now`. Не меньше нуля: прошедший момент
 * не просит ждать себя во второй раз.
 */
export const manoeuvreWaitMs = (readyAt: number, now: number): number => Math.max(0, readyAt - now);
