import { Message } from '@/types/channel';

/**
 * Непрочитанное: сколько чужих реплик пришло с тех пор, как разговор в последний раз был
 * на экране.
 *
 * Прочитанным считается всё, что человек мог видеть, — не то, что он действительно прочёл.
 * Разбирать это подробнее нечем и незачем: разговор либо на экране, либо убран за кромку,
 * и никакой середины между этим нет. Пока он на экране, лента растёт у человека на глазах,
 * и отметка идёт за ней; убрали разговор — отметка встала, и всё, что пришло после, копится
 * в счётчик на кнопке возврата.
 *
 * Считается тут только арифметика: саму отметку ведёт `useUnread`. Разведено это затем,
 * что правило проверяется юнитом, а хук без окна не заводится.
 */

/**
 * Новость ли это для него.
 *
 * Своё не в счёт: человек сам это и отправил. Служебные записи — тоже: они про рейд, а рейд
 * у него перед глазами всегда, разговор там убран или нет. Счётчик, растущий от того, что
 * и так видно в кадре, врал бы о числе непрочитанных реплик.
 */
const isNews = (message: Message, myId: string | null): boolean =>
    message.kind !== 'system' && message.author.memberId !== myId;

/**
 * Сколько новостей в ленте после отметки.
 *
 * Отметка — это последняя запись, которую человек застал на экране. Её самой в ленте может
 * и не быть: канал открывали пустым, и тогда отметки нет вовсе (`null`) — считаем с начала
 * ленты. Так же поступаем и с отметкой, которой в ленте не нашлось: записи отсюда не пропадают,
 * и такого случиться не должно, но выбирать между «ничего не пришло» и «пришло всё» лучше
 * в пользу второго — незамеченная реплика хуже лишней точки на кнопке.
 */
export const unreadAfter = (messages: Message[], seen: string | null, myId: string | null): number => {
    const mark = seen === null ? -1 : messages.findIndex((message) => message.messageId === seen);
    return messages.slice(mark + 1).filter((message) => isNews(message, myId)).length;
};
