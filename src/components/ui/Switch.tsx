import { CSSProperties, useId } from 'react';

import styles from './Switch.module.less';

export interface SwitchOption<T extends string> {
    value: T;
    /** Что написано на положении. Это положение, а не действие: «Ход», а не «дать ход». */
    label: string;
}

interface SwitchProps<T extends string> {
    /**
     * Как называется сам переключатель. На экране этой подписи нет — она для озвучки:
     * из одних положений непонятно, что именно ими выбирают.
     */
    label: string;
    options: readonly SwitchOption<T>[];
    value: T;
    onChange: (value: T) => void;
}

/**
 * Переключатель положений: лежачая дорожка со скруглением в полный рост, внутри в ряд подписи,
 * у выбранного — светлая пилюля поверх тёмного поля.
 *
 * Это не кнопка. Кнопка подписана тем, что случится по нажатию, и потому в каждом состоянии
 * показывает противоположное нынешнему: на якоре предлагает ход, под парами — якорь. Читать
 * по ней текущее состояние нельзя вовсе — видно ровно обратное. Переключатель показывает
 * все положения разом и метит то, в котором стоят: состояние читается без всякого угадывания.
 *
 * Положений в общем случае может быть и три: колонки дорожки нарезаются по их числу, пилюля
 * ездит по ним шагами в свою ширину. Двумя тут ничего не ограничено.
 *
 * Внутри — обычные радиокнопки, спрятанные поверх подписей. Так достаются даром и клавиши
 * (стрелками между положениями, как и положено группе), и озвучка, и выбор одного из многих:
 * писать это самому значило бы переписывать браузер и половину забыть.
 */
export default function Switch<T extends string>({ label, options, value, onChange }: SwitchProps<T>) {
    // Своё имя группы на каждый переключатель: два переключателя на экране с общим именем
    // браузер считал бы одной группой и гасил бы выбор в соседнем.
    const name = useId();
    // Где сейчас стоит пилюля. Ненайденное значение — нулевое положение: пусть лучше пилюля
    // стоит на первом, чем уезжает за край дорожки.
    const at = Math.max(
        0,
        options.findIndex((option) => option.value === value)
    );

    return (
        // Числа — данные: сколько положений и которое выбрано. Стилями этого не выразить,
        // и в разметке они остаются по тому же правилу, что цвет участника и мерки сцены
        // (см. STYLEGUIDE.md).
        <div
            className={styles.track}
            role="group"
            aria-label={label}
            style={{ '--switch-count': options.length, '--switch-at': at } as CSSProperties}
        >
            {/* Пилюля — одна на все положения и ездит между ними. Отдельным слоем, а не заливкой
                выбранной подписи: заливка на новом месте зажигалась бы, а не переезжала. */}
            <span className={styles.pill} aria-hidden="true" />
            {options.map((option) => (
                <label
                    key={option.value}
                    className={option.value === value ? `${styles.label} ${styles.labelOn}` : styles.label}
                >
                    <input
                        type="radio"
                        className={styles.input}
                        name={name}
                        checked={option.value === value}
                        onChange={() => onChange(option.value)}
                    />
                    {option.label}
                </label>
            ))}
        </div>
    );
}
