/** Опорная точка вертикального градиента воды. */
export interface GradientStop {
    /** Положение по вертикали: 0 — линия горизонта, 1 — ближний край. */
    at: number;
    /** Цвет в формате [r, g, b]. */
    color: [number, number, number];
}

/** Одна составляющая волнения: длинный вал, идущий к наблюдателю. */
export interface WaveComponent {
    /** Частота вдоль взгляда: чем больше, тем чаще гребни. */
    depthFrequency: number;
    /** Насколько сильно поперечная зыбь изгибает гребни этой волны, в радианах фазы. */
    bend: number;
    /** Вклад в общий рельеф. */
    amplitude: number;
    /**
     * Множитель скорости. Подобран как sqrt(47 / depthFrequency) — на глубокой
     * воде длинные волны бегут быстрее коротких, из-за этого рисунок всё время
     * немного меняется и не выглядит зациклённым.
     */
    speed: number;
    /** Сдвиг фазы, чтобы гребни разных волн не совпадали. */
    phase: number;
}

/** Составляющая, заданная поперёк взгляда: поперечная зыбь и разрывы дорожки. */
export interface LateralComponent {
    /** Частота поперёк взгляда. */
    crossFrequency: number;
    /** Частота вдоль взгляда: без неё рисунок стоял бы ровными столбами. */
    depthFrequency: number;
    /** Вклад в сумму. */
    amplitude: number;
    /** Скорость дрейфа. */
    speed: number;
    /** Сдвиг фазы. */
    phase: number;
}

