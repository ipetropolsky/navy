import { defineConfig, devices } from '@playwright/test';

/**
 * Сценарные проверки в настоящем браузере. Проверять сцену иначе не выходит: половина правок
 * ловится только замером — совпадают ли кадры воды на стыке цикла, помещаются ли корабли
 * на телефоне, доезжает ли сообщение во вторую вкладку.
 *
 * Запуск: `npm run test:e2e`. Собирать и поднимать сервер руками не нужно — это делает
 * webServer ниже. На чужой машине нужен один разовый шаг: `npx playwright install chromium`.
 */

const PORT = 4173;

/**
 * Готовый браузер в обход `playwright install`. Нужен там, где Chromium уже стоит и качать
 * его нельзя или незачем, — например в контейнере с предустановленными браузерами. На обычной
 * машине переменная не задана, и Playwright берёт свой, как и полагается.
 */
const executablePath = process.env.PLAYWRIGHT_CHROMIUM_PATH;

export default defineConfig({
    testDir: './tests',
    // Срок обычной проверки. Обычная — это открыть канал, нажать и посмотреть; таких в наборе
    // большинство, и укладываются они в секунду-две. Пять секунд — предел, за которым проверка
    // не «медленная», а сломанная, и висеть дольше ей незачем: чем раньше падение, тем раньше
    // о нём узнают.
    //
    // Кому пяти мало — ходу корабля через весь кадр, двум вкладкам, перезаходу на другое
    // место, — тот просит свой срок сам, по замеру: `takes(...)` в первой строке проверки
    // (см. tests/helpers.ts и docs/TESTING.md).
    timeout: 5_000,
    // Срок одного ожидания. Меньше общего нарочно: у проверки, кроме ожидания, есть и остальные
    // шаги, и упереться она должна в своё ожидание, а не в общий срок, — тогда в отчёте видно,
    // чего именно не дождались.
    expect: { timeout: 3_000 },
    fullyParallel: true,
    forbidOnly: Boolean(process.env.CI),
    retries: process.env.CI ? 1 : 0,
    reporter: process.env.CI ? 'github' : 'list',
    use: {
        baseURL: `http://localhost:${PORT}`,
        // Срок одного действия — нажатия, ввода, наведения. Без него Playwright перебирает
        // попытки до самого конца проверки: элемент виден, но нажать в него не выходит,
        // и упавшая проверка показывает восемьдесят подходов подряд вместо трёх. Смотреть
        // в такой отчёт бесполезно — первая попытка и восемьдесят шестая падают одинаково.
        //
        // Две секунды — это подходов пять: они идут через 20 мс, 100 мс и дальше через
        // полсекунды. Ждать элемент, который вот-вот появится, этого хватает с избытком:
        // время в прогоне ускорено вдесятеро, и всякий выезд в кадре идёт доли секунды.
        actionTimeout: 2_000,
        navigationTimeout: 5_000,
        trace: 'on-first-retry',
        ...(executablePath ? { launchOptions: { executablePath } } : {}),
    },
    // Проект один: гонять весь набор ещё раз в телефонном разрешении незачем — раскладка
    // и так проверяется отдельным файлом, который сам задаёт себе размеры экрана.
    projects: [{ name: 'chromium', use: { ...devices['Desktop Chrome'], viewport: { width: 1200, height: 900 } } }],
    webServer: {
        command: `npm run build && npx vite preview --port ${PORT} --strictPort`,
        url: `http://localhost:${PORT}`,
        reuseExistingServer: !process.env.CI,
        // Сборка с подъёмом сервера идут секунд двадцать. Минута — запас на медленную машину
        // и не больше: если сборка сломана, ждать её незачем вовсе.
        timeout: 60_000,
    },
});
