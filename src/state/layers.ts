/**
 * Что сейчас открыто поверх рейда — одним состоянием и набором намерений.
 *
 * Состояние здесь — доска, намерение — ход в нотации: «нажали название канала», «настроить свой
 * корабль», «корабль снялся с рейда». Что из этого выйдет, решает `reduce` — чистая функция без
 * окна, ссылок и таймеров, — а вид только доигрывает разницу. Оттого правила переходов и можно
 * гонять юнитами последовательностями ходов, а браузеру остаётся доказать одно: доска дошла
 * до экрана.
 *
 * Раскладывается всё на два яруса, и разница между ними не в содержимом, а в том, забирает ли
 * показанное экран себе:
 *
 * - **Слои** (`list`, `form`) приезжают внутрь коробки разговора и лежат в ней стопкой: форма
 *   ложится поверх списка и, уходя, возвращает человека в него. Рейд под ними живой.
 * - **Шторки** (`shownId`, `leaving`) встают поверх всего под затемнением: пока они на экране,
 *   разговор идёт только про них.
 *
 * Чего здесь нет нарочно: `inChat`, `loading` и прочего про сам канал. Открытость — это про
 * намерение человека, а видно ли открытое — про данные, и складывает эти две половины вид.
 * Иначе всякий приход сообщения переписывал бы то, что человек открыл.
 */

/** Слои и шторки: что открыто и ради чего поднята панель. */
export interface Layers {
    /** Список кораблей — нижний слой коробки. */
    list: boolean;
    /** Форма своего корабля — верхний слой, ложится поверх списка. */
    form: boolean;
    /** Чей корабль показан карточкой. Своей карточки нет: свой корабль настраивают. */
    shownId: string | null;
    /** Спрашиваем курс на прощание: шторка ухода с рейда. */
    leaving: boolean;
    /** Форма постановки в строй. Гость видит рейд, а не анкету, пока сам не решит встать. */
    joining: boolean;
    /**
     * Панель поднялась ради открытого в неё слоя — и задвинется обратно, когда тот закроется.
     * Помним это про нынешний слой, а не про панель вообще: перешли из формы в список — панель
     * уже просто открытая, и закрывать её за человека не за что.
     */
    brought: boolean;
    /**
     * Слой сел в закрытую панель и ждёт кадра, чтобы та тронулась вместе с ним. Кадр этот нужен,
     * чтобы на экране осталось одно движение вместо двух наехавших друг на друга: панель
     * выдвигается уже с готовым слоем внутри, и своего хода у слоя нет вовсе.
     */
    bringing: boolean;
}

export const NOTHING_OPEN: Layers = {
    list: false,
    form: false,
    shownId: null,
    leaving: false,
    joining: false,
    brought: false,
    bringing: false,
};

/**
 * Ход человека или события.
 *
 * `talking` у открывающих намерений — единственное, что модель спрашивает у раскладки: есть ли
 * куда показать слой прямо сейчас. Разговор на экране принимает слой как есть, убранный или
 * свёрнутый до ручки — сперва выдвигается сам, и это два разных хода, а не один.
 */
export type Intent =
    /** Нажали название канала: открыть список, а стоящую поверх форму — снять. */
    | { type: 'ships'; talking: boolean }
    /** Настроить свой корабль: из кадра, из списка или из карточки. */
    | { type: 'edit-ship'; talking: boolean }
    /** Форму закрыли — крестиком, отменой или отправкой. */
    | { type: 'close-form' }
    /** Список закрыли крестиком. */
    | { type: 'close-list' }
    /** Показать карточку чужого корабля. */
    | { type: 'show-ship'; memberId: string }
    /** Карточку закрыли. */
    | { type: 'close-card' }
    /** Уйти с рейда: спросить новый курс. */
    | { type: 'ask-course' }
    /** Передумали уходить. */
    | { type: 'close-course' }
    /** Корабль снялся с рейда. */
    | { type: 'left' }
    /** Открыть форму постановки в строй. */
    | { type: 'open-join' }
    /** Закрыть её, не вставая. */
    | { type: 'close-join' }
    /** Встал в строй: форма своё отработала. */
    | { type: 'joined' }
    /** Открыли канал. `own` — тот, что завели в этой же вкладке: там форму показываем сразу. */
    | { type: 'arrive'; own: boolean }
    /** Кадр, которого ждала поднимающаяся панель, прошёл. */
    | { type: 'panel-moved' }
    /** Размер разговора человек выбрал сам — панель больше не «поднятая ради слоя». */
    | { type: 'chose' }
    /** Слой уехал с экрана совсем: память о поднятой панели больше ни при чём. */
    | { type: 'layers-gone' };

/**
 * Открыть слой: при убранном разговоре его везёт панель, при показанном он едет сам.
 *
 * `brought` ставится в обоих случаях, а не только в первом: открыли форму поверх разговора,
 * который до того подняли ради списка, — панель перестаёт быть поднятой ради слоя, и задвигать
 * её потом было бы отбиранием того, что человек уже видит.
 */
const bring = (state: Layers, talking: boolean): Layers => ({
    ...state,
    brought: !talking,
    bringing: !talking,
});

export const reduce = (state: Layers, intent: Intent): Layers => {
    switch (intent.type) {
        // Название канала — и открывает список, и закрывает его тем же нажатием. Но если поверх
        // списка стоит форма, то же нажатие снимает её и возвращает к списку, из которого её
        // и позвали: закрывать разом оба слоя человек не просил.
        case 'ships': {
            const opening = state.form || !state.list;
            const next = { ...state, form: false, list: opening };
            return opening ? bring(next, intent.talking) : next;
        }
        // Карточку чужого корабля при этом закрываем: под шторкой лежит затемнение на всё окно,
        // и оставшись поверх формы, она накрыла бы ровно то, ради чего по кораблю и нажали.
        case 'edit-ship':
            return bring({ ...state, shownId: null, form: true }, intent.talking);
        case 'close-form':
            return { ...state, form: false };
        case 'close-list':
            return { ...state, list: false };
        // Список за собой не закрываем: карточка ложится поверх него и, закрывшись, возвращает
        // человека туда, откуда он её открыл.
        case 'show-ship':
            return { ...state, shownId: intent.memberId };
        case 'close-card':
            return { ...state, shownId: null };
        // Форму своего корабля закрываем: выход есть и в ней, а спрашивать курс поверх настроек
        // корабля, который через секунду уйдёт, незачем.
        case 'ask-course':
            return { ...state, form: false, leaving: true };
        case 'close-course':
            return { ...state, leaving: false };
        // Ушёл — и уносит с собой всё, что показывали своему кораблю: список, из которого уходят,
        // и саму шторку прощания.
        case 'left':
            return { ...state, leaving: false, list: false, form: false };
        case 'open-join':
            return { ...state, joining: true };
        case 'close-join':
        case 'joined':
            return { ...state, joining: false };
        // Свой канал встречает открытой формой: человек пришёл ставить корабль, а не смотреть
        // на пустую воду. Чужой — закрытой, и это же закрывает форму на уходе из своего.
        case 'arrive':
            return { ...state, joining: intent.own };
        case 'panel-moved':
            return { ...state, bringing: false };
        case 'chose':
        case 'layers-gone':
            return { ...state, brought: false };
        // Намерения кончились. Сюда попал бы ход, которого нет в `Intent`, — а такой не пройдёт
        // проверку типов: `never` ниже и есть та проверка. Заведут новое намерение, забыв про
        // `reduce`, — сборка встанет здесь.
        default: {
            const unknownIntent: never = intent;
            return unknownIntent;
        }
    }
};
