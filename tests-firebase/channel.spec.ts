/**
 * memberId === userId (см. `useChannel.ts`, «третий кандидат»): участие на Firebase адресуется
 * личностью, а не вкладкой, и вторая вкладка того же человека — это тот же корабль на рейде,
 * а не приглашение встать в строй заново. У местного бэкенда такого узнавания нет и не может
 * быть: там userId один на всех ('local'), а вкладки различают себя сами через localStorage.
 *
 * uid у обеих вкладок нарочно один и тот же — это и есть предмет проверки, а не оплошность.
 */
test('та же личность в новой вкладке видит свой корабль, а не встаёт в строй заново', async ({ browser }) => {
    // Идёт она секунд четырнадцать, но срок стоит не по этому замеру, а поверх собственных
    // ожиданий — захода в строй (WRITE_TIMEOUT + SAIL_TIMEOUT) и двух выходов сцены
    // по десять секунд, — по той же причине, что и в e2e.spec.ts: поставь срок по замеру,
    // и затянувшийся заход упёрся бы не в себя, а в общий срок, оставив в отчёте безличное
    // «Test timeout» вместо «свой корабль так и не встал на рейд».
    takes(35);

    const slug = `two-tabs-${Date.now()}`;
    const uid = 'two-tabs-uid';

    const pageA = await newTab(browser);
    await signIn(pageA, uid, 'Тот же человек');
    await createChannel(pageA, 'Один и тот же', slug);
    await join(pageA, 'Гроза', '101');
    await expect(ships(pageA)).toHaveCount(1);

    // Тот же человек, новый контекст браузера — своя личность, но не своя вкладка.
    const pageB = await newTab(browser);
    await signIn(pageB, uid, 'Тот же человек');
    await openChannel(pageB, slug);

    // Разговор открыт сразу: вторую вкладку не встречает форма постановки в строй.
    await expect(
        pageB.getByPlaceholder('Сообщение'),
        'вторая вкладка не узнала свой корабль и не открыла разговор'
    ).toBeVisible();
    await expect(
        pageB.getByRole('button', { name: 'Встать на рейд' }),
        'вторую вкладку той же личности встретило приглашение встать в строй заново'
    ).toHaveCount(0);

    // И корабль на рейде ровно один — не два одинаковых борта на одну и ту же личность.
    await expect(ships(pageB), 'на рейде оказался второй корабль той же личности').toHaveCount(1);
    await expect(pageB.locator('[class*="chatStatus"]')).toHaveText('1 на связи');

    // Тем же видит рейд и первая вкладка: второго входа не случилось и на сервере — строчка
    // о постановке в строй ровно одна, а не две подряд на одного и того же человека.
    await expect(ships(pageA)).toHaveCount(1);
    await expect(systemLines(pageA).filter({ hasText: 'встал на рейд' })).toHaveCount(1);

    await pageA.context().close();
    await pageB.context().close();
});

/**
 * «Гость» здесь — не тот, кто просто не встал в строй (этот случай для местного бэкенда
 * проверен в tests/channel.spec.ts), а тот, кого сервер не знает вовсе: вкладка без единого
 * входа. Документ канала правила читают только участнику (`isMember(channelId)`
 * в firestore.rules) — до входа канал открывает не он, а отдельная функция без проверки входа
 * (previewChannel, см. functions/src/preview.ts), и та отдаёт только название канала и то,
 * закрыт ли он: ни бортов, ни позывных, ни даже числа стоящих на рейде гостю не показывают
 * вовсе (см. docs/FIREBASE.md, «Что видит гость»). Разговор до входа не открывается ни при
 * каких обстоятельствах: встать на рейд, не назвавшись, нельзя.
 *
 * Разница с местным набором не в бэкенде, а в том, что у входа состояний три, а не два: гость,
 * закрытая форма, открытая форма. Местная вкладка всегда вошедшая (`createLocalEntrance`
 * заводит личность сама), первое состояние ей недостижимо — и в `tests/channel.spec.ts`
 * «пришедший по ссылке» это второе, с кнопкой «Встать на рейд». Здесь на её месте вход.
 *
 * Раньше рейд гостю всё же показывали, но обезличенным — бортовыми номерами вместо позывных, —
 * и первый же прогон этой самой проверки нашёл, что клики по нему `atGate` в App.tsx не запирал:
 * тычок по чужому кораблю открывал его карточку. Модель сменилась (issue #74) — участников
 * гостю не показывают вовсе, и кликать стало не по чему в принципе, поэтому вместо клика здесь
 * теперь проверка, что кораблей в кадре нет.
 */
test('канал по ссылке без входа: видно название канала и вход, а рейд — только после него', async ({ browser }) => {
    // Шесть секунд по замеру, а срок — поверх ожиданий, как и у соседней проверки выше.
    takes(35);

    const slug = `guest-view-${Date.now()}`;

    const owner = await newTab(browser);
    await signIn(owner, 'guest-view-uid', 'Хозяин рейда');
    await createChannel(owner, 'Гостю сюда', slug);
    await join(owner, 'Маяк', '404');

    // Гость: свежий контекст, ни разу не входивший.
    const guest = await newTab(browser);
    await openChannel(guest, slug);

    // Название канала видно и без входа — это и есть тот самый «вход в канал», к которому
    // ведёт ссылка: узнать, куда попал, можно, не входя, — а вот кто на рейде, уже нет.
    await expect(guest.locator('[class*="chatTitle_"]'), 'гостю не показали название канала').toHaveText('Гостю сюда');

    // А рейда не видно вовсе — ни одного корабля, ни настоящим позывным, ни обезличенным.
    await expect(ships(guest), 'гостю виден рейд, хотя он не участник').toHaveCount(0);

    // На месте разговора стоит вход, а не форма постановки в строй и не сам разговор.
    await expect(guest.getByPlaceholder('Сообщение'), 'гостю открыли разговор без входа').toHaveCount(0);
    await expect(guest.getByRole('button', { name: 'Встать на рейд' }), 'гостю предложили встать в строй').toHaveCount(
        0
    );
    await expect(
        guest.getByText('Войдите, чтобы увидеть, кто на связи, и поставить сюда свой корабль.'),
        'вход для гостя не показан'
    ).toBeVisible();
    await expect(guest.getByRole('button', { name: 'Войти' })).toBeVisible();

    // Списка кораблей гостю тоже нет, и мест на рейде не видно: смотреть на них не из чего.
    await expect(shipsButton(guest), 'гостю достался список кораблей').toHaveCount(0);
    await expect(berths(guest), 'гостю показали свободные места на рейде').toHaveCount(0);

    await owner.context().close();
    await guest.context().close();
});

/**
 * У местного бэкенда «вошедший не с этого рейда» — это состояние вкладки (localBackend.test.ts,
 * «вошедший не с этого рейда»); здесь же это состояние сервера. Второй настоящий аккаунт
 * получает от Firestore ровно тот же отказ, что и вовсе не вошедший гость выше, — не сам факт
 * входа решает, что видно (`isMember(channelId)` в firestore.rules), а участие именно в этом
 * канале (см. docs/FIREBASE.md, «Кто ещё может прийти»).
 *
 * Отдельно проверяем две вещи, которых по одному пустому превью не увидеть: что отказ
 * на участниках и ленте не путается с обрывом связи (строка о том, сколько на связи, жива
 * и честно говорит «никого нет», а не рвётся полоской «нет связи» — см. `firebaseBackend.ts`,
 * комментарий у подписки на участников, и docs/FIREBASE.md, «Состояние связи»), и что «Встать
 * на рейд» открывает весь рейд без перезагрузки страницы: настоящий позывной хозяина и реплику,
 * написанную ещё до входа, донашивает не подписка (её первый снимок — это состояние, а не
 * события), а отдельный запрос в `join()` (`hooks/useChannel.ts`).
 */
test('вошедший чужим аккаунтом видит рейд как гость, а встав в строй — как участник, без перезагрузки', async ({
    browser,
}) => {
    // Замер — секунд двадцать: два настоящих входа, один настоящий заход в строй (WRITE_TIMEOUT
    // + SAIL_TIMEOUT) и подтверждение записи сообщения сервером. Срок — поверх этой суммы,
    // а не по общему замеру набора, по той же причине, что и у соседних проверок файла.
    takes(45);

    const slug = `stranger-in-${Date.now()}`;

    const owner = await newTab(browser);
    await signIn(owner, 'stranger-in-owner', 'Хозяин рейда');
    await createChannel(owner, 'Не для чужого', slug);
    await join(owner, 'Маяк', '404');

    await send(owner, 'Есть кто на связи?');
    // Ждём подтверждения с сервера, а не только своей отрисовки: сообщению предстоит доехать
    // до вошедшего чужим аккаунтом через довыгрузку после входа в строй, а не через подписку
    // (см. JSDoc выше), и эта довыгрузка должна найти его уже в настоящем Firestore.
    await expect(pendingIcon(owner), 'сообщение хозяина так и не подтвердилось сервером').toHaveCount(0, {
        timeout: WRITE_TIMEOUT + 5_000,
    });

    // Другой человек, настоящий вход — но не на этот рейд.
    const stranger = await newTab(browser);
    await signIn(stranger, 'stranger-in-uid', 'Не с этого рейда');
    await openChannel(stranger, slug);

    // Рейда не видно вовсе — тем же самым способом (permission-denied → превью), что и вовсе
    // не вошедшему гостю выше: кто уже стоит на рейде, решает не сам факт входа, а участие
    // именно в этом канале.
    await expect(ships(stranger), 'вошедшему чужим аккаунтом виден чужой рейд').toHaveCount(0);

    // Строка связи жива и говорит о рейде, а не об обрыве: отказ Firestore на участниках
    // и ленте (permission-denied) — не то же самое, что обрыв сети, и не должен читаться как он.
    // «Никого нет» здесь не о самом рейде (на нём стоит корабль хозяина), а о том, что из него
    // видно вошедшему чужим аккаунтом: превью участников не отдаёт вовсе (см. JSDoc выше).
    await expect(stranger.locator('[class*="chatStatus"]')).toHaveText('никого нет');
    await expect(
        stranger.locator('[class*="connectionStrip"]'),
        'отказ в чтении чужого рейда показали как обрыв связи'
    ).toHaveCount(0);

    // В отличие от вовсе не вошедшего гостя, входить второй раз не просят — сразу приглашение
    // встать в строй: аккаунт уже есть, не хватает только участия в этом канале.
    await expect(
        stranger.getByRole('button', { name: 'Войти' }),
        'уже вошедшему чужим аккаунтом предложили войти ещё раз'
    ).toHaveCount(0);
    await expect(
        stranger.getByRole('button', { name: 'Встать на рейд' }),
        'вошедшему чужим аккаунтом не предложили встать в строй'
    ).toBeVisible();

    // Разговора не видно вовсе: ни поля ввода, ни реплики, написанной до входа в этот строй.
    await expect(
        stranger.getByPlaceholder('Сообщение'),
        'вошедшему чужим аккаунтом открыли разговор до входа на этот рейд'
    ).toHaveCount(0);
    await expect(bubbles(stranger), 'вошедшему чужим аккаунтом видна чужая лента').toHaveCount(0);
    await expect(shipsButton(stranger), 'вошедшему чужим аккаунтом достался список кораблей чужого рейда').toHaveCount(
        0
    );

    // Встаём в строй — и без перезагрузки страницы открывается всё как есть.
    await join(stranger, 'Секстант', '512');

    await expect(ships(stranger), 'после входа на рейд видны не все корабли').toHaveCount(2);
    await expect(
        stranger.locator('img[alt="Корабль «Маяк»"]'),
        'после входа на рейд бортовой номер хозяина так и не сменился на настоящий позывной'
    ).toBeVisible();
    await expect(
        bubbles(stranger).filter({ hasText: 'Есть кто на связи?' }),
        'сообщение, написанное до входа на этот рейд, не подгрузилось после «Встать на рейд»'
    ).toBeVisible();

    await owner.context().close();
    await stranger.context().close();
});

/**
 * «Закрытая частота» (issue #74): заведённый закрытым канал требует код доступа от всех, кроме
 * самого хозяина, — тот проходит без переспроса, потому что код только что назначил сам (см.
 * `!channel.owner` в joinChannel, functions/src/raid.ts, и `needsCode` в App.tsx). Экран кода
 * стоит на месте формы постановки в строй и не пускает дальше без него — ни посмотреть на рейд,
 * ни тем более на него встать: до верного кода закрытый канал неотличим от превью пустого
 * открытого (см. соседнюю проверку выше).
 *
 * Код на этом экране — не настоящая проверка, а лишь подсказка сразу, не отходя от поля (см.
 * `checkAccessCode` в src/backend/types.ts, previewChannel в functions/src/preview.ts):
 * по-настоящему его сверяет заново сам вход, joinChannel. Неверный код здесь и там отвечает
 * буквально той же фразой — она и проверяется.
 */
test('закрытый канал: неверный код отказывает, верный — пускает и на рейд, и в строй', async ({ browser }) => {
    // Замер — секунд тридцать пять: два настоящих входа, лишний запрос на неверный код,
    // подтверждение сообщения сервером и настоящий заход в строй (WRITE_TIMEOUT + SAIL_TIMEOUT).
    takes(55);

    const slug = `closed-channel-${Date.now()}`;
    const code = 'sword-fish';

    const owner = await newTab(browser);
    await signIn(owner, 'closed-channel-owner', 'Хозяин рейда');
    await createChannel(owner, 'Частота закрыта', slug, code);
    // Свой канал, только что заведённый, — код не спрашивают даже у закрытого: назначил его
    // только что сам (см. JSDoc выше).
    await expect(
        owner.getByRole('heading', { name: 'Закрытая частота' }),
        'хозяину собственного закрытого канала показали экран кода'
    ).toHaveCount(0);
    await join(owner, 'Маяк', '404');

    await send(owner, 'Есть кто на связи?');
    await expect(pendingIcon(owner), 'сообщение хозяина так и не подтвердилось сервером').toHaveCount(0, {
        timeout: WRITE_TIMEOUT + 5_000,
    });

    // Другой человек, настоящий вход, но канал закрыт — до кода не видно ни рейда, ни формы.
    const guest = await newTab(browser);
    await signIn(guest, 'closed-channel-guest', 'Проситель');
    await openChannel(guest, slug);

    await expect(guest.getByRole('heading', { name: 'Закрытая частота' }), 'экран кода не показался').toBeVisible();
    await expect(ships(guest), 'рейд виден до кода доступа').toHaveCount(0);
    await expect(
        guest.getByRole('button', { name: 'Встать на рейд' }),
        'форму постановки в строй открыли до кода'
    ).toHaveCount(0);

    // Неверный код — отказ той же фразой, которую для него завели: «Обратитесь к старшему
    // на рейде».
    await enterAccessCode(guest, 'неверный-код');
    await expect(guest.locator('[class*="snackbar"]'), 'неверный код не отказал').toHaveText(
        'Код доступа неверен. Обратитесь к старшему на рейде.'
    );
    // Экран остаётся на месте — пробуем ещё раз, а не начинаем сначала.
    await expect(guest.getByRole('heading', { name: 'Закрытая частота' }), 'экран кода закрылся сам').toBeVisible();

    // Верный код — и сразу форма постановки в строй, без промежуточного «Встать на рейд».
    await enterAccessCode(guest, code);
    await join(guest, 'Секстант', '512');

    // Встав в строй, видит всё: и весь рейд, а не только себя, и ленту, написанную до входа.
    await expect(ships(guest), 'после верного кода видны не все корабли').toHaveCount(2);
    await expect(
        bubbles(guest).filter({ hasText: 'Есть кто на связи?' }),
        'после верного кода не видно сообщения, написанного до входа'
    ).toBeVisible();

    await owner.context().close();
    await guest.context().close();
});

/**
 * «Закрытая частота, второй заход» (issue #80): код спрашивают заново после высадки, а не
 * после ухода. Экран кода стоит на `needsCode` в App.tsx, а тот смотрит на `verifiedCode` —
 * коду, который вкладка подтвердила один раз за приход на канал. Ушедший сам возвращается
 * тем же кодом, что и подтверждал минуту назад, — переспрашивать его незачем, это и есть
 * задуманное поведение. Высадка — другое дело: снять корабль с рейда решил старший, а не сам
 * ушедший, и продолжать пускать его назад по памяти вкладки, в обход этого решения, нельзя
 * (см. `leftByMe` в App.tsx).
 *
 * Сервер (joinChannel, functions/src/raid.ts) код сверяет заново на каждый настоящий вход,
 * что после ухода, что после высадки, — «мимо приложения» с чужим кодом на закрытый канал
 * не попасть что тогда, что сейчас (см. соседнюю проверку выше). Дыра, которую здесь ловим,
 * была не в проверке, а в том, что вкладка код вовсе не спрашивала, а посылала свой же,
 * оставшийся с прошлого раза, — молча, без экрана «Закрытая частота» на пути.
 */
test('закрытый канал: код не спрашивают после ухода, но спрашивают после высадки (#80)', async ({ browser }) => {
    // Замер — секунд девяносто: три настоящих входа подряд (WRITE_TIMEOUT + SAIL_TIMEOUT
    // каждый), между ними уход и высадка, и лишняя вкладка той же личности на закуску.
    takes(140);

    const slug = `closed-return-${Date.now()}`;
    const code = 'periscope-deep';
    const guestUid = 'closed-return-guest';

    const owner = await newTab(browser);
    await signIn(owner, 'closed-return-owner', 'Хозяин рейда');
    await createChannel(owner, 'Второй заход', slug, code);
    await join(owner, 'Маяк', '404');

    const guest = await newTab(browser);
    await signIn(guest, guestUid, 'Проситель');
    await openChannel(guest, slug);
    await enterAccessCode(guest, code);
    await join(guest, 'Секстант', '512');

    // Ушёл сам — и возвращается без переспроса: код с прошлого раза ещё в счёт, это и есть
    // задуманная память вкладки (см. JSDoc выше).
    await leaveRaid(guest);
    await expect(
        guest.getByRole('heading', { name: 'Закрытая частота' }),
        'вернувшегося самого спросили код заново'
    ).toHaveCount(0, { timeout: WRITE_TIMEOUT + 5_000 });
    await expect(
        guest.getByRole('button', { name: 'Встать на рейд' }),
        'кнопка возврата не показалась без переспроса кода'
    ).toBeVisible();
    await join(guest, 'Секстант', '512');

    // Высадка — то же самое исчезновение с рейда для App (`me` стало null), но старший здесь
    // решал сам, и код спрашивают заново: экран «Закрытая частота» встаёт на пути снова,
    // а не кнопка «Встать на рейд».
    await owner.bringToFront();
    await kickShip(owner, 'Секстант');
    await guest.bringToFront();
    await expect(
        guest.getByRole('heading', { name: 'Закрытая частота' }),
        'высаженного пустили обратно без кода'
    ).toBeVisible({ timeout: WRITE_TIMEOUT + 5_000 });
    // Что осталось у высаженного в кадре, здесь не спрашиваем: подписка его вкладки замерла на
    // отказе, и чужие корабли стоят в ней вечно — отдельная беда, не про код на входе. Свой
    // корабль уходит за кромку как надо, это проверено выше отдельным заходом (#79).
    await expect(
        guest.getByRole('button', { name: 'Встать на рейд' }),
        'форма постановки в строй открылась высаженному до кода'
    ).toHaveCount(0);

    // Свежая вкладка той же самой личности — без всякого местного `verifiedCode`, ей неоткуда
    // взяться: экран кода встречает и её, а не только продолжающую сессию вкладку высаженного.
    const freshGuest = await newTab(browser);
    await signIn(freshGuest, guestUid, 'Проситель');
    await openChannel(freshGuest, slug);
    await expect(
        freshGuest.getByRole('heading', { name: 'Закрытая частота' }),
        'на свежей вкладке высаженного пустили без кода'
    ).toBeVisible();
    await freshGuest.context().close();

    // Верный код — и высаженный снова на рейде, тем же местом, что и раньше.
    await enterAccessCode(guest, code);
    await join(guest, 'Секстант', '512');
    await expect(ships(guest), 'после верного кода высаженный не встал обратно').toHaveCount(2);

    await owner.context().close();
    await guest.context().close();
});

/**
 * Свой корабль уходит из кадра и тогда, когда ушёл сам, и тогда, когда его ссадили (issue #79).
 *
 * Проверка стоит здесь, а не в местном наборе, потому что и ломалось это только здесь. Уход
 * из кадра сцена замечает сравнением: пропал из списка участников — значит уходит (SeaScene.tsx).
 * У местного бэкенда список приходит уходящему как ни в чём не бывало — подписка там решает,
 * что кому показывать, один раз, при заведении, и потерявшего участие не обрезает. Firestore
 * же спрашивает правило заново на каждом снимке: сняли с рейда — запрос к участникам перестал
 * проходить isMember(channelId) и ответил не удалением записи, а отказом всему запросу разом.
 * Сравнивать делалось нечего, и корабль оставался стоять на своём месте — до самого перезахода,
 * когда он наконец трогался, но уже переездом на новую точку строя и совсем некстати.
 *
 * Отсюда и два ожидания на каждый путь: сперва `leaving` — что корабль именно пошёл за кромку,
 * а не пропал из разметки разом, — а следом опустевший кадр, что он до кромки дошёл.
 *
 * Заодно проверяется и то, без чего высадки бы тут не случилось вовсе: старшинство заведший
 * канал получает сразу, не перезагружая вкладку (mergeCatchUp в useChannel.ts). Owner проставляет
 * сервер, в превью, снятом до входа, его нет, — не возьми довыгрузка канал из свежего снимка,
 * кнопки «Высадить» на этом рейде не было бы ни одной.
 */
test('свой корабль уходит из кадра — и когда ушёл сам, и когда его высадили', async ({ browser }) => {
    // Замер — секунд сорок: два настоящих входа (WRITE_TIMEOUT + SAIL_TIMEOUT каждый) и два
    // ухода за кромку следом друг за другом, каждый со своим SAIL_TIMEOUT.
    takes(75);

    const slug = `leave-scene-${Date.now()}`;

    const senior = await newTab(browser);
    await signIn(senior, 'leave-scene-senior', 'Старший');
    await createChannel(senior, 'Кто уходит', slug);
    await join(senior, 'Альбатрос', '101');

    const kicked = await newTab(browser);
    await signIn(kicked, 'leave-scene-kicked', 'Высаженный');
    await openChannel(kicked, slug);
    await join(kicked, 'Вымпел', '202');
    await expect(ships(kicked), 'высаживаемый не увидел весь рейд').toHaveCount(2);

    // Высадка: смотрим не на вкладку старшего, а на вкладку высаженного — там и ломалось.
    // bringToFront не для красоты: Chromium морозит переходы в фоновой вкладке, и уход
    // за кромку в ней не начинается вовсе, сколько ни жди.
    await kicked.bringToFront();
    await kickShip(senior, 'Вымпел');
    await expect(
        kicked.locator('[data-motion="leaving"]'),
        'высаженный корабль не пошёл из кадра у себя же на вкладке'
    ).toHaveCount(1, { timeout: WRITE_TIMEOUT + 5_000 });
    await expect(ships(kicked), 'высаженный корабль так и не ушёл за кромку').toHaveCount(1, {
        timeout: SAIL_TIMEOUT,
    });

    // Уход сам: тот же вопрос к вкладке уходящего, только рейд после него пустеет совсем.
    await senior.bringToFront();
    await leaveRaid(senior);
    await expect(senior.locator('[data-motion="leaving"]'), 'ушедший сам корабль не тронулся с места').toHaveCount(1, {
        timeout: WRITE_TIMEOUT + 5_000,
    });
    await expect(ships(senior), 'ушедший сам корабль так и не ушёл за кромку').toHaveCount(0, {
        timeout: SAIL_TIMEOUT,
    });

    await senior.context().close();
    await kicked.context().close();
});
