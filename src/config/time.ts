/**
 * Скорость времени в приложении: во сколько раз движение отыгрывается быстрее обычного.
 *
 * Обычная скорость — единица, и другой она бывает только под проверками. Время там — главная
 * статья расходов: ход корабля по кадру длится до минуты, и проверка, которой нужен пришедший
 * корабль, честно эту минуту пережидает. Ускорять при этом надо само время, а не проверки:
 * правила остаются те же самые, ход остаётся ходом — просто отыгрывается быстрее, и ждать
 * его нечего.
 *
 * Мерка одна на всё движение сразу: и на ход корабля, который считается в коде, и на переезды
 * раскладки, которые живут в стилях (--time-scale, ставится в index.tsx, делится на неё
 * в motion.less). Разойдись они — и кадр пошёл бы по двум разным временам, а проверка ловила
 * бы то, чего в приложении не бывает.
 *
 * Ускорение — не отключение. Проверки смотрят и на промежуточные кадры: гаснет ли разметка
 * вместе с флотом, поджимает ли повёрнутое окно разговор. Обнулённая длительность их сломала бы —
 * им нужна короткая, а не никакая.
 *
 * Ставится мерка снаружи и до загрузки приложения — скриптом, который браузерный прогон
 * подкладывает каждой странице (см. tests/helpers.ts). Само приложение её не меняет и никуда
 * не сохраняет: это мерка запуска, а не настройка.
 */
declare global {
    interface Window {
        /** Во сколько раз ускорить время. Ставится до загрузки приложения, потом не меняется. */
        timeScale?: number;
    }
}

const readTimeScale = (): number => {
    // Юниты идут вовсе без окна, и ждать там некому.
    const asked = typeof window === 'undefined' ? undefined : window.timeScale;
    // Замедлять нельзя: на длительностях, растянутых до бесконечности, приложение просто встанет.
    return typeof asked === 'number' && Number.isFinite(asked) && asked >= 1 ? asked : 1;
};

export const TIME_SCALE = readTimeScale();

/**
 * Длительность по нынешней скорости времени. Секунды это или миллисекунды — всё равно:
 * делится и то и другое одинаково.
 */
export const paced = (duration: number): number => duration / TIME_SCALE;
