/**
 * Раскладка: числа, которые должны совпадать в стилях и в коде.
 *
 * Приложение состоит из двух вещей — кадра со сценой и разговора, — и раскладок у него две,
 * по форме окна: в вертикальном окне разговор стоит под кадром и меряется высотой, в
 * горизонтальном — сбоку от кадра и меряется шириной. Всё, что ниже, описывает эти две
 * раскладки и шторки поверх них; ничего третьего в приложении нет.
 *
 * Каждое число живёт здесь в единственном экземпляре: `vite.config.ts` подставляет их в каждый
 * `.less`, так что второго мнения о том, где кончается телефон и насколько мелок самый мелкий
 * кадр, в проекте не бывает. Почему раскладка именно такая — в docs/LAYOUT.md.
 */

import type { MagnetPoint } from '@/utils/magnet';

/**
 * Телефонный конец, px. Ширина, на которой и ниже которой всё в приложении стоит в своих
 * телефонных числах.
 *
 * Порогом это число не работает, и в приложении порогов по ширине больше нет вовсе. Оно —
 * нижний конец единственной мерки ширины (`--wide` в index.less): на нём приложение стоит
 * в телефонных числах, на `COLUMN_WIDTH` — в десктопных, а между ними идёт от одних к другим,
 * не перескакивая. Раньше здесь был именно порог, и один пиксель ширины разом переставлял
 * небо, месяц, коридоры рейда и размеры кнопок.
 *
 * 480px — потому что до этой ширины помещается только один столбец: сцена растянута
 * во всю ширину, формы идут от края до края, а полей и кнопок в ряд не бывает.
 */
export const MOBILE_MAX_WIDTH = 480;

/**
 * Десктопный конец шкалы ширины, px. На нём и шире всё в приложении стоит в своих десктопных
 * числах, а между ним и `MOBILE_MAX_WIDTH` идёт от одних к другим, не перескакивая
 * (см. `--wide` в index.less).
 *
 * 760px — ширина колонки, на которой раскладку задумывали: дальше растёт кадр, а не строчки.
 * Порогом это число не работает — как и телефонный конец, оно всего лишь отмечает, где шкала
 * упирается в свой край.
 */
export const COLUMN_WIDTH = 760;

/**
 * Самый мелкий кадр, px. Ниже этого сцена не сжимается: в 300px ещё виден рейд с кораблями
 * и полоса неба над ними, а в меньшем не видно уже ничего.
 *
 * Ниже этой мерки кадр не уменьшают, а накрывают: разговор, поднятый выше, просто идёт
 * поверх сцены, и та остаётся стоять в своём наименьшем росте.
 */
export const SCENE_MIN_HEIGHT = 300;

/**
 * Какую долю окна кадр держит за собой, пока разговор его не накрыл. Вторая мерка того же,
 * что и `SCENE_MIN_HEIGHT`: на высоком окне треть больше трёхсот пикселей, на низком —
 * меньше, и кадру достаётся большая из двух.
 */
export const SCENE_MIN_SHARE = 1 / 3;

/**
 * Размах рейда у переднего края, % ширины кадра с каждой стороны.
 *
 * Сам рейд — вода одних и тех же долей от нуля до ста, и расстановка про кадр не знает вовсе.
 * На экран его точки ложатся трапецией: передний край раздаётся шире кадра на эту мерку,
 * дальний поджимается внутрь на `RAID_SPREAD_FAR`, а между ними размах идёт по той же
 * перспективе, что и всё в сцене (см. `--raid-reach` в SeaScene.module.less).
 *
 * Раздаваться переднему краю нужно на телефоне: кадр там почти квадратный, рейду в нём тесно,
 * и перспектива, которой негде разбежаться, читается плохо. Размах отдаёт рейду ту ширину,
 * которой окно не даёт: коридоры расходятся, корабли встают просторнее, а за кромку уходит
 * вода да оконечность ближнего силуэта — там, где корабли крупные и стоят тесно, это выглядит
 * натурально.
 *
 * Двенадцать процентов — то, что видно на глаз и ещё не мешает. Замер на телефонном окне
 * 390px: передний край выходит 484px — на 94px шире окна, — и оси боковых коридоров отходят
 * от кромки на 60px вместо 86, то есть почти на треть ближе к краю. Больше — и ближние
 * корабли начинают прятаться за кромку целиком, а не оконечностью.
 *
 * На колонке размах сходит на нет вместе с шириной окна (`--wide`): широкому кадру рейд
 * помещается целиком, и выводить его за кромки незачем.
 *
 * Горизонтальной прокрутки от этого не бывает: рейд лежит внутри кадра, а кадр обрезает всё,
 * что за его краями (`overflow: hidden` у `.scene`).
 */
export const RAID_SPREAD_NEAR = 12;

/**
 * То же у дальнего края, % ширины кадра. Отрицательное — край поджат внутрь кадра, и ровно
 * это поджатие делает проекцию трапецией, а не раздутым прямоугольником.
 *
 * Дальний корабль мелкий, места на линии ему с избытком, и виден он должен быть целиком —
 * даже тогда, когда передний край из кадра вышел. Заодно это и про вероятность: чем дальше
 * слот, тем меньше шансов, что кораблю выпадет встать у самой кромки экрана.
 *
 * Четыре процента — то самое «немного»: столько же, на сколько сходятся к дальнему краю оси
 * коридоров (`@berth-spread-far`), и та же мерка, что и поле по краям рейда (`EDGE_MARGIN`).
 */
export const RAID_SPREAD_FAR = -4;

/**
 * Наименьшая область нажатия по кораблю в кадре, px.
 *
 * Своя область у корабля — его же силуэт: в крупный целятся как в кнопку, и отбирать нажатия
 * у соседей ему незачем. Мелкому силуэта мало, и область под ним расширяется до этой мерки
 * вокруг середины корпуса (см. `shipAt` в SeaScene/shipPick).
 *
 * Не хватает кораблю почти всегда высоты, а не ширины. Замер самого мелкого случая, какой
 * в приложении бывает: телефонное окно 390px, дальняя линия, «Пограничный сторожевой катер» —
 * силуэт выходит 46px шириной и вдвое ниже. По ширине мерка ему уже не нужна, по высоте
 * прибавка идёт вниз, под киль, где над водой пусто, — потому она и считается от корпуса,
 * а не от середины коробки: середина у мачтового силуэта стоит выше корпуса, и половина
 * прибавки ушла бы в небо.
 *
 * Сорок четыре — обычная мерка нажимаемого на телефоне, та же, до которой доводится область
 * хвата у ручки шторки (`@grip-reach` в src/grip.less).
 */
export const SHIP_TAP_MIN = 44;

/**
 * Ширина шторки на десктопе, px. Чуть уже колонки: шторка приезжает поверх блока контента,
 * и по её краям должно быть видно, что под ней что-то есть. На телефоне предел ни на что
 * не влияет — там окно и так уже колонки.
 */
export const SHEET_WIDTH = 700;

/**
 * Насколько шторка уже того, во что приезжает, px. Число на обе стороны разом: по 10px
 * с каждой.
 *
 * Предел выше — про десктопную колонку, а шторка приезжает не только в неё: на телефоне
 * её держит окно, в боковой раскладке — панель, и там вычитать не из чего. Эта мерка и есть
 * то самое «видно, что под ней что-то есть», выраженное одинаково для всех трёх случаев.
 *
 * Мерка одна на все шторки приложения, и разговор под кадром — такая же шторка: он тоже
 * приезжает снизу, тоже скруглён сверху и тоже отодвинут от краёв окна на эту полоску.
 *
 * И считается она не от окна, а от того, на чём шторка лежит. Под кадром под шторкой всегда
 * разговор — то есть полоски две: одна разговорная, вторая её собственная. Шторка, вызванная
 * из другой (`cover`), прибавляет третью, и так далее по этажам стопки: по этим полям и видно,
 * что под верхней лежит ещё одна, а под той — ещё. Сбоку разговор шторке не подстилка,
 * а сосед, и полоска у неё там одна (см. `--shade-steps` в `ui/Shade`).
 */
export const SHEET_INSET = 20;

/**
 * Насколько шторка не доезжает до верха окна, px.
 *
 * Ровно на эту полоску смотрит шапка с названием канала и кнопками. Отдавать её шторке нельзя:
 * кнопками из шапки шторка и открывается, и закрывается.
 *
 * Тем же числом отмерен и потолок разговора в вертикальной раскладке: разговор — такая же
 * шторка, и «во весь рост» у него значит «до низа шапки», а не «до верха окна». От него же
 * считаются и доли: 33% — это треть того, что осталось под шапкой, а не треть окна.
 */
export const SHEET_TOP_GAP = 64;

/**
 * Высота ручки, за которую шторку тянут, px: рисочка с полем вокруг неё.
 *
 * Ею же меряется и низ разговора под кадром — то самое малое, во что он сворачивается свайпом.
 * Внизу разговор стоит ручкой и полем ввода под ней: ленты между ними не остаётся вовсе,
 * а написать в канал можно, не разворачивая ничего. Разговор — шторка незакрываемая: утянутый
 * до упора, он не пропадает, а ложится этой полоской вдоль кромки окна.
 *
 * Само число пола здесь не записано: поле ввода бывает разной высоты — с плашкой ответа,
 * с вырезом экрана снизу, — и меряется оно на месте (см. `floor` в App). Отсюда только ручка.
 *
 * Сбоку пола нет: панель у правой кромки сворачивается уходом за неё целиком, и убирает её
 * кнопка в шапке (`hide` в hooks/useLayout).
 */
export const SHEET_HANDLE = 22;

/**
 * Наименьшая лента, которую есть смысл показывать, px.
 *
 * Разговор сверх пола растёт лентой, и первые её пиксели показывать нечем: в щель в двадцать
 * пикселей между ручкой и плашкой ввода попадает не реплика, а её половина — лента домотана
 * книзу, и у верхней кромки всегда стоит середина пузыря. На своей высоте такой срез читается
 * продолжением разговора, а в щели — грязью под ручкой. Пока ленте досталось меньше этого,
 * её нет вовсе: разговор выглядит ровно так же, как свёрнутый, — ручка и плашка ввода.
 *
 * Набрано число из пузыря (22px строки и по 8px полей) и полей самой ленты (12px сверху,
 * 8px снизу): ровно столько нужно, чтобы в ленте поместилась хотя бы одна реплика целиком.
 *
 * Порога этого не миновать никакой точке разговора, кроме пола: ближайшая к полу — треть
 * того, что осталось под шапкой, и она заведомо выше. В покое поэтому лента либо есть,
 * либо разговор свёрнут; щель бывает только под пальцем, пока разговор ведут с пола вверх.
 */
export const FEED_MIN = 58;

/**
 * Какую долю разговор занимает, пока его не двигали руками.
 *
 * Доля, а не пиксели, и не только для умолчания: выбранный размер тоже хранится долей
 * (см. `hooks/useLayout`). На широком мониторе панель в 400px — это узкая щель сбоку,
 * на окне в 1000px — треть экрана; в пикселях одно и то же число значит в разных окнах
 * разное, а треть значит треть.
 *
 * Треть — одна на обе раскладки: и высота под кадром, и ширина сбоку начинаются с неё.
 */
export const CHAT_SHARE = 1 / 3;

/**
 * Где разговор под кадром останавливается, когда его отпустили.
 *
 * Разговор — такая же шторка, как список кораблей, только нижняя: тянут его за коридор вдоль
 * верхней кромки, и отпущенный он приезжает к ближней точке (см. `@/utils/magnet`). Точек
 * четыре, и каждая — отдельный разговор с рейдом: низ — «рейд во весь экран», треть —
 * «поговорить, не теряя рейда из виду», две трети — «рейд краем глаза», весь рост —
 * «сейчас только разговор».
 *
 * Здесь записаны три: самой нижней тут нет, потому что она не доля, а мерка — ручка с полем
 * ввода под кадром и ноль сбоку. Приставляет её `chatMagnets` (см. `floor` в hooks/useLayout).
 *
 * Долями, а не пикселями, по той же причине, что и `CHAT_SHARE`: ход у разговора зависит
 * от окна. И считаны они от той же трети, а не написаны круглыми числами: 33% и 66% разошлись
 * бы с `CHAT_SHARE` на пару пикселей, и нетронутый разговор стоял бы рядом со своей точкой,
 * а не на ней — то есть первый же свайп за кромку и обратно сдвигал бы его на эту пару.
 *
 * Между точками разговор не стоит: положений у него ровно столько, сколько точек, и промежуток
 * между двумя — дорога, а не место (см. `@/utils/magnet`). Правило это общее на все шторки.
 */
export const CHAT_POINTS: MagnetPoint[] = [`${CHAT_SHARE * 100}%`, `${CHAT_SHARE * 2 * 100}%`, '100%'];

/**
 * Насколько кадр заезжает под разговор, px.
 *
 * Кадр кончается не там, где начинается разговор, а чуть ниже (или чуть правее): полоска
 * воды уходит под кромку разговора, и стык не читается щелью между двумя плашками. Зазора
 * при этом не бывает никогда — ни в покое, ни на ходу.
 */
export const CHAT_OVERLAP = 20;

/**
 * Насколько узким разговор соглашается быть сбоку, px. Уже 300 в нём перестаёт помещаться
 * лента: аватарка с пузырём встают в строку, и на текст остаётся меньше половины ширины.
 *
 * Мерка только про боковую раскладку: под кадром разговор стоит во всю ширину окна,
 * и узким там он не бывает.
 */
export const SIDE_MIN_WIDTH = 300;

/**
 * Ширина коридора вдоль кромки разговора, за который его тянут, px. 16px — то, во что
 * уверенно попадают указателем, не целясь, и при этом ещё не полоса.
 *
 * Это толщина коридора поперёк кромки, а не вся область хвата. Под кадром коридор выходит
 * вверх дальше — там ниже кромки лежит ручка, и вдвоём они набирают телефонные 44px
 * (см. `.gripUnder` в App.module.less).
 */
export const CHAT_GRIP = 16;

/**
 * Сколько ширины остаётся кадру рядом с разговором, px. Шире разговор не растягивается: рейд
 * про ширину, и в окне уже 600px он становится вертикальным — корабли уходят вверх, а не вдаль.
 */
export const SCENE_MIN_WIDTH = 600;
