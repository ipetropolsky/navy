/**
 * Раскладка: числа, которые должны совпадать в стилях и в коде.
 *
 * Точка перехода в мобильный вид одна на всё приложение. Отсюда её берёт и JS
 * (`utils/viewport`), и Less: `vite.config.ts` подставляет `@mobile-width` в каждый
 * `.less`-файл из этой же константы, так что второго числа, которое можно забыть поправить,
 * в проекте нет.
 *
 * 480px — потому что до этой ширины помещается только один столбец: сцена растянута
 * во всю ширину, формы идут от края до края, а полей и кнопок в ряд не бывает.
 */
export const MOBILE_MAX_WIDTH = 480;

/** Медиавыражение мобильного вида — оно же стоит в `@media` после подстановки в Less. */
export const MOBILE_MEDIA_QUERY = `(max-width: ${MOBILE_MAX_WIDTH}px)`;
