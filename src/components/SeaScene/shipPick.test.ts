import { describe, expect, test } from 'vitest';

import { Box, ShipTarget, hullSpot, shipAt, tapArea } from '@/components/SeaScene/shipPick';
import { HULL_CENTER } from '@/types/channel';

/**
 * Нажатия по кораблям. Руками эту механику не проверить: на экране видно только то, что
 * открылась не та карточка, а почему — область не дотянулась, или спор о расстоянии решился
 * в другую сторону — не видно вовсе. E2e ловит попадания в живом кадре, а здесь считаются
 * сами области и расстояния, на числах, которые в кадре не показывают.
 */

/** Коробка от левого верхнего угла: так их удобнее задавать, чем четырьмя кромками. */
const box = (left: number, top: number, width: number, height: number): Box => ({
    left,
    top,
    right: left + width,
    bottom: top + height,
});

const ship = (memberId: string, at: Box, hull = HULL_CENTER): ShipTarget => ({ memberId, box: at, hull });

describe('hullSpot', () => {
    test('по умолчанию корпус — середина по ширине и треть от воды', () => {
        // Коробка 100×90 от (200, 300): вода под килем на 390, треть от неё — 360.
        expect(hullSpot(ship('a', box(200, 300, 100, 90)))).toEqual({ x: 250, y: 360 });
    });

    test('поправка справочника сдвигает точку, куда сказано', () => {
        // Мачта задрала коробку вдвое выше корпуса: корпусу отвели нижнюю шестую.
        const spot = hullSpot(ship('a', box(0, 0, 60, 120), { x: 0.5, y: 1 / 6 }));
        expect(spot).toEqual({ x: 30, y: 100 });
    });
});

describe('tapArea', () => {
    test('крупный корабль остаётся при своей коробке', () => {
        const big = box(100, 100, 200, 160);
        expect(tapArea(ship('a', big), 44)).toEqual(big);
    });

    test('мелкому область раздувают до мерки', () => {
        // Катер 10×12 у (100, 200): корпус в (105, 208), и вокруг него просят 44.
        expect(tapArea(ship('a', box(100, 200, 10, 12)), 44)).toEqual({
            left: 83,
            right: 127,
            top: 186,
            bottom: 230,
        });
    });

    test('прибавка идёт только по той стороне, которой не хватает', () => {
        // Мачтовый силуэт: по высоте коробки хватает с запасом, по ширине — нет.
        const area = tapArea(ship('a', box(0, 0, 20, 300)), 44);
        expect([area.left, area.right], 'узкую сторону не растянули').toEqual([-12, 32]);
        expect([area.top, area.bottom], 'высокую сторону тронули зря').toEqual([0, 300]);
    });

    test('прибавка встаёт вокруг корпуса, а не вокруг середины коробки', () => {
        // Коробка 10×60: её середина по высоте на 30, корпус же на 40 — ниже. Область обязана
        // накрыть корпус целиком и потому уходит на пару точек под киль, до 62. От середины
        // коробки её нижняя кромка осталась бы на 60, и половина прибавки ушла бы в небо.
        const area = tapArea(ship('a', box(0, 0, 10, 60)), 44);
        expect(area.bottom).toBe(62);
        expect(area.top, 'верхнюю кромку тронули зря').toBe(0);
    });
});

describe('shipAt', () => {
    test('мимо всех областей — ничей', () => {
        const fleet = [ship('a', box(100, 100, 40, 40))];
        expect(shipAt(fleet, 400, 400, 44), 'пустая вода открыла карточку').toBeNull();
    });

    test('нажатие по кораблю достаётся кораблю', () => {
        const fleet = [ship('a', box(100, 100, 40, 40))];
        expect(shipAt(fleet, 120, 130, 44)).toBe('a');
    });

    test('мелкий берёт нажатие рядом с собой — тем и живёт наименьшая мерка', () => {
        // Катер шириной в 8 точек: без прибавки в него пальцем не попасть.
        const fleet = [ship('boat', box(200, 300, 8, 10))];
        expect(shipAt(fleet, 204, 296, 44), 'мимо мелкого прошли в четырёх точках от него').toBe('boat');
        expect(shipAt(fleet, 204, 296, 8), 'без прибавки нажатие всё же попало').toBeNull();
    });

    test('в споре двоих побеждает тот, до чьего корпуса ближе', () => {
        // Ближний стоит перед дальним и накрывает его своей областью: нажатие по торчащему
        // из-за него дальнему обязано достаться дальнему.
        const fleet = [ship('far', box(300, 200, 30, 40)), ship('near', box(300, 220, 80, 60))];
        expect(shipAt(fleet, 305, 225, 44), 'дальний отдал своё нажатие ближнему').toBe('far');
        expect(shipAt(fleet, 330, 245, 44), 'ближний отдал своё нажатие дальнему').toBe('near');
    });

    test('порядок в списке спора не решает', () => {
        const far = ship('far', box(300, 200, 30, 40));
        const near = ship('near', box(300, 220, 80, 60));
        expect(shipAt([far, near], 305, 225, 44)).toBe(shipAt([near, far], 305, 225, 44));
        expect(shipAt([far, near], 330, 245, 44)).toBe(shipAt([near, far], 330, 245, 44));
    });

    test('пустое море не отдаёт нажатие никому', () => {
        expect(shipAt([], 10, 10, 44)).toBeNull();
    });
});
