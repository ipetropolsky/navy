import { Member, ShipField, ShipNotice, ShipTitle, isSameBerth } from './types/channel';

/**
 * Что канал пишет в ленту о корабле — данными, а не фразой.
 *
 * Отдельным файлом от самого эмулятора: это чистые функции без хранилища и без вкладок,
 * и проверять их надо так же — вызовом, а не через браузер.
 */

/**
 * Как корабль зовут: тип, позывной, бортовой номер. Снимок, а не ссылка на участника —
 * канал пишет о том, что было, и написанное не должно меняться задним числом.
 */
export const shipTitle = (member: Member): ShipTitle => ({
    shipKind: member.shipKind,
    name: member.name,
    hullNumber: member.hullNumber,
});

/**
 * Поля, по которым канал и различает переоснащение. Цвет позывного сюда не входит:
 * он не меняет ни имени, ни облика. Место на рейде — тоже, но по другой причине: перемена
 * места не переоснащение, а манёвр, и о нём канал пишет отдельно (см. `moveNotices`).
 */
const SHIP_FIELDS: ShipField[] = ['shipKind', 'name', 'hullNumber'];

/**
 * Записи о переоснащении: по одной на каждую перемену. Сменил корабль разом позывной, номер
 * и силуэт — получится три записи, и в ленте они встанут тремя сообщениями.
 *
 * Отдельными записями, а не одной с перечислением, потому что каждая из них — полноценное
 * сообщение канала: со своим временем, своим номером и своим ответом. Одна запись на три
 * перемены была бы строчкой, на которую отвечают целиком, хотя речь в ней о разном.
 *
 * Порядок — тот же, что и в `SHIP_FIELDS`: сперва силуэт, потом позывной, потом номер.
 * Порядок не случайный, а от крупного к мелкому: сменившийся силуэт — новость крупнее
 * сменившегося номера, и читаться она должна первой.
 *
 * Текста здесь нет и быть не должно: бэкенд знает, что случилось, а как об этом сказать —
 * дело интерфейса (см. `components/chat/ShipNoticeLine`). Сравнение всё же остаётся тут:
 * оба состояния на руках только у бэкенда, и второй раз выводить одно из другого интерфейсу
 * незачем. Ничего не поменялось — записей нет вовсе.
 */
export const refitNotices = (before: Member, after: Member): ShipNotice[] => {
    const from = shipTitle(before);
    const to = shipTitle(after);
    return SHIP_FIELDS.filter((field) => from[field] !== to[field]).map((changed) => ({
        event: 'refit',
        before: from,
        after: to,
        changed,
    }));
};

/**
 * Запись о перемене места: одна на манёвр, и только если корабль правда пошёл на другое место.
 * Развернуться на месте манёвр тоже, и сцена его отыгрывает, но новость это не канала,
 * а картинки: в ленте от «сменил курс» пользы столько же, сколько от «сменил цвет позывного».
 *
 * Пишется в начале манёвра, а не в конце: канал рассказывает о том, что происходит, а не
 * подводит итоги, и строчка «пошёл» посреди хода честнее строчки «пришёл» через десять секунд
 * после того, как это и так стало видно.
 *
 * Корабль тут один — тот, что тронулся; ни откуда, ни куда в записи нет. Место на рейде
 * называется координатами, а не словами, и переводить их в «с третьего на пятое» некому:
 * человек и так смотрит на сцену, где корабль идёт у него на глазах.
 */
export const moveNotices = (before: Member, after: Member): ShipNotice[] =>
    isSameBerth(before.place, after.place) ? [] : [{ event: 'moved', before: shipTitle(after) }];
