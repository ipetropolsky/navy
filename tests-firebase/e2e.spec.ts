import { expect } from '@playwright/test';

import { bubbles, createChannel, join, newTab, openChannel, send, signIn, takes, test } from '@tests-firebase/helpers';

/**
 * Единственная сквозная проверка этого набора — доказательство, что стенд вообще работает,
 * а не пересказ docs/FIREBASE.md («Проверки») целиком. От пустой базы: вход через эмулятор,
 * свой канал, два разных аккаунта на рейде — и реплика одного доходит до другого через
 * настоящий Firestore, а не через общую вкладку. Остального из списка (повтор без двойников,
 * «нет сети» и «нет канала», замер задержки, вид гостя) здесь нарочно нет — это заход следующий.
 *
 * Не пустая формальность: первый же её прогон нашёл поломку, которую местный набор поймать
 * не мог в принципе, — вошедший не узнавал свой корабль и оставался с открытой формой
 * (см. `join` в hooks/useChannel.ts).
 */
test('два аккаунта на разных вкладках видят реплики друг друга через сервер', async ({ browser }) => {
    // Не замер, в отличие от остального набора: в норме проверка идёт секунд десять-тринадцать.
    // Здесь срок собран из собственных ожиданий — два входа по WRITE_TIMEOUT + SAIL_TIMEOUT
    // и три ожидания реплики по десять секунд, — и он нарочно больше их суммы. Поставь общий
    // срок по замеру, и первое же затянувшееся ожидание упёрлось бы не в себя, а в общий срок:
    // в отчёте вместо «свой корабль так и не встал на рейд» стояло бы «Test timeout», то есть
    // ровно то, ради чего сроки тут расставлены поимённо, и пропало бы.
    takes(75);

    // Свой адрес на запуск: emulators:exec поднимает базу пустой, но повторный запуск проверки
    // в тот же процесс (retry) не должен упереться в уже занятый слаг.
    const slug = `e2e-${Date.now()}`;

    const pageA = await newTab(browser);
    await signIn(pageA, 'e2e-uid-a', 'Экипаж А');
    await createChannel(pageA, 'Сквозная проверка', slug);
    await join(pageA, 'Гроза', '101');

    const pageB = await newTab(browser);
    await signIn(pageB, 'e2e-uid-b', 'Экипаж Б');
    await openChannel(pageB, slug);
    await join(pageB, 'Отзвук', '202');

    // Вход второго корабля дошёл до первой вкладки той же строчкой, что видит на экране
    // и сам вошедший, — то есть через канал, а не только у себя.
    await expect(pageA.getByText('Отзвук').first(), 'вторая вкладка не появилась в ленте первой').toBeVisible({
        timeout: 10_000,
    });

    await send(pageA, 'Слышно на Отзвуке?');
    await expect(bubbles(pageB).last(), 'реплика от Грозы не дошла до второй вкладки').toContainText(
        'Слышно на Отзвуке?',
        { timeout: 10_000 }
    );

    await send(pageB, 'Слышно, приём.');
    await expect(bubbles(pageA).last(), 'ответ от Отзвука не дошёл до первой вкладки').toContainText('Слышно, приём.', {
        timeout: 10_000,
    });

    await pageA.context().close();
    await pageB.context().close();
});
