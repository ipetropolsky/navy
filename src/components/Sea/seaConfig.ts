/**
 * Перспектива. Глубина считается как 1 / (t + PERSPECTIVE_NEAR), где t — доля
 * высоты моря от горизонта. Это обычная проекция плоскости: у горизонта волны
 * сжимаются почти в линию, у нижнего края растягиваются.
 */
export const PERSPECTIVE_NEAR = 0.06;

/**
 * Степень, с которой перспектива сжимает картинку по горизонтали.
 * 1 — честная проекция, но тогда у горизонта поперечная зыбь дробится на
 * десяток мелких извивов и вода отдаёт кружевом. Значение меньше единицы
 * оставляет изгибы примерно одного размера на любом удалении.
 */
