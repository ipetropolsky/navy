import { describe, expect, it } from 'vitest';

import { unreadBoundary } from '@/hooks/useUnread';

/**
 * Черта отсчёта непрочитанного — чистая функция внутри useUnread, и здесь проверяется
 * только она: без React, без бэкенда, без таймеров. Сам хук — это уже проводка (эффекты,
 * throttle записи, запрос счёта) и её место — браузерный прогон (tests/channel.spec.ts),
 * как и у остальных эффектных хуков этого проекта (см. hooks/useLayout.test.ts).
 */
describe('unreadBoundary', () => {
    it('ни местной памяти, ни отметки сервера — считать не от чего', () => {
        expect(unreadBoundary(null, null)).toBeNull();
    });

    it('есть только местная память (только что убрали панель, сервер ещё не подтвердил)', () => {
        expect(unreadBoundary(1000, null)).toBe(1000);
    });

    it('есть только отметка сервера (холодный старт: свежий канал или новая вкладка)', () => {
        expect(unreadBoundary(null, 1000)).toBe(1000);
    });

    it('местная память свежее отметки сервера — черта по ней', () => {
        // Сервер ещё не увидел throttled-запись этой же вкладки — её собственное «уже видено»
        // всё равно точнее.
        expect(unreadBoundary(2000, 1000)).toBe(2000);
    });

    it('отметка сервера свежее местной памяти — черта по ней', () => {
        // Другое устройство прочитало дальше, чем помнит эта вкладка, — доверяем более
        // свежему источнику, а не собственному, отставшему.
        expect(unreadBoundary(1000, 2000)).toBe(2000);
    });

    it('совпали — та же черта', () => {
        expect(unreadBoundary(1500, 1500)).toBe(1500);
    });
});
