/**
 * Приём сообщения: с какой скоростью оно печатается у получателя и в каких местах лампа
 * отправителя переставляет передачу.
 *
 * Индикация здесь не живая, а восстановленная. Пока человек набирает, по проводу не идёт
 * ничего: сообщение приходит целиком, и уже получатель разыгрывает у себя то, что при живой
 * передаче видел бы вживую, — буквы появляются одна за другой, а корабль отправителя всё это
 * время мигает лампой. Стоит это ровно ноль записей на сервере (см. `backend/types`).
 *
 * Считается тут только арифметика: сами таймеры — в `useReception`. Разведено это затем,
 * что числа проверяются юнитом, а хук без окна не заводится.
 */

/** На сколько частей режется текст под лампу. */
const PARTS = 10;

/**
 * Короче этой части не бывает. Лампа передаёт знак около секунды, и с границы у неё должно
 * оставаться хотя бы несколько знаков — иначе она замолкала бы между границами, и мигание
 * рассыпалось бы на отдельные вспышки вместо непрерывной передачи.
 */
const MIN_PART = 5;

/**
 * Длиннее — тоже не бывает. Последнюю часть лампа договаривает уже после того, как текст
 * допечатался, и часть в полсотни знаков означала бы минуту мигания в тишине. Десять частей —
 * это про обычную реплику в строку-две; у длинной их выходит больше, а размер стоит на месте.
 */
const MAX_PART = 10;

/** Кусок текста, с которого лампа начинает передавать заново. */
export interface ReceptionPart {
    /** С какого символа часть начинается: на нём печать и переставляет передачу. */
    at: number;
    /** Что лампа передаёт с этого места. */
    text: string;
}

/**
 * Разрезать текст на части под лампу.
 *
 * Мигание длиннее печати — знак Морзе идёт секунду, а печатается за сотую её долю, — поэтому
 * лампа за буквами не поспевает и идти за ними не пытается. Вместо этого печать переставляет
 * её на своё место: дошла до границы части — лампа начинает передавать с той же границы.
 *
 * Никто не сверяет, что мигание передало текст целиком: между границами лампа успевает знак-два
 * от начала части, остальное её уводят. Но начало и конец уходят честно — первую часть никто
 * не перебивает, потому что печать только началась, а последнюю потому, что переставлять уже
 * не с чего. Их и пытаются прочитать, если пытаются вообще.
 *
 * Хвост короче `MIN_PART` своей границы не заводит, а достаётся предыдущей части: иначе
 * последним лампа передавала бы одну букву — то есть как раз то, что читают, и передала бы
 * огрызком.
 */
export const receptionParts = (text: string): ReceptionPart[] => {
    const size = Math.min(MAX_PART, Math.max(MIN_PART, Math.ceil(text.length / PARTS)));
    const bounds: number[] = [];
    for (let at = 0; at < text.length; at += size) {
        bounds.push(at);
    }
    if (bounds.length > 1 && text.length - bounds[bounds.length - 1] < MIN_PART) {
        bounds.pop();
    }
    return bounds.map((at, index) => ({ at, text: text.slice(at, bounds[index + 1] ?? text.length) }));
};

/**
 * Сколько держать набранный знак перед следующим, мс.
 *
 * Печать быстрая и чуть неровная: ровный отсчёт читается бегущей строкой, а не человеком
 * за клавиатурой. Неровность берётся случайной, и предсказывать её незачем — это отделка,
 * а не механика; проверяются у неё пределы, а не конкретное число.
 *
 * После пробела пауза длиннее: слово от слова человек отделяет заметнее, чем букву от буквы,
 * и без этой паузы фраза печатается одним слитным потоком.
 */
const TYPE_MS = 34;
const TYPE_JITTER_MS = 26;
const AFTER_SPACE_MS = 90;

export const charDelay = (char: string): number =>
    Math.round(TYPE_MS + Math.random() * TYPE_JITTER_MS + (char === ' ' ? AFTER_SPACE_MS : 0));
