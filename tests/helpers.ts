import { BrowserContext, Locator, Page, expect, test as base } from '@playwright/test';

// Приложение объявляет window.timeScale — импорт нужен ради этого объявления.
import '@/config/time';

/**
 * Общее для всех проверок: как открыть канал, как встать в строй, как заглянуть в хранилище.
 *
 * Хранилище у каждой проверки своё — Playwright даёт каждой свой контекст, — поэтому демо-канал
 * всегда свежий: три корабля и семь реплик из `src/backend/seed.ts`.
 */

/**
 * Во сколько раз время в проверках идёт быстрее обычного.
 *
 * Ход корабля по кадру длится до минуты, и половина набора этот ход пережидала: четыре самые
 * долгие проверки съедали треть всего прогона. Ускоряется при этом само приложение, а не
 * проверки: правила остаются те же, движение остаётся движением — просто отыгрывается вдесятеро
 * быстрее (см. src/config/time.ts).
 *
 * Десятая доля — не потолок, а предел разумного. Выше начинает мешать не приложение,
 * а сам браузер: переезд раскладки в 0.42 с при таком ускорении укладывается в три кадра,
 * и проверки, которые смотрят на движение посередине, ловить станет нечего.
 */
export const TIME_SCALE = 10;

/**
 * Ускорить время в контексте. Мерка ставится скриптом до загрузки страницы: приложение читает
 * её один раз при запуске, и подложить её позже — значит не подложить вовсе.
 *
 * Нужна руками только тем проверкам, которые заводят себе контекст сами; всем остальным
 * его выдаёт `test` ниже, уже ускоренным.
 */
export const hasten = async (context: BrowserContext): Promise<void> => {
    await context.addInitScript((scale) => {
        window.timeScale = scale;
    }, TIME_SCALE);
};

/**
 * Вернуть вкладке обычное время. Нужно тем немногим проверкам, которые смотрят не на итог
 * движения, а на его промежуточные кадры: переезд в 0.42 с, ускоренный вдесятеро, укладывается
 * в три кадра экрана — «поехало или прыгнуло» на таком не различить.
 *
 * Ставится тем же способом и поверх общего ускорения: скрипты страницы выполняются после
 * скриптов контекста, и последнее слово остаётся за этим. Звать до перехода на страницу —
 * приложение читает мерку один раз, при запуске.
 */
export const unhasten = async (page: Page): Promise<void> => {
    await page.addInitScript(() => {
        window.timeScale = 1;
    });
};

/**
 * Сколько ждать конца манёвра, мс. Мерка не запасная, а расчётная: самый длинный ход в кадре —
 * уход с ближней линии через весь рейд, — идёт на наименьшем ходу по кадру (`MIN_SAIL_PACE`)
 * около 53 с, а под проверками во столько же раз меньше, во сколько ускорено время. Отсюда
 * и запас: меньше — и проверки начнут падать от того, что корабль ещё в пути, а не от того,
 * что он идёт не туда.
 *
 * Слагаемым, а не множителем: ускоряется ход корабля, а не открытие канала, загрузка картинок
 * и постановка в строй, которые в это же ожидание попадают. Сбавят ход ещё — первое число
 * сбавляют вместе с ним.
 *
 * Это единственное ожидание набора, которому общих трёх секунд мало по делу, и выдаётся оно
 * на месте — там же, где написано, чего ждём. Проверка с таким ожиданием просит и свой срок
 * (`takes` ниже): в пять секунд ход корабля не укладывается.
 */
export const SAIL_TIMEOUT = 60_000 / TIME_SCALE + 10_000;

/**
 * Запас поверх замера: во столько раз проверке дают больше, чем она идёт на самом деле.
 * Запас этот — на медленную машину и на соседей по прогону, а не на «мало ли что»: щедрый срок
 * ничего не чинит, он только оттягивает падение — а падение и есть то, ради чего проверку писали.
 */
const TIME_MARGIN = 1.5;

/**
 * Сколько эта проверка идёт, секунд. Ставится первой строкой в теле — до всего остального,
 * чтобы отсчёт начался сразу.
 *
 * Число тут — замер, а не срок: прогнать проверку, посмотреть её время в отчёте и округлить
 * вверх до секунды. Запас накидывается сам (`TIME_MARGIN`), и в этом весь смысл — правило
 * живёт одним местом на весь набор, а не полусотней чисел, посчитанных каждое по-своему.
 *
 * Общий срок — пять секунд (см. playwright.config.ts), и большинству проверок его хватает
 * с запасом; замер объявляют те, кому и правда есть чего ждать: ход корабля через весь кадр,
 * вторая вкладка, перезаход на другое место.
 */
export const takes = (seconds: number): void => base.setTimeout(Math.ceil(seconds * TIME_MARGIN) * 1000);

/**
 * Тот же `test`, что и у Playwright, только время в нём идёт быстрее. Берут его отсюда все
 * проверки набора: ускорение — свойство прогона, а не отдельной проверки, и помнить о нём
 * в каждом файле никто не должен.
 */
// Второй параметр фикстуры Playwright зовёт `use`, но здесь он `run`: линтер React считает
// всякое `use(...)` вызовом хука и ругается на него посреди обычной функции.
export const test = base.extend({
    context: async ({ context }, run) => {
        await hasten(context);
        await run(context);
    },
});

export const DEMO = 'demo';

/** Корабли демо-канала: их id заданы руками в seed.ts, на них можно ссылаться. */
export const ALBATROS = 'm-albatros';
export const VYMPEL = 'm-vympel';
export const REZVY = 'm-rezvy';

/**
 * Сколько идёт проявление сцены, мс: те же 600 мс из стилей, поделённые на скорость времени,
 * плюс запас на кадр-другой. Считается из длительности, а не берётся круглым числом, — сбавят
 * проявление в стилях, сбавится и тут.
 */
const FADE_MS = 600 / TIME_SCALE + 100;

/**
 * Дождаться, пока сцена проступит и станет пригодной для нажатий.
 *
 * Признаков два, и приходят они порознь. `data-scene-painted` — задники: картинки грузятся все
 * разом и показываются только вместе, пока последняя не пришла, в кадре темно.
 * `data-scene-ready` — сам канал: флот пришёл с «сервера», встал на места, разметка свободных
 * мест посчитана. До этого сцена уже в разметке, но вода в ней пустая, и целиться проверке
 * не во что — ни в корабль, ни в точку места.
 *
 * Срок у ожидания свой, а не общий: и картинки, и «сервер» — местные, счёт идёт на десятые доли
 * секунды, трёх хватает с запасом даже на холодную вкладку. Больше ставить бессмысленно:
 * у самой проверки сроку пять секунд, и ожидание длиннее до конца всё равно не доживёт.
 *
 * А вот конец проявления приходится пережидать временем: признака «проступило» у перехода нет.
 * Спросить о нём саму страницу (`getAnimations`) не выходит — к этому мигу переход может ещё
 * не начаться, и тогда ждать нечего; по прозрачности слоёв тоже не понять — облака и на
 * проступившей сцене стоят полупрозрачными, такими они и нарисованы.
 *
 * Экспортирован ради проверок, которым нужна настоящая перезагрузка вкладки (`page.reload`,
 * а не переход по адресу) — например, что набранное, но не отправленное, переживает её
 * (issue #69, ящик неотправленного в sessionStorage). `openChannel`/`openNewChannel` внизу
 * пользуются им же, тем же самым признаком готовности, а не своим.
 */
export const sceneReady = async (page: Page): Promise<void> => {
    await page.locator('[data-scene-painted][data-scene-ready]').first().waitFor({ timeout: 3_000 });
    await page.waitForTimeout(FADE_MS);
};

/**
 * Открыть канал. `memberId` в адресе перебивает сохранённую личность вкладки — так вторая
 * вкладка говорит за другой корабль, не трогая первую.
 *
 * Ждём разметку, а не тишину в сети. `networkidle` — это по устройству полсекунды молчания
 * поверх всего остального, и платит их каждая проверка набора: полутора сотнями выходит больше
 * минуты на пустом месте. Дожидаться же тут нечего — следом стоит `sceneReady`, и он ждёт
 * не сеть вообще, а именно те картинки, без которых в кадре темно.
 *
 * Раскладку тут никто не подкладывает: приложение открывается с разговором в треть окна —
 * сбоку в лежачем, под кадром в стоячем (см. `defaultWish` в hooks/useLayout), — и это ровно
 * то, что проверкам и нужно. Прежде сюда писали в хранилище сжатый кадр: раскладок было
 * четыре, умолчание уводило кадр во весь экран, и каждой проверке пришлось бы начинаться
 * с пары нажатий по шапке.
 */
export const openChannel = async (page: Page, slug = DEMO, memberId?: string): Promise<void> => {
    const address = memberId ? `/?channel=${slug}&memberId=${memberId}` : `/?channel=${slug}`;
    await page.goto(address, { waitUntil: 'domcontentloaded' });
    await sceneReady(page);
};

/**
 * Завести свой канал и остаться в нём. Нужен там, где важен ровно один корабль в кадре
 * и он же — свой: в демо-канале на рейде уже стоит эскадра.
 */
export const openNewChannel = async (page: Page, slug: string): Promise<void> => {
    await page.goto('/', { waitUntil: 'domcontentloaded' });
    await page.getByPlaceholder('Эскадра «Полночь»').fill(slug);
    await page.locator('input[placeholder="eskadra-polnoch"]').fill(slug);
    await page.locator('button[type=submit]').click();
    await sceneReady(page);
};

/**
 * Отметка «как было до отправки»: сколько записей лежит в лентах всех каналов, а заодно —
 * пометка на плашке, которая висит сейчас. Нужна, чтобы дождаться исхода по признаку,
 * а не по времени, — см. `awaitWrite` ниже.
 *
 * Плашку метим, а не считаем: она на экране всегда одна, следующая вытесняет предыдущую
 * (см. Snackbar), — счёт от этого не меняется. Зато меняется сам узел: у нового сообщения
 * свой `key`, и React кладёт в разметку другой элемент, без нашей пометки.
 */
const before = (page: Page): Promise<number> =>
    page.evaluate(() => {
        document.querySelector('[role="status"]')?.setAttribute('data-seen', '');
        // eslint-disable-next-line no-restricted-syntax -- взгляд снаружи, а не код приложения
        const raw = localStorage.getItem('kilvater.state');
        const state = raw ? (JSON.parse(raw) as StoredState) : undefined;
        return Object.values(state?.channels ?? {}).reduce((count, channel) => count + channel.messages.length, 0);
    });

/**
 * Дождаться, пока «сервер» запишет отправленное.
 *
 * Запись идёт не в тот же тик, что нажатие: сперва общая очередь на запись, потом сама запись
 * (см. exclusive в localBackend). «Сервер» при этом живёт в самой вкладке — уйти с неё на другой
 * адрес раньше, чем очередь дошла до записи, значит унести отправленное с собой. Человек столько
 * не успевает, а проверка, у которой следом стоит переход, успевает всегда.
 *
 * Признак — прибавка в ленте: и вход, и переоснащение, и уход пишут о себе строчку канала,
 * и она ложится в хранилище той же записью, что и сама перемена. Ждать её честнее, чем ждать
 * время: прежде тут стояла глухая пауза в 300 мс, и платила её каждая постановка в строй,
 * хотя сама запись укладывается в сорок.
 *
 * Ждём в самой странице (`waitForFunction` опрашивает по кадрам), а не заходами снаружи:
 * каждый заход стоит миллисекунд, и на частом опросе они складываются в ту же паузу.
 *
 * Отказ считается тем же концом ожидания, что и запись: занятый позывной или чужой номер
 * «сервер» отбивает, в ленте от этого не прибавляется ничего, а на экране всплывает плашка
 * (`role=status`). Проверкам на отказы нужен именно этот исход — ждать от них записи значит
 * ждать того, чего не будет. Плашка считается новой по пометке, которую перед отправкой
 * поставили на прежнюю (см. `before`): висящая с прошлого отказа за ответ не сойдёт.
 *
 * Обе развилки смотрим одним ожиданием, а не гонкой двух: гонка оставляет позади проигравшее
 * ожидание, и падает оно потом, посреди чужого шага.
 */
const awaitWrite = async (page: Page, was: number): Promise<void> => {
    await page.waitForFunction(
        (mark) => {
            if (document.querySelector('[role="status"]:not([data-seen])')) {
                return true;
            }
            // eslint-disable-next-line no-restricted-syntax -- взгляд снаружи, а не код приложения
            const raw = localStorage.getItem('kilvater.state');
            const state = raw ? (JSON.parse(raw) as StoredState) : undefined;
            const now = Object.values(state?.channels ?? {}).reduce(
                (count, channel) => count + channel.messages.length,
                0
            );
            return now > mark;
        },
        was,
        { timeout: 3_000 }
    );
};

/**
 * Открыть форму постановки в строй. Канал по ссылке встречает гостя закрытой формой — пустой
 * плашкой с одной кнопкой посреди, — и до нажатия по ней ни полей, ни свободных мест на рейде
 * на экране нет. Свой, только что заведённый канал сюда не приходит: там форма открыта сразу.
 */
export const openJoinForm = async (page: Page): Promise<void> => {
    await page.getByRole('button', { name: 'Встать на рейд' }).click();
    await expect(page.getByPlaceholder('Гром'), 'форма постановки в строй не открылась').toBeVisible();
};

/**
 * Заполнить форму постановки в строй и отправить её. Закрытую сперва открываем: проверке,
 * которой нужен сам вход, дорога к форме безразлична, а гостя встречает именно закрытая.
 *
 * Кнопку берём из самой формы, а не со страницы: при переоснащении форма выезжает поверх
 * разговора, и поле ввода со своей кнопкой отправки никуда не девается — «отправить» на
 * странице в этот момент двое.
 */
export const join = async (page: Page, name: string, hullNumber: string, shipKind?: string): Promise<void> => {
    if (await page.getByRole('button', { name: 'Встать на рейд' }).isVisible()) {
        await openJoinForm(page);
    }
    const mark = await before(page);
    const form = page.locator('form').filter({ has: page.getByPlaceholder('Гром') });
    await page.getByPlaceholder('Гром').fill(name);
    await page.locator('input[inputmode="numeric"]').fill(hullNumber);
    if (shipKind) {
        await page.getByText(shipKind, { exact: true }).click();
    }
    await form.locator('button[type=submit]').click();
    await awaitWrite(page, mark);
};

/**
 * Открыть список кораблей — нажатием на название канала в шапке: значок списка стоит в конце
 * названия, и нажимаются они вместе. Тем же нажатием список и закрывается: кнопка эта
 * переключатель.
 *
 * Ищется кнопка по подсказке, а не по подписи: подпись у неё — само название канала, разное
 * от канала к каналу, а та же подпись «Корабли на связи» стоит и на самом списке.
 */
export const shipsButton = (page: Page) => page.locator('button[title="Корабли на связи"]');

/**
 * Сколько ждать конца выезда, мс: те же `@slide-seconds` из стилей, поделённые на скорость
 * времени, плюс запас на кадр-другой. Ждать выезда всё равно приходится временем — признака
 * «доехало» у перехода нет, — но пусть это будет его длительность, а не круглое число.
 */
const SLIDE_MS = 280 / TIME_SCALE + 60;

/**
 * Открыть список кораблей — именно открыть, а не переключить. Кнопка-то переключатель, и вызов
 * подряд закрывал бы уже открытое: проверка, которая сперва посмотрела список, а потом позвала
 * помощника снова, оставалась без него и падала на первом же нажатии внутри. Спрашиваем поэтому
 * у самой кнопки, в каком она положении (`aria-expanded`), и жмём только когда есть что открывать.
 */
export const openSheet = async (page: Page): Promise<void> => {
    if ((await shipsButton(page).getAttribute('aria-expanded')) === 'true') {
        return;
    }
    await shipsButton(page).click();
    await page.waitForTimeout(SLIDE_MS);
};

/** Сам слой со списком кораблей: он стоит в коробке разговора и накрывает собой ленту. */
const shipsList = (page: Page) => page.locator('section[aria-label="Корабли на связи"]');

/**
 * Убрать список кораблей — и дождаться, пока он и правда уедет.
 *
 * Нужен он тем проверкам, которые после списка берутся за ленту: список стоит слоем поверх неё
 * и нажатия себе забирает. Сам собой он не уходит и после закрытой формы своего корабля —
 * форма ложилась поверх него, и, уйдя, возвращает человека туда, откуда он её позвал.
 *
 * Ждать приходится дважды. Сперва — пока список окажется наверху: пока поверх него стоит форма,
 * то же нажатие вернуло бы к списку, а не убрало его, и об этом кнопка говорит своим положением.
 * Форма же уходит не в тот же миг, когда её отправили: сперва запись в «сервер», потом рендер, —
 * и помощник, спросивший положение разом после `join`, застаёт ещё форму. Потом — пока слой
 * снимется с экрана: до конца движения он всё ещё ловит нажатия.
 */
export const closeSheet = async (page: Page): Promise<void> => {
    if ((await shipsList(page).count()) === 0) {
        return;
    }
    await expect(shipsButton(page)).toHaveAttribute('aria-expanded', 'true');
    await shipsButton(page).click();
    await expect(shipsList(page)).toHaveCount(0);
};

/**
 * Кнопка выхода внизу списка кораблей.
 *
 * Ищется по первому слову: второе — «с рейда» — стоит только там, где список широк, а на узком
 * от подписи остаётся одно «Уйти» (см. `.wide` в MembersList.module.less). Ширину списку задаёт
 * разговор, и в боковой раскладке он и в треть окна бывает — рассчитывать на полную подпись
 * нельзя нигде.
 */
export const leaveButton = (page: Page) => page.getByRole('button', { name: /^Уйти/ });

/**
 * Уйти с рейда: кнопка внизу списка кораблей, а следом — новый курс в шторке прощания.
 *
 * Курс обязателен: молча с рейда не уходят, и без набранного курса подтверждение недоступно.
 * Дорог к выходу две — эта и кнопка в шапке, пока открыта форма своего корабля, — но шторка
 * прощания у них одна, и проверкам, которым нужен сам уход, а не путь к нему, хватает короткой.
 *
 * `successorName` называет, кого оставить старшим, — тычком по его строчке в шторке. Поле это
 * не обязательное (см. `LeaveRaid`), и большинству проверок оно не нужно вовсе: не назвали —
 * старшинство решает бэкенд сам, по прежнему правилу.
 */
export const leaveRaid = async (page: Page, course = 'В Кронштадт', successorName?: string): Promise<void> => {
    await openSheet(page);
    const mark = await before(page);
    await leaveButton(page).click();
    if (successorName) {
        await page.getByLabel(`Оставить старшим «${successorName}»`).click();
    }
    await page.getByLabel('Задайте новый курс').fill(course);
    await page.getByRole('button', { name: 'Курс верный' }).click();
    await awaitWrite(page, mark);
};

