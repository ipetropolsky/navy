/**
 * Ход корабля по сцене: сколько ему идти, куда и как долго.
 *
 * Расстояния считаются в длинах корпуса, а не в пикселях и не в долях экрана: CSS-свойство
 * translate в процентах отсчитывается от собственной ширины элемента, то есть «120%» — это
 * ровно 1.2 длины корабля, и переводить ничего не нужно.
 *
 * А вот длительность считается через метры и узлы. Иначе никак: «длина корпуса в секунду»
 * у катера и у тральщика означает совершенно разную скорость, и корабли ходили бы по одному
 * морю в разных единицах. Сколько метров в кадре, знает мерка сцены; с какой скоростью идут
 * на рейде — константа ниже.
 */

/** Узел — морская миля в час. */
const KNOT_MPS = 1852 / 3600;

/*
 * Линейка сцены — SCENE_SCALE_LENGTH из справочника кораблей: сколько метров в единице масштаба.
 * Мерка нужна общая для всех: море одно, и катер не может идти по нему в других метрах,
 * чем тральщик. На ближнем плане получается кадр шириной около 140 м, у горизонта —
 * около 300 м: это и есть перспектива, выраженная в метрах.
 */

/**
 * Ход на рейде, узлов: у самого длинного корабля справочника и у самого короткого. Полный ход
 * тут ни при чём — маневрируют не им. Зато размер важен: катеру и разогнаться, и остановиться
 * проще, чем тяжёлому кораблю, и волны он разводит меньше, поэтому позволить себе может больше.
 *
 * Числа — стилизация, и это стоит знать. Настоящий манёвр на рейде идёт три-четыре узла,
 * но кадр здесь шириной около ста метров на переднем плане и около двухсот пятидесяти
 * у горизонта: на четырёх узлах корабль пересекал бы его две-четыре минуты, и смотреть на это
 * никто не станет. Взято чуть больше настоящего — так манёвр укладывается в те минуты,
 * что на него смотрят, и при этом остаётся неспешным.
 *
 * Это средняя по манёвру. В самый быстрый момент корабль идёт вдвое быстрее: он разгоняется
 * и тормозит, а кривая в стилях распределяет скорость внутри прогона (замер по самим кривым).
 *
 * У короткого было 6.7 — вместе с наименьшим ходом по кадру (см. ниже) он сбавлен на пятую
 * часть. Порознь эти два предела трогать нельзя: сбавишь один — корабль упрётся в другой
 * и сбавит не на столько, на сколько просили. У длинного 4 узла и остаются: это и так
 * настоящий рейдовый ход, и кадра он не достигает ни на одной линии.
 */
const ROADSTEAD_KNOTS_LONGEST = 4;
const ROADSTEAD_KNOTS_SHORTEST = 5.4;

/**
 * Насколько корабль велик среди прочих: 0 — самый короткий справочника, 1 — самый длинный.
 * По этой доле разложено всё, что зависит от размера: и ход на рейде, и дифферент, и кивок.
 */
const sizeShare = (kind: ShipKind): number =>
    (SHIP_SPECS[kind].length - SHORTEST_SHIP_LENGTH) / (SCENE_SCALE_LENGTH - SHORTEST_SHIP_LENGTH);

/** Ход на рейде у этого корабля: между двумя пределами по его длине. */
const roadsteadKnots = (kind: ShipKind): number =>
    ROADSTEAD_KNOTS_SHORTEST + (ROADSTEAD_KNOTS_LONGEST - ROADSTEAD_KNOTS_SHORTEST) * sizeShare(kind);

/** Задним ходом корабль идёт медленнее переднего: винт и обводы работают не в свою сторону. */
const ASTERN_SPEED_RATIO = 0.7;

/**
 * Разгон и торможение, м/с². Одно число на все манёвры и на все корабли, и в этом весь смысл:
 * рывок глаз ловит не по скорости, а по тому, как быстро она набирается, и от длины хода
 * зависеть это не должно.
 *
 * Само по себе ускорение ничего не двигает — форму движения задаёт кривая в стилях, — оно
 * только ограничивает скорость короткого хода, см. ниже.
 */
const MANOEUVRE_ACCEL = 1;

/**
 * Средняя скорость прогона, м/с. Пока путь длинный, она упирается в ход на рейде: корабль
 * успевает разогнаться, идёт и тормозит. На коротком не успевает — он выходит на пик к середине
 * пути и оттуда сразу гасит ход, и настоящая скорость получается ниже заданной.
 *
 * Отсюда и формула. У кривых захода и ухода пик вдвое выше средней — ровно как у треугольного
 * профиля, где половину пути разгоняются, а половину тормозят; в таком профиле путь и ускорение
 * дают среднюю sqrt(a * s) / 2. Порог, после которого одно сменяется другим, считать отдельно
 * не нужно: до него верх берёт разгон, после — ход на рейде.
 *
 * Без этого короткий манёвр шёл бы с той же средней скоростью, что и заход через весь кадр,
 * только вчетверо резче: путь короче, скорость та же, а времени на разгон почти нет. Со стороны
 * это читается как дёрганая парковка, а не как манёвр.
 */
const sailSpeed = (metres: number, kind: ShipKind, astern: boolean): number => {
    const cruise = roadsteadKnots(kind) * KNOT_MPS;
    return Math.min(cruise, Math.sqrt(MANOEUVRE_ACCEL * metres) / 2) * (astern ? ASTERN_SPEED_RATIO : 1);
};

/**
 * Наименьший ход по кадру, % ширины сцены в секунду, — и он же сейчас главный ограничитель.
 * Кадр на переднем плане шириной около ста метров, у горизонта — около двухсот пятидесяти,
 * и на четырёх узлах корабль проходил бы его несколько минут. Это честно, но смотреть
 * на такое никто не станет: вошедший не должен ждать своего корабля дольше, чем длится
 * сама новость о нём.
 *
 * Так что настоящая скорость в кадре сейчас определяется этим числом, а не узлами: почти
 * каждый манёвр в него и упирается. Заодно оно отменяет и предел разгона — упёршийся
 * в него корабль трогается резче, чем ему положено. Иначе никак: это про терпение
 * смотрящего, а оно кончается раньше любой физики.
 *
 * Мерка тут экранная, а не временная, и это важнее, чем кажется. Плоский потолок в секундах
 * тут стоял раньше, и с ним длительность манёвра переставала зависеть от его длины вовсе:
 * укоротишь путь вдвое — корабль просто пойдёт вдвое медленнее и придёт в те же полминуты.
 * Ход по кадру держит вместо этого постоянным то, что и видно глазу, и время идёт за путём:
 * короткий манёвр и отыгрывается быстро.
 *
 * Число тут одно на всех, и меняется оно тоже сразу всем: раз в этот предел упирается каждый
 * манёвр в кадре, то самые быстрые корабли — это все они и есть. Было 4, стало на пятую часть
 * меньше: на четырёх ближний катер пересекал кадр за восемнадцать секунд и выглядел
 * не маневрирующим, а проносящимся. Ниже опускать некуда — дальний корабль и так идёт
 * через весь кадр почти минуту.
 */
const MIN_SAIL_PACE = 3.2;

/**
 * Запас за кромкой кадра, длин корпуса. Отсчитан он от положения, в котором корабль уже
 * спрятан целиком: до кромки идёт сам путь, ещё полкорпуса уходит на то, чтобы кормой
 * миновать обрез кадра, — и вот дальше начинается запас.
 *
 * Заходящему хватает половины корпуса. Он и так за кадром, а запас тут на неточность:
 * место корабля проходит через clamp у краёв, отступ задан в пикселях, и от расчётной точки
 * настоящая немного отличается. Раньше из-за этого из-за кромки торчал нос стоящего корабля.
 *
 * Уходящему — полторы: он не тормозит у края, а уходит и уходит, и пропасть из разметки
 * должен заведомо после того, как скрылся с глаз. Раньше запас был в целый кадр, и это
 * оказалось дорого: ход на рейде неспешный, и корабль, меняющий место, минуту шёл
 * за кромкой туда и обратно, прежде чем показаться на новом.
 */
export const ENTER_GUARD = 0.5;
export const LEAVE_GUARD = 1.5;

/**
 * Ширина овала свободного места, % ширины сцены. Считается от той же ширины слота, что
 * и корабль, поэтому дальние места мельче ближних — овалы лежат на воде и подчиняются
 * той же перспективе. Доля заметно меньше единицы: овал — отметка места, а не обвод корпуса,
 * и в кадре он спорит и с соседними коридорами (те разнесены на треть кадра), и с соседними
 * линиями, которые перспектива сводит к горизонту тем теснее, чем они дальше.
 */
const BERTH_WIDTH_SHARE = 1 / 3;

export const berthWidthPercent = (slot: number): number => slotWidthPercent(slot) * BERTH_WIDTH_SHARE;

/** Сколько метров моря приходится на процент ширины кадра на этой дальности. */
const metresPerPercent = (slot: number): number => SCENE_SCALE_LENGTH / slotWidthPercent(slot);

/**
 * Сколько кораблю идти от стоянки за край кадра, % ширины рейда. Путь до кромки — это про
 * кадр, и меряется он кадром; а вот запас за кромкой — про сам корабль, и меряется корпусами:
 * спрятаться должен каждый одинаково, и катеру для этого нужно куда меньше моря, чем кораблю.
 *
 * Кромок при этом две. Рейд бывает уже сцены — в развёрнутом кадре по бокам от него остаётся
 * просто море (см. .raid в стилях), — и уйти корабль должен за кромку сцены, а не за край
 * рейда, где его прекрасно видно. Лишнее море приходит отдельным слагаемым и в тех же долях
 * рейда: одно и то же расстояние по обе стороны, поэтому на выбор стороны ухода оно не влияет
 * и по умолчанию его нет.
 */
export const pathToEdge = (
    leftPercent: number,
    widthPercent: number,
    side: 'left' | 'right',
    /** Запас за кромкой, длин корпуса: ENTER_GUARD или LEAVE_GUARD. */
    guard: number,
    /** Насколько сцена шире рейда с этой стороны, % ширины рейда. */
    overhang = 0
): number => {
    const span = side === 'left' ? leftPercent : 100 - leftPercent;
    return span + overhang + widthPercent * (0.5 + guard);
};

/**
 * Сколько секунд кораблю идти столько-то процентов кадра. Путь переводим в метры по мерке
 * сцены, скорость берём по размеру корабля и по длине пути. Задним ходом — дольше.
 *
 * Скорость здесь средняя по манёвру, а не мгновенная: корабль и так трогается с нуля и в ноль
 * приходит, поэтому «столько-то метров за столько-то секунд» — честная мерка, а как скорость
 * распределится внутри прогона, решает кривая в стилях.
 *
 * Готовое число делится на скорость времени (см. config/time): под проверками весь кадр живёт
 * быстрее, и ход — первое, что там незачем пережидать. Делится оно в самом конце, одним местом
 * на все манёвры: соотношения между ними от этого не меняются, а разъехаться с длительностями
 * в стилях, поделёнными на ту же мерку, нечему.
 */
export const sailSeconds = (pathPercent: number, slot: number, kind: ShipKind, astern: boolean): number => {
    const metres = pathPercent * metresPerPercent(slot);
    return paced(Math.min(metres / sailSpeed(metres, kind, astern), pathPercent / MIN_SAIL_PACE));
};

/**
 * Дифферент на полном манёвренном ходу, градусов: у самого короткого корабля справочника
 * и у самого длинного. Идущий корабль приподнимает ту оконечность, которой идёт вперёд, —
 * он всходит на собственную волну, а корма садится.
 *
 * Больше размер — меньше угол, и это не условность: волна, на которую корабль всходит, растёт
 * не так быстро, как сам корабль, и длинному корпусу она приходится куда ниже скулы. Углы
 * при этом нарочно маленькие: на рейде маневрируют, а не идут глиссером, и разница со стоящим
 * должна читаться, а не бросаться в глаза.
 */
const TRIM_SHORTEST_DEG = 0.7;
const TRIM_LONGEST_DEG = 0.3;

/** Скорость, на которой дифферент выходит на предельный угол, м/с: самый быстрый манёвр справочника. */
const TRIM_FULL_MPS = ROADSTEAD_KNOTS_SHORTEST * KNOT_MPS;

/**
 * Дифферент на этом манёвре, градусов: предел по размеру корабля, взятый по доле от полного
 * хода. Скорость считается настоящая — путь, делённый на время, — а не паспортная: длительность
 * упирается в наименьший ход по кадру, и упёршийся в него корабль идёт быстрее, чем ему
 * положено по размеру.
 *
 * Угол идёт за скоростью прямо: сколько хода, столько и дифферента, а на стопе его нет вовсе.
 * Отсюда и гашение в стилях — там переход тянет угол в ноль той же кривой, что и сам ход,
 * поэтому к концу захода корабль приходит уже почти выровнявшимся.
 *
 * Знак ставит компонент: угол зависит от того, какой стороной корабль идёт вперёд, а не от того,
 * куда смотрит нос.
 */
export const sailTrim = (pathPercent: number, seconds: number, slot: number, kind: ShipKind): number => {
    if (pathPercent <= 0 || seconds <= 0) {
        return 0;
    }
    const speed = (pathPercent * metresPerPercent(slot)) / seconds;
    const full = TRIM_SHORTEST_DEG + (TRIM_LONGEST_DEG - TRIM_SHORTEST_DEG) * sizeShare(kind);
    return Math.min(speed / TRIM_FULL_MPS, 1) * full;
};

/**
 * Кивок, градусов: у самого короткого корабля справочника и у самого длинного. Это не дифферент,
 * а два коротких движения по краям манёвра: трогаясь, корабль вскидывает нос и оттуда выходит
 * на свой ходовой угол, а гася ход — клюёт носом и выравнивается. Идёт это не по волне
 * и не по скорости, а по её перемене, поэтому и живёт отдельно и от качки, и от дифферента.
 *
 * Размер работает так же, как в дифференте: лёгкий катер упор винта разворачивает вокруг миделя
 * почти без сопротивления, а кораблю в полсотни метров на это нужно куда больше. Крупным кивок
 * оставлен на десятую долю градуса: по правде его там нет, но кадр без него мертвеет — стоящий
 * флот и трогающийся корабль выглядят одинаково неподвижными.
 */
const NOD_SHORTEST_DEG = 0.3;
const NOD_LONGEST_DEG = 0.1;

/**
 * Кивок этого корабля, градусов. Знак ставит компонент: на трогании вскидывается та оконечность,
 * которой корабль идёт вперёд, на остановке — наоборот.
 */
export const nodAngle = (kind: ShipKind): number =>
    NOD_SHORTEST_DEG + (NOD_LONGEST_DEG - NOD_SHORTEST_DEG) * sizeShare(kind);

/**
 * Проходит ли корабль сквозь остров, идя в эту сторону. Остров занимает левую часть кадра
 * и на дальних слотах стоит выше корабля по кадру — корабль нарисовался бы прямо на нём.
 * Ближе ISLAND_FREE_SLOT он проходит перед берегом, и это как раз нормально.
 */
export const crossesIsland = (slot: number, side: 'left' | 'right'): boolean =>
    side === ISLAND_SIDE && slot < ISLAND_FREE_SLOT;

/**
 * За сколько слотов чужой корабль ещё считается стоящим на дороге. Ровно за один: сосед
 * бывает и на своей дальности — на линии их помещается двое, — и тогда он стоит по другому
 * борту кадра, и уходить кораблю положено в свою, свободную сторону. Соседний слот отличается
 * по глубине на девятую часть
 * всей перспективы: корабли там почти одного размера и почти на одной линии, и проход
 * сквозь такого соседа читается как столкновение. Через слот разница уже видна, и корабль
 * проходит перед соседом или за ним — это в кадре происходит постоянно и вопросов не вызывает.
 */
const NEIGHBOUR_REACH = 1;

/** Кто стоит на пути — на своей или соседней дальности и с той стороны, куда идём. */
const shipsInTheWay = (place: ShipPlacement, others: ShipPlacement[], side: 'left' | 'right'): ShipPlacement[] =>
    others.filter(
        (other) =>
            Math.abs(other.slot - place.slot) <= NEIGHBOUR_REACH &&
            (side === 'left' ? other.left < place.left : other.left > place.left)
    );

/**
 * Цены манёвра, длин корпуса. Единица тут не случайная: длиной корпуса меряется и сам путь
 * до кромки кадра, поэтому помеха, задний ход и лишний круг складываются с расстоянием
 * без переводных коэффициентов — всё в одном счёте.
 *
 * Задний ход стоит два корпуса: ход вперёд всегда лучше, и перемещение на два корпуса носом
 * должно перевешивать перемещение на один корпус кормой (2 < 1 + 2). Запрета на задний ход
 * при этом нет — он просто дороже и включается, когда иначе мешают соседи.
 *
 * Круг вокруг сцены — полтора корпуса, и мерка тут не морская, а зрительская: самого круга
 * никто не видит, корабль просто пропадает за одной кромкой и появляется из-за другой, так
 * что дорого он стоить не может. Но и даром не даётся — за кромкой лежит целое море, которое
 * корабль обходит, пока его нет в кадре.
 *
 * Число зажато с двух сторон, и вилка узкая. Кадр в корпусах невелик: на ближней линии
 * он шириной 2.2 корпуса, на дальней — 4.5, а боковой коридор смещён от середины всего
 * на 1.2–2.5 корпуса. Чтобы перестановка на соседнюю линию своего же коридора шла в одну
 * и ту же кромку — а не кругом, ради того чтобы зайти носом, — круг должен стоить дороже
 * 0.8. Чтобы переход в середину кадра и через рейд шёл по-старому, кругом и носом вперёд,
 * дешевле 2.0. Полтора берёт середину этой вилки.
 *
 * Помехи идут поверх этого лесенкой, и каждая ступень дороже всего кадра разом: обходить
 * чужой корабль корабль должен при любой длине пути, а не когда обход случайно окажется
 * короче. Сосед через линию отличается по глубине и размеру — корабль проходит перед ним
 * или за ним, и в кадре это видно именно так, поэтому шесть корпусов: помеха, но проходимая
 * с любой стороны кадра. Сосед по своей линии стоит на той же воде и того же размера, пройти
 * его насквозь ничем не прикроешь — двадцать, дороже любой пары помех через линию. Берег
 * не обойти вовсе, и цена ему запретительная.
 */
const ASTERN_COST = 2;
const DETOUR_COST = 1.5;
const NEIGHBOUR_COST = 6;
const SAME_LINE_COST = 20;
const ISLAND_COST = 100;

/**
 * Чем плох уход в эту сторону. Не «да/нет», а лесенка, потому что выбирать иногда приходится
 * из плохого: чисто, мимо соседа по соседней линии, сквозь стоящего на своей, по берегу.
 *
 * Порядок в ней не случаен. Сосед через линию отличается по глубине и размеру — корабль
 * проходит перед ним или за ним, и в кадре это видно именно так. Сосед по своей линии стоит
 * на той же воде и того же размера: пройти его насквозь ничем не прикроешь. Ну а берег
 * не обойти вовсе.
 */
const courseCost = (place: ShipPlacement, others: ShipPlacement[], side: 'left' | 'right'): number => {
    if (crossesIsland(place.slot, side)) {
        return ISLAND_COST;
    }
    const ships = shipsInTheWay(place, others, side);
    if (ships.some((other) => other.slot === place.slot)) {
        return SAME_LINE_COST;
    }
    return ships.length > 0 ? NEIGHBOUR_COST : 0;
};

/** Путь от стоянки за кромку кадра, длин корпуса: тем же счётом, что и цены выше. */
const hullsToEdge = (place: ShipPlacement, kind: ShipKind, side: 'left' | 'right', guard: number): number => {
    const width = shipWidthPercent(place.slot, kind);
    return pathToEdge(place.left, width, side, guard) / width;
};

/** Ход через кромку кадра: в какую сторону и задним ли ходом. */
export interface EdgeCourse {
    side: Side;
    astern: boolean;
}

/**
 * Чего стоит уйти в эту сторону: путь до кромки, помехи по дороге и разворот, если идти
 * не туда, куда смотрит нос.
 */
const leaveCost = (place: ShipPlacement, kind: ShipKind, others: ShipPlacement[], side: Side): number =>
    hullsToEdge(place, kind, side, LEAVE_GUARD) +
    courseCost(place, others, side) +
    (side === place.facing ? 0 : ASTERN_COST);

/**
 * Чего стоит зайти с этой стороны. Считается тем же, что и уход, с одной переменой: задний ход
 * тут не там, где сторона расходится с курсом, а там, где сходится. Заходящий справа корабль
 * идёт по кадру влево — и если нос у него смотрит вправо, идёт он кормой вперёд.
 */
const enterCost = (place: ShipPlacement, kind: ShipKind, others: ShipPlacement[], side: Side): number =>
    hullsToEdge(place, kind, side, ENTER_GUARD) +
    courseCost(place, others, side) +
    (side === place.facing ? ASTERN_COST : 0);

/**
 * В какую сторону корабль уходит из кадра и задним ли ходом. Это про уход с рейда совсем:
 * возвращаться такому кораблю некуда, и довод у него один — что перед носом.
 *
 * Обычно верх берёт ход вперёд, куда смотрит нос: разворачиваться посреди рейда незачем.
 * Но если впереди остров или чужой корабль, корабль уходит задним ходом, кормой вперёд:
 * медленнее, зато не по суше и не в чужой борт.
 *
 * Перезаходящий считается иначе — у него уход и заход связаны, см. relocateCourse.
 */
export const leaveCourse = (place: ShipPlacement, kind: ShipKind, others: ShipPlacement[]): EdgeCourse => {
    const back = otherSide(place.facing);
    // При равном счёте корабль остаётся при своём курсе: разворот сам по себе ничего
    // не исправляет.
    const goBack = leaveCost(place, kind, others, back) < leaveCost(place, kind, others, place.facing);
    return { side: goBack ? back : place.facing, astern: goBack };
};

/** Весь перезаход разом: как корабль уходит со старого места и как заходит на новое. */
export interface RelocateCourse {
    leave: EdgeCourse;
    enter: EdgeCourse;
}

/**
 * Как корабль перебирается на новое место через кромку кадра.
 *
 * Считается это одним счётом на оба перегона, и в этом вся суть. Раньше сторона захода была
 * назначена наперёд — заходят носом вперёд, значит с борта, обратного курсу, — а уход только
 * под неё подстраивался. На дальнем конце рейда правило и работало: заходить всё равно через
 * полкадра, и лишний перегон незаметен. А вот перестановка на соседнюю линию своего же
 * коридора выходила нелепой: корабль в правом коридоре носом вправо пятился через весь кадр
 * влево и оттуда же шёл обратно направо — четыре пролёта там, где хватает двух.
 *
 * Теперь сочетаний четыре, по стороне на каждый перегон, и у каждого своя цена: путь до кромки,
 * помехи на дороге, разворот и круг вокруг сцены, если уходить в одну сторону, а возвращаться
 * с другой. Все цены — в длинах корпуса, см. выше. Побеждает обычно привычное — уйти вперёд
 * и зайти носом, — но если оба места жмутся к одной кромке, дешевле выходит выйти за неё
 * и оттуда же вернуться кормой вперёд: полтора корпуса круга дешевле не выходят, а вот
 * пути до дальней кромки и обратно они уже не окупают.
 *
 * Порядок в списке не случаен: при равном счёте берётся первое, а первым идёт привычный ход.
 */
export const relocateCourse = (from: Afloat, to: Afloat, others: ShipPlacement[]): RelocateCourse => {
    const ways: [Side, Side][] = [
        [from.place.facing, otherSide(to.place.facing)],
        [from.place.facing, to.place.facing],
        [otherSide(from.place.facing), otherSide(to.place.facing)],
        [otherSide(from.place.facing), to.place.facing],
    ];
    const price = ([leave, enter]: [Side, Side]): number =>
        leaveCost(from.place, from.shipKind, others, leave) +
        enterCost(to.place, to.shipKind, others, enter) +
        (leave === enter ? 0 : DETOUR_COST);
    const [leave, enter] = ways.reduce((best, way) => (price(way) < price(best) ? way : best));
    return {
        leave: { side: leave, astern: leave !== from.place.facing },
        enter: { side: enter, astern: enter === to.place.facing },
    };
};

/** Переход по воде: куда идти, задним ли ходом, сколько пути и сколько на него секунд. */
export interface Shift {
    toward: Side;
    astern: boolean;
    /** Путь между осями коридоров, % ширины сцены. */
    path: number;
    seconds: number;
}

/**
 * Можно ли перейти на новое место прямо по воде — и если да, то как.
 *
 * Всякая другая перемена места отыгрывается перезаходом: корабль уходит за кромку, пропадает
 * на паузу и заплывает заново. Для соседнего коридора на своей же дальности это и неправда,
 * и долго: до кромки и обратно кораблю идти полкадра туда да полкадра сюда, а между точками —
 * меньше трети. Стоит он при этом на той же линии, то есть на той же воде и того же размера,
 * и весь манёвр умещается в кадр целиком.
 *
 * Условий три, и каждое — про то, что кораблю нечего отыгрывать за кромкой. Дальность одна:
 * менять слот значит менять и размер, а расти на глазах кораблю нельзя. Силуэт тот же: сменивший
 * корабль человек меняет не место, а корабль, и прежний обязан уйти с рейда. Курс тот же:
 * развернуться на месте корабль не может, а мгновенно отзеркалить силуэт — то же самое, что
 * подменить его.
 *
 * Задний ход тут в порядке вещей: до соседней точки ходу меньше трети кадра, и разворачиваться
 * ради этого незачем — на рейде так и маневрируют. Дороже он только временем, см. sailSeconds.
 */
export const shiftAcross = (from: Afloat, to: Afloat): Shift | null => {
    if (from.place.slot !== to.place.slot || from.shipKind !== to.shipKind || from.place.facing !== to.place.facing) {
        return null;
    }
    const path = Math.abs(to.place.left - from.place.left);
    if (path === 0) {
        return null;
    }
    const toward: Side = to.place.left > from.place.left ? 'right' : 'left';
    const astern = toward !== to.place.facing;
    return { toward, astern, path, seconds: sailSeconds(path, to.place.slot, to.shipKind, astern) };
};

/**
 * Сколько корабль пропадает из виду, перезаходя на другое место, с. Пауза нужна, чтобы уход
 * и заход читались как два разных манёвра, а не как рывок из одного края кадра в другой.
 *
 * Она часть манёвра, а не отсрочка перед ним, — поэтому идёт по той же скорости времени,
 * что и сам ход (см. config/time). Иначе ускоренный перезаход состоял бы почти из одной паузы.
 */
export const RELOCATE_PAUSE_SECONDS = paced(3);

/** Ход через кромку кадра от места, где корабль стоит по расстановке, с. */
const edgeSeconds = (afloat: Afloat, course: EdgeCourse, guard: number): number => {
    const width = shipWidthPercent(afloat.place.slot, afloat.shipKind);
    const path = pathToEdge(afloat.place.left, width, course.side, guard);
    return sailSeconds(path, afloat.place.slot, afloat.shipKind, course.astern);
};

/**
 * Сколько манёвр займёт целиком, с: заход новичка, переход по воде или уход, пауза и заход
 * заново. Ровно то, что отыграет сцена, — той же механикой и теми же ценами.
 *
 * Оценка, а не замер, и в двух местах нарочно грубее сцены. Во-первых, считается она до того,
 * как манёвр начался: место назначает бэкенд, и корабль может встать не туда, куда целился
 * человек. Во-вторых, путь до кромки берётся от рейдовой доли, а сцена ведёт корабль
 * от настоящей точки в кадре — с разбросом внутри полосы, с расхождением с соседом,
 * с проекцией дальнего края и с лишним морем по бокам от рейда.
 *
 * Грубости этой хватает. Отвечает число на один вопрос — идёт манёвр ещё или уже кончился, —
 * и цена ошибки в нём: пришедший под самый конец либо доиграет лишнюю секунду, либо
 * не доиграет её же. Точность тут стоила бы того, чтобы считать ход по чужому кадру,
 * а кадры у всех разные.
 *
 * Секунды здесь по скорости времени этой вкладки, как и везде в этом файле. Наружу, в запись
 * манёвра, они уходят через `unpaced` — см. `Manoeuvre.seconds`.
 */
export const manoeuvreSeconds = (from: Afloat | undefined, to: Afloat, others: ShipPlacement[]): number => {
    if (!from) {
        // Новичок приходит из-за кромки: откуда — известно из места, задним ли ходом — тоже
        // (нос смотрит туда же, откуда пришёл, — значит идёт кормой вперёд).
        return edgeSeconds(
            to,
            { side: to.place.enterFrom, astern: to.place.facing === to.place.enterFrom },
            ENTER_GUARD
        );
    }
    const shift = shiftAcross(from, to);
    if (shift) {
        return shift.seconds;
    }
    const course = relocateCourse(from, to, others);
    return (
        edgeSeconds(from, course.leave, LEAVE_GUARD) +
        RELOCATE_PAUSE_SECONDS +
        edgeSeconds(to, course.enter, ENTER_GUARD)
    );
};

/**
 * Сколько с. занимает уход с рейда сам по себе, без встречного захода, — тем же счётом, что
 * и первая половина перезахода в `manoeuvreSeconds`, только курс берётся не под пару заходу
 * (`relocateCourse`), а сам по себе, как при настоящем уходе (`leaveCourse`): возвращаться
 * уходящему некуда, и второй половины у его манёвра нет.
 *
 * Сам по себе уход с рейда манёвром в записи участника не считается: `isManoeuvre` сравнивает
 * два места, а у ушедшего участия уже нет вовсе — сервер вычёркивает его целиком, а не переводит
 * в какое-то «ушёл» место (см. `functions/src/raid.ts`, `leaveChannel`). Но в кадре это тот же
 * самый ход, со своей длительностью, — и она нужна тому, кто здесь же садится в строй заново:
 * не начинать новый манёвр, пока сцена не доиграла предыдущий уход этого же корабля, — иначе
 * вход накладывается на ещё идущий выход, и корабль дёргается назад на прежнее место, а потом
 * идёт на новое быстрее хода (см. `App.tsx`, `departureEndsAtRef`).
 */
export const departureSeconds = (from: Afloat, others: ShipPlacement[]): number =>
    edgeSeconds(from, leaveCourse(from.place, from.shipKind, others), LEAVE_GUARD);
