/**
 * Чем по приложению тыкают: пальцем или указателем.
 *
 * Ширина окна тут ни при чём. Раньше вопрос «телефон ли это» решался порогом в 480px, и вместе
 * с шириной менялось всё разом — и размеры в кадре, и поведение форм. Размеры про ширину и живут
 * в стилях (см. --wide в index.less); здесь остаётся одно поведение — ставить ли фокус в поле
 * сразу, — и зависит оно от указателя: на тачскрине фокус выкидывает клавиатуру поверх формы.
 *
 * `(pointer: coarse)` — про основной указатель устройства. Мышь, воткнутая в планшет, ответ
 * не меняет: клавиатура там всё равно экранная.
 */
export const isTouch = (): boolean => window.matchMedia('(pointer: coarse)').matches;
