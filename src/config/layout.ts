/**
 * Раскладка: числа, которые должны совпадать в стилях и в коде.
 *
 * Точка перехода в мобильный вид одна на всё приложение. Отсюда её берёт и JS
 * (`utils/viewport`), и Less: `vite.config.ts` подставляет `@mobile-width` в каждый
 * `.less`-файл из этой же константы, так что второго числа, которое можно забыть поправить,
 * в проекте нет.
 *
 * 480px — потому что до этой ширины помещается только один столбец: сцена растянута
 * во всю ширину, формы идут от края до края, а полей и кнопок в ряд не бывает.
 */
export const MOBILE_MAX_WIDTH = 480;

/** Медиавыражение мобильного вида — оно же стоит в `@media` после подстановки в Less. */
export const MOBILE_MEDIA_QUERY = `(max-width: ${MOBILE_MAX_WIDTH}px)`;

/**
 * С какой высоты окна кнопки формы прилипают к нижней кромке панели, px.
 *
 * Отсечка по высоте окна, а не по тому, сколько места досталось самой форме. Места этого
 * тем меньше, чем выше сцена, а сцена сжимается плавно и вместе с окном: считай мы по нему,
 * кнопки прилипали бы и отлипали от пары пикселей, набежавших неизвестно откуда. Высота
 * окна — то, что человек меняет сам и заметно.
 *
 * Число выведено из раскладки: сцене отдано 34% высоты окна (не больше 300px), остальное —
 * панель под ней. На 620px панели достаётся 409px, и это те самые «больше 400», ниже которых
 * прилипшие кнопки съедали бы у короткой формы слишком заметную долю.
 */
export const PINNED_ACTIONS_MIN_HEIGHT = 620;

/**
 * До какой высоты окна шторки не бывает вовсе, px.
 *
 * Шторка живёт только в полноэкранном режиме и делит окно со сценой. Делить его есть смысл,
 * пока обеим что-то достаётся: сложенная шторка занимает 320px, и в окне ниже этой отсечки
 * сцене остаётся меньше, чем ей отдано в обычном виде (34% высоты окна). Сходятся эти две
 * доли на 485px — чуть выше отсечки, то есть ниже неё разворот на весь экран заведомо
 * показывает меньше кадра, чем нераскрытый, — а шторка при этом всё ещё ходит поверх
 * и накрывает то немногое, что видно. Телефон, положенный на бок, — ровно этот случай:
 * 390–430px в высоту, из них 320 под сложенную шторку.
 *
 * Ниже отсечки шторка перестаёт быть шторкой: ступеней, ручки и затемнения у неё нет, она просто
 * лежит под сценой, и страница прокручивается целиком — экран сцены, за ним экран разговора.
 *
 * 480px — потому что портретные телефоны начинаются от 560–670px в высоту, а лежащие на боку
 * кончаются на 430: отсечка стоит в промежутке и ни одну из ориентаций не задевает краем.
 */
export const SHORT_WINDOW_MAX_HEIGHT = 480;

/** Медиавыражение короткого окна — оно же стоит в `@media` после подстановки в Less. */
export const SHORT_WINDOW_MEDIA_QUERY = `(max-height: ${SHORT_WINDOW_MAX_HEIGHT}px)`;

/**
 * Насколько экраны короткого окна не дотягивают до его высоты, px.
 *
 * Экранов в нём два — кадр и разговор, — и лежат они друг под другом одной прокручиваемой
 * полосой. Будь каждый ровно в высоту окна, в любом конце полосы был бы виден ровно один: за
 * соседа не потянуть, и о том, что он вообще есть, знать неоткуда. Поэтому каждый ниже окна
 * на эту полоску: сверху из-под кадра выглядывает край шторки, снизу над шторкой — полоска воды.
 *
 * Ею же чинится клавиатура. Выехав, она прокручивает полосу до конца, чтобы показать поле ввода,
 * и обратно после себя не отматывает — шторка так и оставалась верхом у верхней кромки окна,
 * а кадр уезжал из виду совсем. С полоской «до конца» означает «шторка на 72px ниже верха», то
 * есть с кадром, который видно, и отматывать назад нечего.
 *
 * В стилях число берётся с потолком в 20svh: в окне ростом 300px две полоски по 72px съели бы
 * почти половину полосы, а начиная с 2 × 72 ≥ высоты окна прокручивать стало бы нечего вовсе.
 */
export const SHORT_WINDOW_PEEK = 72;

/**
 * Ширина колонки приложения, px. В обычном виде по ней обрезано всё — и сцена, и лента;
 * в полноэкранном её держит только содержимое: во весь экран просили кадр, а не ленту
 * сообщений, растянутую на два монитора.
 */
export const COLUMN_WIDTH = 760;

/**
 * Щёлка шторки, px: сколько её видно в самом нижнем положении.
 *
 * Не «чуть-чуть» и не подсказка: сложенная шторка обязана быть рабочей. Из неё читается
 * не «там что-то лежит», а сам разговор — три последние реплики вместе с полем ввода,
 * и переписываться, не открывая шторку вовсе, уже можно. Три, а не одна: по одной строчке
 * видно, что кто-то что-то сказал, но не видно, кто кому отвечает.
 *
 * Отсюда и число: 22px ручки с отступом ленты, три строки по 79px (подпись и строка текста
 * в узкой колонке телефона) и 57px поля ввода — 316, округлённые до 320.
 *
 * Одна высота на телефон и на десктоп. Раньше на телефоне щёлка была вдвое ниже (132px,
 * «видно, что там чат»), но мерка у обеих одна и та же: строки на широком окне не ниже,
 * а лента и там, и там обрезана по @column-width. Разной высоте взяться неоткуда.
 */
export const SHADE_PEEK_HEIGHT = 320;

/**
 * Насколько сложенная шторка заезжает на воду, px.
 *
 * Кадр в полноэкранном режиме встаёт не встык со шторкой, а на столько выше: нижняя полоска
 * моря уходит под неё. Иначе шторка лежит ровно на кромке кадра, и стык этот виден — у моря
 * там своя граница, у шторки своя, и обе приходятся на одну линию. Заехав на воду, шторка
 * оказывается на ней, как всё остальное в кадре, и линия остаётся одна.
 *
 * Продолжение моря ниже кадра (см. .appFull в App.module.less) при этом никуда не девается:
 * по бокам от шторки оно по-прежнему видно, просто начинается на 30px ниже.
 */
export const SHADE_SEA_OVERLAP = 30;

/**
 * Насколько шторка не доезжает до верха, px.
 *
 * Ровно на эту полоску смотрит шапка с названием канала и кнопками. Отдавать её шторке
 * нельзя: кнопка «Свернуть сцену» — единственный выход из полноэкранного режима, и прятать
 * её под то, что закрывается перетаскиванием, значит запирать человека в режиме.
 */
export const SHADE_TOP_GAP = 64;
