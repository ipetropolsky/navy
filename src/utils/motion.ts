/** Ближайший кадр. Ждём его там, где надо дать браузеру пересчитать стили. */
export const frame = (): Promise<void> =>
    new Promise((resolve) => {
        requestAnimationFrame(() => resolve());
    });

/**
 * Конец движения блока: обещание сбывается, когда у блока не осталось ни одного перехода
 * и ни одной анимации.
 *
 * Спрашиваем у самого блока (`getAnimations()`), а не отмеряем сроком. Срок пришлось бы брать
 * с запасом от самого долгого перехода, и он всё равно врал бы: длительности делятся
 * на `--time-scale`, а браузер поверх этого умеет замедлять движение целиком — панелью анимаций
 * в отладчике. Всё, что отмерено сроком, на замедленном движении срабатывает посреди дороги:
 * блок снимают с экрана на полпути, лента гаснет в недосложившейся коробке. Спрошенный блок
 * отвечает за себя сам, и длительности его переходов знать никому не надо.
 *
 * Движений у блока бывает несколько, и кончаются они вразнобой: слой уходит сдвигом, а коробка
 * под ним в это же время меняет высоту и уезжает за кромку. Ждём, пока не останется ни одного.
 *
 * `stale` спрашивают перед каждым шагом: пока ждали, всё могло перемениться — закрытое открыли
 * обратно, блок сняли с экрана, — и сбывшееся обещание застало бы уже другой экран. Отвечает
 * оно тем же самым: `true` — доехали, `false` — ждать больше нечего и незачем.
 */
export const stillness = async (node: Element, stale: () => boolean): Promise<boolean> => {
    // Переход заводится не в тот миг, когда сменился класс, а на ближайшем пересчёте стилей.
    // Спросив раньше, мы не застали бы движения вовсе и решили, что блок уже доехал.
    await frame();
    // Круги тут именно последовательные: каждый следующий спрашивает о том, что завелось
    // в предыдущем, и складывать их в один Promise.all нечего — их ещё нет.
    /* eslint-disable no-await-in-loop */
    while (!stale()) {
        const moves = node.getAnimations();
        if (moves.length === 0) {
            return true;
        }
        // Отказом `finished` отвечает на отменённое движение — для нас это такой же его конец,
        // как и обычный.
        await Promise.all(moves.map((move) => move.finished.catch(() => undefined)));
        // Кончившееся движение могло потянуть за собой следующее — спрашиваем заново, дав
        // браузеру кадр на то, чтобы его завести.
        await frame();
    }
    /* eslint-enable no-await-in-loop */
    return false;
};
