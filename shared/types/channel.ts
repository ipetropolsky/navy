import { ChannelErrorCode } from '../errors';

/**
 * Корабли, которые можно выбрать. Все настоящие: у каждого свой номер проекта, свой рисунок
 * и свои числа из справочника. Пять безномерных силуэтов из первых набросков отсюда убраны:
 * рисунков на них было три на пятерых, а размеры подобраны на глаз, и рядом с проектами
 * это читалось как ошибка масштаба.
 */
export type ShipKind = 'pr1234' | 'pr12412' | 'pr1141' | 'pr201' | 'pr205' | 'pr1258' | 'pr1400';

/**
 * Внешность корабля: силуэт и цвет. Хранится не при канале, а при личности — последней записью
 * в её истории кораблей (`users/{userId}/ships`, см. docs/FIREBASE.md): это вкус человека,
 * а не свойство участия, и в новом канале позывной с номером выбираются заново, а ходить
 * предпочитают тем же кораблём того же цвета.
 */
export interface Look {
    shipKind: ShipKind;
    color: string;
}

/**
 * Корабль, каким его завели, — целиком. Этим приложение пополняет личную историю кораблей
 * (`users/{userId}/ships`, см. docs/FIREBASE.md) при входе на рейд и при переоснащении.
 *
 * Позывной и номер лежат в записи вместе с остальным, хотя обратно их сегодня не читает
 * никто — форма подставляет только силуэт и цвет, а позывной с номером в каждом канале
 * выбираются заново (продуктовое решение, см. Look). Без них запись была бы просто прошлым
 * `Look` с лишним полем `channelId`, а не историей флота.
 */
export interface ShipSetup {
    name: string;
    hullNumber: string;
    shipKind: ShipKind;
    color: string;
    /** В каком канале этот корабль завели. */
    channelId: string;
}

/** Борт: левый или правый. Именованный тип, потому что повторяется всюду, где что-то движется. */
export type Side = 'left' | 'right';

/**
 * Вертикальная полоса кадра, в которой стоит корабль. Перечисление, а не номер: номер стоил бы
 * читателю знания таблицы, которой у него нет, — а порядок коридоров от left к right очевиден.
 */
export type Corridor = 'left' | 'center' | 'right';

export const CORRIDORS: Corridor[] = ['left', 'center', 'right'];

/**
 * Место на рейде: точка, на которой стоит корабль. Их конечное число, и они начерчены
 * на воде — свободные показываются овалами, когда человек выбирает, куда встать.
 * Дальность и коридор — что это за место, `left` — где именно оно в кадре.
 */
export interface Berth {
    /** Номер слота: 0 — у горизонта, дальше к наблюдателю. */
    slot: number;
    corridor: Corridor;
    /** Центр корабля, % ширины сцены. */
    left: number;
}

/**
 * Где корабль стоит на рейде и как он туда пришёл. Место выбирает человек, а сторону
 * захода назначает бэкенд, и хранится всё это вместе с участником: сцена должна выглядеть
 * одинаково во всех вкладках, а не пересобираться у каждого по-своему.
 *
 * Тип общий (`shared/`) — его знает не только сцена в браузере, но и сам сервер, который
 * это место назначает.
 */
export interface ShipPlacement extends Berth {
    /** Куда смотрит нос. Определяется стороной входа: корабль идёт носом вперёд. */
    facing: Side;
    /** С какой стороны заплыл: 'right' — из-за правого края кадра. */
    enterFrom: Side;
}

/** Одно ли это место на рейде. Сравниваем по дальности и коридору: точка в них своя и постоянная. */
export const isSameBerth = (one: Berth, other: Berth): boolean =>
    one.slot === other.slot && one.corridor === other.corridor;

/** Сколько мест на рейде. */
export const SLOT_COUNT = 10;

/**
 * Во сколько раз дальний слот дальше ближнего. Это и есть глубина рейда: ближний край
 * принят за единицу, дальний стоит на SLOT_RANGE таких же единиц от наблюдателя.
 * Больше число — дальше уходит рейд и сильнее сбиты в кучу дальние линии.
 */
export const SLOT_RANGE = 5.5;

/**
 * Насколько слот далеко, в дальностях ближнего слота: 1 — первая линия, SLOT_RANGE — последняя.
 * Расстояния между линиями одинаковые, потому что это расстояния по морю: рейд размечен
 * ровным шагом, как стоянка, а не ровным шагом по экрану.
 */
export const slotDistance = (slot: number): number =>
    1 + ((SLOT_COUNT - 1 - slot) * (SLOT_RANGE - 1)) / (SLOT_COUNT - 1);

/**
 * Насколько разметка отступает от строгой перспективы, 0…1. Ноль — как в природе: обратная
 * дальность, и точка. Единица — ровная лесенка по экрану, будто моря нет вовсе.
 *
 * Отступать приходится, потому что кадр невысокий, а рейд длинный. По строгому 1/D половина
 * линий сбивается в пятачок у горизонта: три ближние занимают больше высоты, чем все семь
 * остальных вместе, а дальше четвёртой линии всё слипается в кашу — и корабли, и огоньки,
 * и разметка. Правдиво, но смотреть не на что. Поэтому перспектива здесь не отменена,
 * а смягчена: дальние линии по-прежнему теснее ближних (втрое, а не втридцатеро), просто
 * сходятся не так круто.
 */
export const PERSPECTIVE_EASE = 0.6;

/** Глубина по строгой перспективе: обратная дальность, и ничего больше. */
const trueDepth = (slot: number): number => 1 / slotDistance(slot);

/** Она же без перспективы: те же концы, но ровный шаг по экрану. */
const evenDepth = (slot: number): number => trueDepth(0) + ((1 - trueDepth(0)) * slot) / (SLOT_COUNT - 1);

/**
 * Глубина слота: 1 — первая линия, ближе к нулю — дальше в море. От неё зависит и размер
 * корабля, и его высота в кадре, и размах качки, и ровно этого требует перспектива: всё,
 * что видно на дальности D, и уменьшается, и поднимается к горизонту как 1/D.
 *
 * Поэтому глубина идёт от обратной дальности, а не от номера слота. Ровный шаг по морю
 * даёт на экране неровный — так рейд и выглядит с мостика, и другого способа показать,
 * что море уходит вдаль, у плоской картинки нет. Но целиком отдавать высоту кадра
 * этой правде нельзя, см. PERSPECTIVE_EASE: концы остаются на своих местах, а середина
 * расходится к ровному шагу настолько, насколько сцене нужно дышать.
 */
export const slotDepth = (slot: number): number =>
    trueDepth(slot) + (evenDepth(slot) - trueDepth(slot)) * PERSPECTIVE_EASE;

/**
 * Доля пути от дальней линии к ближней: 0 — самая дальняя линия, 1 — самая ближняя.
 * Та же перспектива, но с другой меркой: глубина отвечает на «во сколько раз меньше»,
 * а доля — на «где между концами рейда». Рейд натянут между двумя отметками у горизонта
 * и у нижней кромки кадра, и стоит на нём линия по этой доле, а не по глубине: глубина
 * дальней линии не ноль, и от неё рейд начинался бы не там, где ему отмерено.
 */
export const slotShare = (slot: number): number =>
    (slotDepth(slot) - slotDepth(0)) / (slotDepth(SLOT_COUNT - 1) - slotDepth(0));

/**
 * Куда точка рейда ложится на экран, % ширины рейда. Рейд всегда один и тот же — вода в долях
 * от нуля до ста, — а на экран его точки ложатся трапецией: передний край раздаётся шире кадра,
 * дальний поджимается внутрь, и размах идёт по той же доле пути от горизонта, что и всё
 * остальное в сцене.
 *
 * Считает это CSS (см. `--raid-reach` в SeaScene.module.less), а здесь — тот же счёт для сцены:
 * путь корабля за кромку кадра меряется настоящим местом в кадре, а не рейдовой долей.
 * На дальней линии проекция уводит корабль к середине, и до кромки ему дальше, чем значится
 * в расстановке; на ближней — наоборот, ближе. Мерка поджатия снимается с вёрстки: она едет
 * вместе с шириной окна, и второго мнения о ней в проекте быть не должно.
 *
 * `share` — доля пути от дальней линии к ближней (`slotShare`), `reachFar` — во сколько раз
 * дальний край уже переднего. Середина кадра у обоих концов трапеции общая, от неё и считаем.
 */
export const projectLeft = (left: number, share: number, reachFar: number): number =>
    50 + (left - 50) * (reachFar + (1 - reachFar) * share);

/**
 * Ширина слота, % ширины сцены: столько занял бы самый длинный корабль справочника,
 * стоя на этой дальности. Числа общие для размера корабля и для мерки моря (см. shipMotion.ts):
 * сделай их больше, и корабли станут крупнее, а кадр — уже в метрах, что одно и то же.
 *
 * По-честному размер шёл бы за глубиной один в один — она и есть 1/D, — и дальний корабль
 * выходил бы в пять с половиной раз мельче ближнего: катер у горизонта стал бы точкой
 * в три десятка пикселей, в которой не разобрать ни силуэта, ни номера. Поэтому слагаемое:
 * перспектива держит основное, а постоянная часть не даёт дальнему краю выродиться. Поджато
 * ровно настолько, чтобы корабль всё ещё читался кораблём, — дальше уже начинается неправда,
 * и стоящий у горизонта корабль выглядит подвешенным над водой.
 */
export const slotWidthPercent = (slot: number): number => 10 + slotDepth(slot) * 50;

/**
 * Во сколько раз мельче ближней линии всё, что стоит на этой. Та же формула, что и у ширины
 * корабля, — и нужна она затем, чтобы размеченный на воде круг уходил в даль ровно с той же
 * скоростью, что и корпуса, которые на нём встанут: разметка и флот лежат на одной воде,
 * и разъезжаться им не по чему.
 */
export const slotScale = (slot: number): number => slotWidthPercent(slot) / slotWidthPercent(SLOT_COUNT - 1);

/**
 * Остров занимает левую часть кадра, и его берег стоит примерно на дальности четвёртой линии.
 * Начиная с ISLAND_FREE_SLOT корабль заметно ближе острова: он проходит перед берегом,
 * и это выглядит правильно. Дальше — уже по берегу, поэтому туда ни вставать, ни ходить.
 *
 * Порог на линию меньше, чем кажется по картинке: у острова на воде широкая тень, а контур
 * мы снимали по альфа-каналу и вместе с берегом захватили её. Настоящий берег кончается
 * раньше, и на четвёртой линии корабль стоит уже перед ним, а не на нём.
 *
 * Знают об этом двое: расстановка (куда встать и с какой стороны зайти) и сцена
 * (в какую сторону уходить), поэтому числа живут здесь, а не у кого-то одного из них.
 */
export const ISLAND_SIDE: Side = 'left';
export const ISLAND_FREE_SLOT = 3;

/** Противоположный борт. Пригождается всюду, где корабль идёт не туда, куда смотрит. */
export const otherSide = (side: Side): Side => (side === 'left' ? 'right' : 'left');

/**
 * Канал связи сам по себе, без списков. Списки лежат рядом, а не внутри: поля канала
 * и коллекции — разные вещи, и мешать их в одном объекте значит однажды не понять,
 * чьё поле читаешь.
 */
export interface Channel {
    /** Основной идентификатор: неизменный, машинный, по нему адресуется всё. */
    channelId: string;
    /** Читаемый адрес для ссылки. Меняется, в отличие от channelId. */
    slug: string;
    title: string;
    createdAt: number;
    /**
     * Старший на рейде: тот, кто в канале за него отвечает и может высадить чужой корабль.
     * Ссылкой на участника, а не флагом у самого участника: старший один на канал, и хранить
     * это надо там, где канал, — иначе однажды окажется, что старших двое.
     *
     * Поля может не быть: канал заводят раньше, чем в него встаёт первый корабль. Старшим
     * становится тот, кто встал первым, и остаётся им, пока не снимется с рейда.
     */
    owner?: MemberRef;
}

/**
 * Каким корабль был виден в ленте: позывной, номер на аватарке, цвет подписи. Ровно то,
 * чем автор сообщения представлен читателю, и ничего больше — ни силуэта, ни места на рейде:
 * в ленте их не видно.
 *
 * Отдельно от `ShipTitle`, хотя половина полей общая: `ShipTitle` — про то, как корабль
 * назвать во фразе, и потому знает тип корабля и не знает цвета; `AuthorLook` — про то,
 * как показать говорящего, и потому наоборот.
 */
export interface AuthorLook {
    name: string;
    hullNumber: string;
    color: string;
}

/**
 * Ссылка на участника. Объект, а не голая строка: рядом с id лежит снимок того, как корабль
 * выглядел в тот момент.
 *
 * Снимок нужен затем, что ссылка переживает самого участника. Сообщение остаётся в ленте
 * и после того, как корабль снялся с рейда, — а искать автора среди нынешних участников
 * тогда уже негде: у такой строчки пропадала аватарка, а в цитате ответа вместо позывного
 * вставало «Неизвестный». Снимок отвечает на это сам, без списка участников.
 *
 * Поля может не быть: ссылка на старшего в канале и ссылка в событии печати говорят о том,
 * кто на рейде сейчас, и снимок им незачем. Не будет его и у сообщений, записанных до того,
 * как снимок завели.
 */
export interface MemberRef {
    memberId: string;
    look?: AuthorLook;
}

/** Как корабль выглядит в ленте сейчас. */
export const memberLook = (member: Member): AuthorLook => ({
    name: member.name,
    hullNumber: member.hullNumber,
    color: member.color,
});

/** Ссылка на участника со снимком: так на него ссылаются сообщения. */
export const memberRef = (member: Member): MemberRef => ({
    memberId: member.memberId,
    look: memberLook(member),
});

/**
 * Как показать автора: нынешним кораблём, а если его на рейде уже нет — снимком из ссылки.
 *
 * Нынешний важнее снимка, и это не мелочь: корабль, сменивший позывной, назван в ленте
 * новым именем везде, где он говорил, — так это работало до снимков и так остаётся. Снимок
 * же говорит только за тех, кого спросить уже не у кого.
 *
 * Ответа может не быть вовсе: у старой записи снимка нет, а её автор ушёл. Тогда в ленте
 * пусто там, где стояла бы аватарка, — и это честнее выдуманного позывного.
 */
export const authorLook = (ref: MemberRef, member?: Member): AuthorLook | undefined =>
    member ? memberLook(member) : ref.look;

/** Ссылка на сообщение. По той же причине объект. */
export interface MessageRef {
    messageId: string;
}

/**
 * Корабль в канале. Позывной, бортовой номер, силуэт и цвет участник выбирает сам,
 * когда встаёт в строй; цветом подписаны его реплики в ленте.
 */
export interface Member {
    memberId: string;
    /** Позывной — он же название корабля. */
    name: string;
    /** Бортовой номер: ровно три цифры, белым по борту и вместо аватарки в чате. */
    hullNumber: string;
    shipKind: ShipKind;
    color: string;
    /** Место на рейде: его назначает бэкенд, участник на него не влияет. */
    place: ShipPlacement;
    joinedAt: number;
    /**
     * Докуда этот участник дочитал разговор — своими глазами, а не общим для канала: у каждого
     * из рейда отметка своя. Пишет её только он сам (см. `ChannelBackend.markSeen`,
     * `firestore.rules`) — участие несёт её просто потому, что канал больше ничего личного
     * для человека не хранит.
     *
     * `at` — метка самого этого сообщения (его `sentAt`), а не время, когда его прочли.
     * Разница не в словах: по этой черте считается непрочитанное (`ChannelBackend.countUnread`
     * спрашивает `sentAt > at`), и обе стороны сравнения обязаны идти по одним часам. Часы же
     * здесь у каждой вкладки свои: `sentAt` ставит отправитель, а «время прочтения» ставил бы
     * читатель. Спешат часы читателя — и всё, что отставший отправитель послал в этот зазор,
     * молча провалилось бы мимо счёта, потому что легло бы по времени раньше черты.
     *
     * Нет её у только что вставшего в строй: отметки ещё не было ни одной.
     */
    lastSeen?: { messageId: string; at: number };
}

/**
 * Как корабль звали в тот момент, о котором речь: тип, позывной, бортовой номер.
 *
 * Снимок, а не ссылка на участника: канал пишет о том, что было, и написанное не должно
 * меняться задним числом. Переоснастился корабль ещё раз — строчка о первом переоснащении
 * остаётся про то, чем он был тогда; снялся с рейда — в списке участников его уже нет,
 * а строчка о нём стоит и должна называть его.
 */
export interface ShipTitle {
    shipKind: ShipKind;
    name: string;
    hullNumber: string;
}

/** Что в корабле может поменяться так, чтобы об этом стоило написать в ленту. */
export type ShipField = keyof ShipTitle;

/**
 * Что случилось с кораблём, о чём канал написал в ленту.
 *
 * Это данные, а не текст: бэкенд сообщает, что произошло и с чем, а как об этом сказать —
 * дело интерфейса. Иначе фраза оказывается зашита в хранилище, и поправить формулировку
 * (или сказать её на другом языке) можно только правкой того, что уже записано.
 *
 * Одна запись — одна перемена: сменивший разом позывной, номер и силуэт корабль даёт три
 * записи, а не одну с тремя пометками. Каждая из них — отдельное сообщение в ленте, со своим
 * временем и своим номером, и на каждую можно ответить; собранные в кучу, они были бы одной
 * строчкой, на которую отвечают целиком, хотя речь в ней о трёх разных вещах.
 */
export interface ShipNotice {
    event: 'joined' | 'refit' | 'left' | 'kicked';
    /** Каким корабль был: до правки, а у входа и ухода — каким он был в тот момент. */
    before: ShipTitle;
    /** Каким стал. Только у переоснащения. */
    after?: ShipTitle;
    /**
     * Какое поле переоснащение поменяло. Выводится сравнением `before` с `after`, и всё же
     * приходит с бэкенда: сравнивать — его дело, у него оба состояния на руках, а интерфейс
     * остаётся про то, как сказать, а не про то, что случилось.
     */
    changed?: ShipField;
    /**
     * Новый курс уходящего: куда он пошёл, своими словами. Только у ухода — и то не всегда:
     * записи, сделанные до того, как курс стали спрашивать, его не знают, и строчка о них
     * складывается по-старому.
     */
    course?: string;
}

/**
 * Доставка сообщения этой вкладкой. Поля нет — сообщение подтверждено сервером; это
 * и есть обычное, всегдашнее состояние, и у подавляющего большинства сообщений в ленте
 * (пришедших не от этой вкладки, или отправленных и подтверждённых уже давно) его не будет
 * никогда.
 *
 * На сервере не хранится — это состояние отправки у этой вкладки, а не свойство сообщения,
 * и заполняет его слой бэкенда: по `hasPendingWrites` из Firestore (см. firebaseBackend.ts)
 * и по своему ящику неотправленного (см. backend/outbox.ts).
 */
export interface MessageDelivery {
    status: 'pending' | 'failed';
    /** Почему не вышло. Только у `failed`. */
    error?: { code: ChannelErrorCode; message: string };
}

interface MessageBase {
    messageId: string;
    /** Кто отправил. У системной записи — тот, о ком она. */
    author: MemberRef;
    /** Время отправки, мс эпохи. Формат для показа выбирает интерфейс, а не хранилище. */
    sentAt: number;
    /** Статус отправки у этой вкладки. См. MessageDelivery. */
    delivery?: MessageDelivery;
}

/** Реплика участника. */
export interface ChatMessage extends MessageBase {
    kind?: undefined;
    text: string;
    /** Ответ: сообщение, к которому он привязан. Поля нет — реплика сама по себе. */
    thread?: MessageRef;
}

/**
 * Системная запись: её пишет сам канал, а не участник. Текста в ней нет вовсе — только
 * то, что случилось; фразу складывает лента (см. `components/chat/ShipNoticeLine`).
 */
export interface ShipNoticeMessage extends MessageBase {
    kind: 'system';
    notice: ShipNotice;
}

export type Message = ChatMessage | ShipNoticeMessage;

/** Порция символов для передачи азбукой Морзе; seq делает каждую порцию уникальной. */
export interface MorseFeed {
    seq: number;
    text: string;
    /**
     * Передачу переставили в другое место текста: прежнюю очередь лампе не дописывают,
     * а заменяют. Без этого лампа сперва договорила бы то, откуда её уже увели, и отставала
     * бы от печати тем сильнее, чем длиннее сообщение (см. `hooks/reception`).
     */
    restart?: boolean;
}

