import { Account } from '@/backend';

import styles from './HomeFooter.module.less';

/**
 * Приписка под кнопками на главной: ход в демо и кто вошёл. Одна на оба экрана главной —
 * список своих каналов и форму создания, — потому что и там и там она про одно и то же:
 * заглянуть в демо, если своих каналов нет, и убедиться, что вошёл ты, а не кто-то другой.
 *
 * Раньше она жила прямо в CreateChannel, и это было незаметно ровно до тех пор, пока форма
 * создания была главной целиком. Теперь главная начинается со списка, а выход из аккаунта
 * не должен требовать открыть форму, в которой человек ничего создавать не собирался.
 */

interface HomeFooterProps {
    /** Адрес демо-канала: обычная ссылка, её видно и можно скопировать. */
    demoHref: string;
    /** Переход в демо без перезагрузки страницы. */
    onOpenDemo: () => void;
    /** Кто вошёл. Показывается мелко и только ему самому — в канале за человека говорит корабль. */
    account: Account | null;
    onSignOut: () => void;
}

export default function HomeFooter({ demoHref, onOpenDemo, account, onSignOut }: HomeFooterProps) {
    return (
        <>
            Или загляни в{' '}
            {/* Ссылка настоящая: её видно в строке состояния, можно скопировать и открыть
                в новой вкладке. Но обычный клик уводим в приложение — перезагружать страницу
                незачем, а со сцены при этом слетают и анимация входа, и загруженные картинки.
                Клик с модификатором и средней кнопкой не трогаем: человек метит в новую вкладку. */}
            <a
                className={styles.demoLink}
                href={demoHref}
                onClick={(event) => {
                    if (event.metaKey || event.ctrlKey || event.shiftKey || event.altKey) {
                        return;
                    }
                    event.preventDefault();
                    onOpenDemo();
                }}
            >
                демо-канал
            </a>
            {/* Кто вошёл — приписка, а не заголовок: имя и почта нужны здесь только
                для того, чтобы человек убедился, что он это он, и мог выйти. */}
            {account && (
                <span className={styles.account}>
                    {`Вы вошли как ${account.name ?? account.email ?? 'моряк'}. `}
                    <button type="button" className={styles.signOut} onClick={onSignOut}>
                        Выйти
                    </button>
                </span>
            )}
        </>
    );
}
