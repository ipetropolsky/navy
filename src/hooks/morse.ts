const MORSE_CODES = new Map(MORSE_CODE_PAIRS);

/** Длительность точки, мс. */
export const MORSE_UNIT = 110;

export interface LampSegment {
    /** Сколько держать лампу включённой (0 — не включать). */
    on: number;
    /** Пауза после включения. */
    off: number;
}

/**
 * Раскладывает символ в тайминги лампы.
 * Пробел — пауза между словами, символ без кода Морзе — спокойное периодическое мигание.
 */
export function charToSegments(char: string): LampSegment[] {
    if (char === ' ') {
        return [{ on: 0, off: MORSE_UNIT * 7 }];
    }
    const code = MORSE_CODES.get(char.toUpperCase());
    if (!code) {
        return [
            { on: MORSE_UNIT * 2, off: MORSE_UNIT * 2 },
            { on: MORSE_UNIT * 2, off: MORSE_UNIT * 3 },
        ];
    }
    return code.split('').map((symbol, index) => ({
        on: symbol === '-' ? MORSE_UNIT * 3 : MORSE_UNIT,
        off: index === code.length - 1 ? MORSE_UNIT * 3 : MORSE_UNIT,
    }));
}
