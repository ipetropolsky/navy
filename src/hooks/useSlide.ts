import { TransitionEvent, useEffect, useState } from 'react';

/**
 * Свойства, по концу которых блок снимают с экрана.
 *
 * Своим ходом блок уезжает вниз — едет `transform`, по нему и считается конец. Приехавший
 * вместе с панелью не двигается сам вовсе: его увозит она, и кончиться должно её движение —
 * уход за кромку (`translate`) или сворачивание до полоски ручки (`height`, `width`).
 */
const OWN_MOVE = ['transform'];
const PANEL_MOVE = ['translate', 'height', 'width'];

/**
 * Блок, который выезжает снизу и уезжает обратно: сколько его держать на экране.
 *
 * Показать уход можно только тому, что в этот момент нарисовано. Снятый в тот же миг, когда
 * его закрыли, блок исчезает без движения — а закрывается он тем же путём, каким появился,
 * иначе выезд читается как показ, а уход как поломка. Поэтому блок остаётся на экране, пока
 * едет, и снимается по концу перехода. Переходы всего остального внутри блока — свои и до конца
 * выезда не относятся, поэтому и цель события проверяется, и его свойство.
 *
 * `still` — блок едет не сам, а вместе с панелью, в которую его открыли: закрытая панель
 * выдвигается уже с готовым содержимым внутри и с ним же задвигается обратно (см. `openLayer`
 * в App.tsx). Собственного движения у блока в этом случае нет, и на экране он держится до конца
 * панелиного.
 *
 * Так устроены обе выезжающие вещи в приложении — список кораблей и форма корабля поверх
 * разговора, — и правило у них одно на двоих.
 */
export const useSlide = (
    open: boolean,
    still = false
): { mounted: boolean; onTransitionEnd: (event: TransitionEvent<HTMLElement>) => void } => {
    const [mounted, setMounted] = useState(open);

    // Открыли — рисуем. Обратно в состоянии это не отражается: закрытый блок ещё едет,
    // и снимет его конец перехода.
    useEffect(() => {
        if (open) {
            setMounted(true);
        }
    }, [open]);

    // Подстраховка на случай, когда конца перехода не будет вовсе: перехода нет в системе,
    // где движение выключено, или его отменили прямо посреди ухода. Событие тогда не приходит,
    // и блок, снимаемый по нему, оставался бы на экране навсегда. Срок взят с запасом
    // от самого долгого из переходов, какими блок уходит: своим ходом это @slide-seconds (0.28s),
    // вместе с панелью — @expand-seconds (0.42s). На обычном уходе он и не понадобится.
    useEffect(() => {
        if (open) {
            return undefined;
        }
        const timer = window.setTimeout(() => setMounted(false), 600);
        return () => window.clearTimeout(timer);
    }, [open]);

    const onTransitionEnd = (event: TransitionEvent<HTMLElement>) => {
        const moves = still ? PANEL_MOVE : OWN_MOVE;
        if (!open && event.target === event.currentTarget && moves.includes(event.propertyName)) {
            setMounted(false);
        }
    };

    return { mounted: open || mounted, onTransitionEnd };
};
