/**
 * Раскладка: числа, которые должны совпадать в стилях и в коде.
 *
 * Приложение состоит из двух вещей — кадра со сценой и блока контента под ним, — и раскладок
 * у него две: «больше контента» и «больше сцены». Всё, что ниже, описывает эти две раскладки
 * и одну шторку поверх них; ничего третьего в приложении нет.
 *
 * Каждое число живёт здесь в единственном экземпляре: `vite.config.ts` подставляет их в каждый
 * `.less`, так что второго мнения о том, где кончается телефон и насколько сжато сжатое,
 * в проекте не бывает. Почему раскладка именно такая — в docs/LAYOUT.md.
 */

/**
 * Точка перехода в мобильный вид, px.
 *
 * 480px — потому что до этой ширины помещается только один столбец: сцена растянута
 * во всю ширину, формы идут от края до края, а полей и кнопок в ряд не бывает.
 */
export const MOBILE_MAX_WIDTH = 480;

/** Медиавыражение мобильного вида — оно же стоит в `@media` после подстановки в Less. */
export const MOBILE_MEDIA_QUERY = `(max-width: ${MOBILE_MAX_WIDTH}px)`;

/**
 * Ширина колонки приложения, px. По ней обрезаны и сцена, и блок контента. В раскладке
 * «больше сцены» предел снимается со сцены, но не с блока: во весь экран просят кадр,
 * а не ленту сообщений, растянутую на два монитора.
 */
export const COLUMN_WIDTH = 760;

/**
 * Сколько достаётся сжатому, px.
 *
 * Число одно на обе раскладки, потому что случай один и тот же: одному из двух блоков отдают
 * место, второй сжимается до рабочего минимума. В раскладке «больше контента» сжата сцена,
 * в раскладке «больше сцены» — блок контента, и высота у них одна.
 *
 * 300px — это и кадр, в котором видно рейд с кораблями и полосу неба над ними, и разговор,
 * из которого читаются три последние реплики вместе с полем ввода.
 */
export const COMPACT_HEIGHT = 300;

/**
 * Сколько достаётся сжатому блоку контента на десктопе, px.
 *
 * Единственное исключение из общего числа. На широком окне у ленты своя разбивка — реплики
 * стоят в две колонки по краям и занимают меньше строк, — и те же три реплики с полем ввода
 * просят чуть больше высоты, чем на телефоне.
 */
export const CONTENT_DESKTOP_HEIGHT = 320;

/**
 * Насколько блок контента заезжает на сцену, px.
 *
 * Кадр кончается не встык с блоком, а на столько ниже: нижняя полоска моря уходит под него.
 * Иначе у моря своя граница, у блока своя, и обе приходятся на одну линию; заехав на воду,
 * блок оказывается лежащим на ней, как всё остальное в кадре.
 */
export const CONTENT_OVERLAP = 30;

/**
 * Ширина шторки на десктопе, px. Чуть уже колонки: шторка приезжает поверх блока контента,
 * и по её краям должно быть видно, что под ней что-то есть. На телефоне предел ни на что
 * не влияет — там окно и так уже колонки.
 */
export const SHEET_WIDTH = 720;

/**
 * Насколько шторка не доезжает до верха окна, px.
 *
 * Ровно на эту полоску смотрит шапка с названием канала и кнопками. Отдавать её шторке нельзя:
 * кнопками из шапки шторка и открывается, и закрывается.
 */
export const SHEET_TOP_GAP = 64;

/**
 * Высота полоски у верхней кромки прокручиваемого, под которую уходит содержимое, px.
 *
 * Прокручиваемое иначе обрывается по кромке ровной линией: реплика или строчка формы срезана
 * пополам, и срез читается краем разметки, а не продолжением списка. Градиент от цвета фона
 * к прозрачному растворяет уходящее в этом же фоне.
 *
 * Тем же числом полоска и набирается: на первых 28px прокрутки она входит в полную силу.
 * Мерка одна на оба дела нарочно — полоска проявляется ровно тогда, когда под неё заходит
 * первая строка, а не раньше и не позже.
 *
 * 28px — половина строки списка: меньше не растворяет, а подкрашивает, больше — съедает
 * верхнюю строчку целиком.
 */
export const FADE_HEIGHT = 28;
