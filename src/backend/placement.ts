/**
 * Где на рейде стоят корабли: какие места вообще есть, какие из них свободны и куда встать
 * тому, кто не выбрал сам.
 *
 * Место человек выбирает в форме — свободные показываются овалами прямо на воде, — но хранит
 * и назначает его бэкенд. Поэтому сцена у всех одинаковая: чей-то корабль стоит на одном
 * и том же месте и смотрит в одну и ту же сторону во всех вкладках, а не разъезжается
 * у каждого по-своему. И поэтому же выбор проверяется здесь: пока человек раздумывал,
 * на выбранное место мог встать кто-то другой.
 *
 * Мест на рейде десять дальностей — это «слоты» — по три коридора в каждой. На одной дальности
 * стоят самое большее двое, считая остров (SLOT_CAPACITY), и помещаются они туда, только если
 * расходятся бортами (sideBySide) — не обязательно стоя на серединах своих коридоров: тесной
 * паре разрешено разойтись внутри них (spreadPair), и в кадре это и происходит. Само место
 * от этого не меняется: расхождение считает сцена, каждая вкладка по своему экрану.
 * Кто места не выбирал, встаёт случайно: строй не должен выглядеть построенным. Свободная
 * случайность, впрочем, быстро собирает корабли в кучу, поэтому её ограничивают три правила:
 * коридоры разводят соседей по ширине кадра, размер корабля задаёт, в какой части рейда
 * он скорее встанет, а из оставшегося берётся самое свободное — как место в автобусе,
 * где сперва садятся подальше от всех.
 *
 * Коридор — вертикальная полоса кадра, в которой стоит корабль. Их три, с серединами
 * на 20%, 50% и 80% ширины, и корабль сейчас встаёт ровно на середину своего: место
 * человек выбирает глазом, по нарисованной на воде точке, и вставать корабль должен туда,
 * куда ткнули. Разброс внутри коридора вернётся отдельно — как положение корабля внутри
 * выбранного места. Два корабля в одном коридоре должны стоять хотя бы через два слота
 * друг от друга — тогда они разнесены по дальности достаточно, чтобы не наложиться силуэтами.
 */

import { MOBILE_SHIP_ZOOM } from '@/config/layout';
import {
    Berth,
    CORRIDORS,
    Corridor,
    ISLAND_FREE_SLOT,
    ISLAND_SIDE,
    Member,
    SHIP_KINDS,
    SHIP_SPECS,
    SLOT_COUNT,
    ShipKind,
    ShipPlacement,
    Side,
    otherSide,
    shipWidthPercent,
    shownLeft,
} from '@/types/channel';

/**
 * Чужой корабль на рейде, каким его видит расстановка: где стоит и какой ширины. Размер
 * нужен ей не меньше места — помещаются ли двое на одной линии, решают именно борта.
 */
export type Standing = Pick<Member, 'shipKind' | 'place'>;

/**
 * Корабль на линии для счёта бортами: дальность, коридор и силуэт. Не `Standing`, потому что
 * считать приходится и то, чего на рейде ещё нет, — место, которое человеку только предлагают.
 */
interface Spot {
    slot: number;
    corridor: Corridor;
    kind: ShipKind;
}

const spotOf = (ship: Standing): Spot => ({
    slot: ship.place.slot,
    corridor: ship.place.corridor,
    kind: ship.shipKind,
});

/** Центры коридоров, % ширины сцены. */
const CORRIDOR_CENTERS: Record<Corridor, number> = { left: 20, center: 50, right: 80 };

/** Ближе этого числа слотов друг к другу два корабля в одном коридоре не встают. */
const MIN_SLOT_GAP = 3;

/**
 * Сколько объектов стоит на одной дальности — считая остров. Двое, и это не про тесноту,
 * а про свободу выхода: у двоих на линии всегда есть по своему борту наружу, и уходя с рейда
 * каждый идёт в свою сторону, никого не задевая. Третий встал бы между ними и оказался заперт
 * с обеих сторон — ему пришлось бы проходить сквозь соседа.
 *
 * Остров тут такой же сосед, только неподвижный: он держит левый коридор дальних слотов,
 * и корабль там остаётся на линии один.
 *
 * Правило это про топологию, а sideBySide — про геометрию, и одно другого не заменяет: двое
 * помещаются на линию, только если и место есть, и борта расходятся.
 */
const SLOT_CAPACITY = 2;

/**
 * Насколько сцена сводит боковые коридоры к горизонту, % ширины кадра (@berth-spread-far
 * в стилях). Коридоры не строго вертикальные: у дальнего края они сходятся к середине кадра,
 * к наблюдателю — расходятся, и на воде это видно по точкам свободных мест. Расстановке
 * важен тесный конец: взяв дальний, она ошибётся только в свою пользу — там, где корабли
 * разведены сильнее, места им тем более хватит.
 */
const CORRIDOR_SQUEEZE = 3;

/**
 * Сколько воды остаётся между бортами, долей корпуса. Меркой служит сам корабль, а не проценты
 * кадра: на дальней линии те же три процента — это половина корпуса, а на ближней едва
 * ли не швартовный конец. Седьмой части хватает, чтобы борта читались раздельно и на глаз
 * было видно, что это двое, а не один длинный силуэт.
 */
const BOARD_GAP = 0.15;

/**
 * Левый коридор упирается в остров: тот занимает левую часть кадра, а его берег стоит
 * примерно на дальности слота 0.7. Корабль на дальних слотах там либо оказывается прямо
 * на суше (замер: на слоте 0 под его ватерлинией земля), либо, будучи мелким и далёким,
 * рисуется поверх более близкого острова и читается выброшенным на берег.
 *
 * Поэтому левый коридор закрыт для дальних слотов. Начиная с ISLAND_FREE_SLOT корабль
 * заметно ближе острова и крупнее — перекрытие читается как «прошёл перед берегом»,
 * а это как раз то, что нужно. Сам порог живёт в types/channel.ts: про остров знает
 * не только расстановка, но и сцена, когда решает, в какую сторону кораблю уходить.
 */
const ISLAND_CORRIDOR: Corridor = 'left';

/**
 * Сколько слотов от «своей» дальности рассматриваем как равноценные. Не правило, а склонность:
 * из этого набора слот берётся случайно, поэтому крупный корабль встаёт где-то в дальней
 * половине рейда, а не строго на последнем слоте, и строй не выстраивается по росту.
 */
const SLOT_CHOICE = 4;

/**
 * Из скольких самых свободных мест выбираем в итоге. Рейд занимается как автобус: сначала
 * места подальше от всех, и только когда таких не осталось — те, что ближе к соседям.
 * Не одно самое дальнее, а несколько лучших: иначе расстановка стала бы алгоритмом,
 * который на одних и тех же кораблях каждый раз выдаёт одну и ту же картинку.
 */
const SPOT_CHOICE = 3;

/** Наибольшее расстояние между центрами коридоров, % ширины сцены: от левого до правого. */
const CORRIDOR_SPAN = CORRIDOR_CENTERS.right - CORRIDOR_CENTERS.left;

/**
 * Насколько корабль может отойти от середины своего коридора, % ширины сцены. Это и есть
 * ширина коридора: половина расстояния до соседнего — дальше начинается уже он.
 *
 * Отходит корабль не сам по себе, а от соседа, которому иначе не хватает воды, и не насовсем:
 * ушёл сосед — вернулся на своё место (см. spreadPair). Место при этом не меняется: в канале
 * корабль по-прежнему стоит там, куда его поставили, а расхождение живёт только в кадре.
 *
 * Третьему на линии это не мешает: больше двоих на неё и так не встают (SLOT_CAPACITY),
 * так что занять полосу соседнего коридора некому.
 */
const CORRIDOR_ROOM = CORRIDOR_SPAN / (CORRIDORS.length - 1) / 2;

/**
 * Куда тянет корабль этого размера: самый длинный — к дальнему краю рейда, самый мелкий —
 * к переднему плану. Так сцена уравновешивается сама: крупные не загораживают собой весь кадр,
 * а катера не теряются у горизонта точками.
 */
const preferredSlot = (kind: ShipKind): number => {
    const lengths = SHIP_KINDS.map((item) => SHIP_SPECS[item].length);
    const shortest = Math.min(...lengths);
    const longest = Math.max(...lengths);
    const size = (SHIP_SPECS[kind].length - shortest) / (longest - shortest);
    return Math.round((1 - size) * (SLOT_COUNT - 1));
};

const pick = <T>(items: T[]): T => items[Math.floor(Math.random() * items.length)];

const shuffled = <T>(items: T[]): T[] => {
    const copy = [...items];
    for (let i = copy.length - 1; i > 0; i--) {
        const j = Math.floor(Math.random() * (i + 1));
        [copy[i], copy[j]] = [copy[j], copy[i]];
    }
    return copy;
};

const allSlots = (): number[] => [...new Array<number>(SLOT_COUNT)].map((_, index) => index);

/**
 * Где корабль этого размера на самом деле стоит в этом коридоре, % ширины сцены. Не середина
 * коридора: боковые сведены к горизонту, а у края кадра корабль ещё и упирается в отступ —
 * чем он крупнее, тем дальше от кромки его держат стили, и на ближних линиях двое сходятся
 * теснее, чем стоят их коридоры.
 *
 * Считается по самому тесному раскладу — телефонному, где корабли растянуты (MOBILE_SHIP_ZOOM).
 * Расстановка одна на всех, и разводить корабли внахлёст на узком экране она не должна;
 * на широком то же место окажется только просторнее.
 */
const standingLeft = (spot: Spot, zoom: number, aside = 0): number => {
    const side = CORRIDOR_CENTERS[spot.corridor] - CORRIDOR_CENTERS.center;
    const squeeze = CORRIDOR_SQUEEZE * Math.sign(side);
    return shownLeft(CORRIDOR_CENTERS[spot.corridor] - squeeze + aside, shipWidthPercent(spot.slot, spot.kind), zoom);
};

/**
 * Сколько воды нужно этим двоим между серединами корпусов: полусумма ширин да немного воды
 * сверх того. Та же мерка, что и на глаз: борта не должны налезать друг на друга, и между
 * ними должно быть видно, что это двое, а не один длинный силуэт.
 */
const needApart = (one: Spot, other: Spot, zoom: number): number =>
    ((shipWidthPercent(one.slot, one.kind) + shipWidthPercent(other.slot, other.kind)) / 2) * zoom * (1 + BOARD_GAP);

/** Насколько корабль может отойти в эту сторону: своя полоса коридора минус то, что съел край кадра. */
const asideRoom = (spot: Spot, away: number, zoom: number): number =>
    Math.abs(standingLeft(spot, zoom, away * CORRIDOR_ROOM) - standingLeft(spot, zoom));

/**
 * Как двое расходятся на одной линии. Стоят они на серединах своих коридоров, и, если воды
 * между бортами хватает, там и остаются. Не хватает — расходятся внутри своих коридоров:
 * первым отходит тот, кто стоял раньше, а вставший позже уступает только то, чего не хватило
 * соседу. Так это и выглядит: пришедший занял место, а стоявший подвинулся.
 *
 * Отходят не насовсем и не по-настоящему: место в канале не меняется, расхождение живёт
 * только в кадре и держится, как на резинке, — ушёл сосед, и корабль вернулся на свою точку.
 * Отсюда и порядок «сперва стоявший»: это его резинку натянули, ему и отпускать.
 *
 * `short` — сколько воды не хватило даже так. Больше нуля — значит эти двое на одной линии
 * не помещаются, и расстановка эту пару не составит (см. freeCorridors). Меньше или ровно —
 * помещаются, а `resident` и `guest` говорят, на сколько каждому отойти.
 */
const spreadPair = (resident: Spot, guest: Spot, zoom: number): { resident: number; guest: number; short: number } => {
    const apart = Math.abs(standingLeft(resident, zoom) - standingLeft(guest, zoom));
    const short = needApart(resident, guest, zoom) - apart;
    if (short <= 0) {
        return { resident: 0, guest: 0, short: 0 };
    }
    // Отходит каждый от соседа: тот, кто стоит правее, — вправо. Считается по серединам
    // коридоров, а не по самим кораблям: у края кадра оба прижаты клампом и стоят на одном
    // и том же месте, и «кто правее» по ним не разобрать.
    const away = Math.sign(CORRIDOR_CENTERS[resident.corridor] - CORRIDOR_CENTERS[guest.corridor]);
    const byResident = Math.min(short, asideRoom(resident, away, zoom));
    const byGuest = Math.min(short - byResident, asideRoom(guest, -away, zoom));
    return { resident: away * byResident, guest: -away * byGuest, short: short - byResident - byGuest };
};

/**
 * Помещаются ли эти двое борт о борт — с учётом того, что разойтись они могут не только
 * коридорами, но и внутри них (см. spreadPair и CORRIDOR_ROOM). Считается по самому тесному
 * раскладу — телефонному, где корабли растянуты: пустив пару на линию, расстановка отвечает
 * за неё на любом экране.
 *
 * Раньше на месте этого счёта стояли два числа на глазок — ближняя граница, за которой двоих
 * уже не ставили, и список соседних коридоров, — и вместе они выходили строже любой геометрии:
 * пара помещалась ровно на двух линиях из десяти, третьей и четвёртой, да и там лишь по краям
 * кадра. В правилах она была, а в кадре её почти никто не видел: на пять кораблей — одна
 * расстановка из одиннадцати (замер). Настоящий предел ставит размер: два катера расходятся
 * по бортам и у самой кромки, а двум крупным тесно уже на середине рейда.
 *
 * Стоять на серединах коридоров при этом никто не обязан, и правило это учитывает: считается
 * не то, сколько воды между коридорами, а то, сколько её будет, когда оба разойдутся до края
 * своих полос. Пока корабли жёстко стояли на серединах, крупному отказывали там, где ему
 * не хватало пары процентов кадра, — а взять их было откуда.
 *
 * Вместимость линии при этом осталась на месте (SLOT_CAPACITY): размер решает, помещаются ли
 * двое, а не сколько их. Это разные вопросы — и когда счёт бортами заменил собой и вместимость
 * тоже, на дальних линиях стало по три объекта, остров да двое, и средний оказывался заперт
 * между ними (замер: 3.7% расстановок по пять кораблей).
 */
const sideBySide = (slot: number, corridor: Corridor, kind: ShipKind, other: Standing): boolean =>
    spreadPair(spotOf(other), { slot, corridor, kind }, MOBILE_SHIP_ZOOM).short <= 0;

/**
 * Коридоры, свободные для этого слота, в случайном порядке. Сначала линия целиком: если на ней
 * уже стоят двое (или один да остров), она занята — сколько бы воды между ними ни оставалось.
 * Дальше по коридорам: мимо идут занятые соседом по дальности в том же коридоре, те, где
 * кораблю не разойтись бортами с уже стоящим на этой линии, и остров.
 *
 * Дальность и ширина проверяются порознь, потому что мешают по-разному. Сосед на соседней
 * линии того же коридора закрывает её собой: разница в дальности там на девятую часть
 * перспективы, силуэты почти одного размера и почти на одном месте — это читается наложением,
 * сколько бы воды между ними ни было. А вот на одной дальности всё решают борта, и решают
 * честным счётом.
 */
const freeCorridors = (slot: number, kind: ShipKind, taken: Standing[]): Corridor[] => {
    const island = slot < ISLAND_FREE_SLOT;
    const here = taken.filter((other) => other.place.slot === slot);
    if (here.length + (island ? 1 : 0) >= SLOT_CAPACITY) {
        return [];
    }
    const blocked = new Set<Corridor>();
    for (const other of taken) {
        if (Math.abs(other.place.slot - slot) < MIN_SLOT_GAP) {
            blocked.add(other.place.corridor);
        }
    }
    for (const other of here) {
        CORRIDORS.filter((corridor) => !sideBySide(slot, corridor, kind, other)).forEach((corridor) =>
            blocked.add(corridor)
        );
    }
    if (island) {
        blocked.add(ISLAND_CORRIDOR);
    }
    return shuffled(CORRIDORS).filter((corridor) => !blocked.has(corridor));
};

/**
 * Насколько место далеко от чужого корабля. Обе разницы приведены к долям своего размаха
 * и сложены: 0 — тот же слот и тот же коридор, 2 — противоположный угол рейда. Дальность
 * и ширина считаются наравне, потому что в кадре они и выглядят наравне: сосед через
 * два слота разнесён с тобой примерно так же, как сосед в другом коридоре.
 */
const distanceTo = (slot: number, corridor: Corridor, other: ShipPlacement): number =>
    Math.abs(slot - other.slot) / (SLOT_COUNT - 1) +
    Math.abs(CORRIDOR_CENTERS[corridor] - CORRIDOR_CENTERS[other.corridor]) / CORRIDOR_SPAN;

/** Насколько место свободно: расстояние до ближайшего соседа. Пустой рейд — свободно всё. */
const loneliness = (slot: number, corridor: Corridor, taken: Standing[]): number =>
    taken.length === 0 ? Infinity : Math.min(...taken.map((other) => distanceTo(slot, corridor, other.place)));

/**
 * Место на рейде целиком: дальность, коридор и точка в кадре. Точка — ровно середина
 * коридора: место человек выбирает глазом по этой точке, и стоять корабль должен там,
 * куда ткнули, а не рядом. Разброс внутри коридора вернётся отдельно — уже как положение
 * корабля внутри выбранного места, а не как положение самого места.
 */
const berthAt = (slot: number, corridor: Corridor): Berth => ({
    slot,
    corridor,
    left: CORRIDOR_CENTERS[corridor],
});

/**
 * С какой стороны корабль заходит на рейд.
 *
 * На дальних слотах выбора нет: с той стороны остров, и корабль прошёл бы прямо по нему.
 * А там, где выбор есть, он не честная монетка, а противовес: чем больше кораблей уже пришло
 * с одной стороны, тем вероятнее следующий придёт с другой. Иначе рейд заполнялся бы
 * в основном справа — дальние слоты вынужденно правые, а крупные корабли тянутся именно туда.
 *
 * Перевес считается по квадратам, а не напрямую: перекос надо не смягчать, а выправлять.
 * Дальние слоты все правые, и крупные корабли тянутся именно туда, так что вольную половину
 * рейда приходится уводить влево заметно сильнее, чем «чуть чаще». Единица в каждой скобке —
 * обычное сглаживание: на пустом рейде выходит ровно половина, и правая сторона не запрещена
 * никогда.
 */
const enterSide = (slot: number, taken: Standing[]): Side => {
    if (slot < ISLAND_FREE_SLOT) {
        return otherSide(ISLAND_SIDE);
    }
    const fromLeft = (taken.filter((other) => other.place.enterFrom === 'left').length + 1) ** 2;
    const fromRight = (taken.filter((other) => other.place.enterFrom === 'right').length + 1) ** 2;
    return Math.random() < fromRight / (fromLeft + fromRight) ? 'left' : 'right';
};

/**
 * Место с назначенной стороной захода: откуда корабль придёт и куда будет смотреть носом.
 * Само место к этому моменту уже выбрано — человеком в форме или расстановкой.
 */
const placeAt = (berth: Berth, taken: Standing[]): ShipPlacement => {
    const enterFrom = enterSide(berth.slot, taken);
    // Пришёл справа — значит идёт влево, носом вперёд.
    return { ...berth, facing: enterFrom === 'right' ? 'left' : 'right', enterFrom };
};

/**
 * Все свободные места рейда — то, что показывается овалами на воде. Предпочтений по размеру
 * тут нет: куда встать, человек решает сам, и предлагать ему половину рейда только потому,
 * что у него крупный корабль, незачем. А вот сам размер важен — от него зависит, куда этот
 * корабль вообще влезет, и, выбрав в форме другой силуэт, человек видит, как часть точек
 * на воде пропадает или появляется.
 */
export const freeBerths = (kind: ShipKind, taken: Standing[]): Berth[] =>
    allSlots().flatMap((slot) => freeCorridors(slot, kind, taken).map((corridor) => berthAt(slot, corridor)));

/** Свободно ли это место для такого корабля. */
export const isBerthFree = (berth: Berth, kind: ShipKind, taken: Standing[]): boolean =>
    freeCorridors(berth.slot, kind, taken).includes(berth.corridor);

/** Корабль в кадре, каким его видит расхождение: где стоит, какой ширины и с каких пор. */
export type Anchored = Standing & Pick<Member, 'memberId' | 'joinedAt'>;

/**
 * На сколько корабли отходят от своих точек, % ширины сцены со знаком: минус — к левому краю
 * кадра, плюс — к правому. Кого нет в ответе, тот стоит на своём месте.
 *
 * Это единственное, что рисуется не по сохранённому месту. Место остаётся тем, куда корабль
 * поставили, — во всех вкладках одно и то же, — а расхождение считает и показывает каждая
 * вкладка сама, по своему экрану: на телефоне корабли растянуты и расходиться им приходится
 * заметнее, чем на широком. Хранить тут нечего: из одного и того же состава на одном и том же
 * экране всегда выходит одно и то же расхождение.
 *
 * Считается по парам на линии: больше двоих на неё не встают, так что пара — это всё, что
 * бывает. Отходят корабли только внутри своих коридоров и только друг от друга: сменить
 * коридор сосед никого заставить не может.
 */
export const spreadAside = (fleet: Anchored[], zoom: number): Record<string, number> => {
    const aside: Record<string, number> = {};
    for (const slot of new Set(fleet.map((ship) => ship.place.slot))) {
        // Кто раньше встал, тот и «стоявший»: отходит он, а пришедший позже занимает своё
        // место и уступает только то, чего стоявшему не хватило места отдать.
        const here = fleet
            .filter((ship) => ship.place.slot === slot)
            .sort((one, other) => one.joinedAt - other.joinedAt);
        if (here.length === 2) {
            const [resident, guest] = here;
            const spread = spreadPair(spotOf(resident), spotOf(guest), zoom);
            aside[resident.memberId] = spread.resident;
            aside[guest.memberId] = spread.guest;
        }
    }
    return aside;
};

/**
 * Куда этот корабль может встать сам. В отличие от freeBerths — с оглядкой на дальность:
 * сначала отбираются слоты, ближайшие к «своей» части рейда, а потом раскладываются
 * по свободным коридорам.
 */
const preferredBerths = (kind: ShipKind, taken: Standing[]): Berth[] => {
    const wanted = preferredSlot(kind);
    return allSlots()
        .filter((slot) => freeCorridors(slot, kind, taken).length > 0)
        .sort((a, b) => Math.abs(a - wanted) - Math.abs(b - wanted))
        .slice(0, SLOT_CHOICE)
        .flatMap((slot) => freeCorridors(slot, kind, taken).map((corridor) => berthAt(slot, corridor)));
};

/**
 * Место для корабля — как место в автобусе: сперва подальше от всех, и только когда таких
 * не осталось, поближе к соседям. Считается это одинаково для обоих случаев: свободные места
 * сортируются по расстоянию до ближайшего соседа, и выбор идёт из нескольких самых свободных.
 *
 * Случайность нужна: без неё расстановка превратилась бы в алгоритм, который на одном
 * и том же составе каждый раз рисует одну и ту же картинку.
 */
const pickBerth = (kind: ShipKind, taken: Standing[]): Berth | null => {
    const berths = preferredBerths(kind, taken);
    if (berths.length === 0) {
        return null;
    }
    // Перемешиваем до сортировки: сортировка устойчива, поэтому одинаково свободные места
    // сохранят случайный порядок. Без этого на пустом рейде, где свободно всё, в набор
    // попадали бы три коридора одного и того же слота — и первый корабль всегда вставал бы
    // на одно и то же место.
    const roomiest = shuffled(berths)
        .sort((a, b) => loneliness(b.slot, b.corridor, taken) - loneliness(a.slot, a.corridor, taken))
        .slice(0, SPOT_CHOICE);
    return pick(roomiest);
};

/**
 * Ставит корабль на рейде. Место человек выбирает сам, но полагаться на этот выбор нельзя:
 * пока он раздумывал, туда мог встать кто-то другой, — и тогда корабль встаёт на случайное
 * свободное, как если бы места не выбирали вовсе.
 *
 * Возвращает null, если свободных мест нет: при пяти участниках на десять слотов это
 * невозможно, но проверка дешевле, чем разбирательство, если однажды станет возможно.
 */
export const placeShip = (kind: ShipKind, taken: Standing[], wanted?: Berth): ShipPlacement | null => {
    const berth = wanted && isBerthFree(wanted, kind, taken) ? wanted : pickBerth(kind, taken);
    return berth && placeAt(berth, taken);
};
