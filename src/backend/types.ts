// Реэкспортом, а не только импортом: интерфейс ниже (ChannelBackend) использует MemberDraft
// напрямую, а `export type { X } from '…'` даёт лишь пересылку — локального имени она не заводит.
import type { MemberDraft } from '@shared/types/calls';
import { Channel, Member, MemberRef, Message, MessageRef } from '@shared/types/channel';

/**
 * Контракт бэкенда. Фронтенд знает только его и ничего — про то, где лежат данные:
 * сегодня это localStorage в соседней вкладке, завтра Firebase. Поэтому все методы
 * асинхронные, даже когда реализация может ответить мгновенно: синхронный ответ
 * приучил бы UI к порядку, которого у настоящего сервера не будет.
 *
 * Форма контракта подчинена правилам из docs/API-PRINCIPLES.md. Коротко: всё, что может
 * стать объектом, кладётся объектом; ссылка называется по сущности и несёт её канонический
 * идентификатор (`author: { memberId }`, а не `memberId`); методы принимают один именованный
 * объект; ответ — тоже объект, а не голая сущность. Всё это ради одного: чтобы завтрашнее
 * поле дописывалось рядом, а не ломало читателей.
 *
 * У канала два имени, и путать их нельзя. `channelId` — основной идентификатор: неизменный,
 * машинный, по нему адресуются все действия и события. `slug` — читаемый адрес для ссылки
 * (`?channel=eskadra-polnoch`), его можно переназначить, и внутри системы на него никто
 * не ссылается. Отсюда и отдельный метод разбора адреса: getChannelBySlug.
 */

/** Канал целиком: сам канал и его коллекции, каждая своим ключом. */
export interface ChannelSnapshot {
    channel: Channel;
    members: Member[];
    /**
     * Лента — не вся, а последняя страница (см. `config/network.ts`, MESSAGE_PAGE):
     * разговор в канале не ограничен, а держать его в памяти вкладки целиком незачем,
     * пока видна только нижняя часть.
     */
    messages: Message[];
    /** Есть ли выше messages ещё лента. Правда — повод звать loadOlderMessages. */
    hasMoreMessages: boolean;
}

/**
 * Что участник о себе сообщает: и когда встаёт в строй, и когда переоснащает корабль.
 * Общая с сервером форма — оба конца провода должны разбирать один и тот же черновик.
 */
export type { MemberDraft };

/**
 * Что у канала можно задать и потом поменять: адрес и человеческое название. `closed`/`code`
 * сюда же, хотя меняются только на создании (см. createChannel) — updateChannel их не принимает
 * и сам не отправляет, они неизменны после создания (firestore.rules держит их вне onlyChanges
 * у update): заводить для одной пары полей второй, почти такой же черновик было бы дороже,
 * чем не заводить.
 */
export interface ChannelDraft {
    /** Латинские буквы, цифры и дефис; в ссылке стоит именно он. */
    slug: string;
    title: string;
    /**
     * Закрытая частота: войти можно, только зная код доступа (`code`). Не указано — канал
     * открыт, как и раньше.
     */
    closed?: boolean;
    /**
     * Код доступа закрытого канала. Обязателен вместе с `closed: true`, и только тогда
     * (см. closedSane в firestore.rules; ACCESS_CODE_MAX_LENGTH в shared/types/channel.ts).
     * С сервера потом не возвращается никому и никогда, даже участнику, — единственное
     * в канале, что не входит в тип Channel (см. Channel.closed там же).
     */
    code?: string;
}

/**
 * Тело сообщения — и только оно. Отправитель сюда не входит: он адресует запрос,
 * а не является частью текста, и передаётся отдельным полем метода.
 */
export interface MessageDraft {
    text: string;
    /** Ответ: сообщение, к которому он привязан. */
    thread?: MessageRef;
    /**
     * Под каким идентификатором записать сообщение. Повторная отправка с тем же —
     * не второе сообщение, а та же запись: так устроен повтор после обрыва
     * (см. retryMessage). Не указан — назначает бэкенд, как и раньше.
     */
    messageId?: string;
}

/**
 * Общий конверт события. Поля здесь у всех одинаковые, различает события только `type`,
 * поэтому добавить новый вид — например системное уведомление о шторме — можно, ничего
 * не ломая: транспорт и подписка про конкретные типы не знают, а UI разбирает знакомые
 * и молча пропускает незнакомые.
 *
 * По проводу идёт только то, что канал у себя оставляет. Печати среди событий нет и не будет:
 * сообщение доставляется целиком, а по буквам его набирает уже получатель, у себя (см.
 * `hooks/useReception`). Дело не в экономии — событие на каждую букву значит запись документа
 * на каждую букву, и в тот день, когда за подпиской окажется Firebase, за печать одной реплики
 * придётся заплатить полусотней записей.
 */
interface ChannelEventBase {
    /** Свой у каждого события: по нему отбрасываем повторную доставку. */
    eventId: string;
    channelId: string;
    at: number;
}

export type ChannelEvent = ChannelEventBase &
    (
        | { type: 'channel-created'; channel: Channel }
        | { type: 'channel-updated'; channel: Channel }
        | { type: 'member-joined'; member: Member }
        | { type: 'member-updated'; member: Member }
        | { type: 'member-left'; member: MemberRef }
        | { type: 'message-added'; message: Message }
        /** Статус доставки сменился — например, пришло подтверждение сервера. См. #69. */
        | { type: 'message-updated'; message: Message }
        /** Неотправленное выброшено (см. discardMessage) — в ленте его больше нет. */
        | { type: 'message-removed'; message: MessageRef }
    );

export type ChannelEventType = ChannelEvent['type'];

/**
 * Почему действие не вышло. Коды одни и те же у сервера и у клиента: сервер бросает
 * `ChannelError` изнутри транзакции, а этот файл остаётся единственной дверью для фронтенда.
 */
export { ChannelError } from '@shared/errors';
export type { ChannelErrorCode } from '@shared/errors';

export type Unsubscribe = () => void;

/** Есть ли связь с бэкендом прямо сейчас — и с какого момента она в этом состоянии. */
export type ConnectionStatus = 'online' | 'offline';

export interface Connection {
    status: ConnectionStatus;
    /** `Date.now()` того момента, с которого действует текущий статус. */
    since: number;
}

/**
 * Адрес канала — во всех методах, кроме создания и разбора ссылки. Скаляром, а не объектом:
 * это адрес запроса, то, что в настоящем API стояло бы в пути, а не его содержимое.
 */
interface ChannelAddress {
    channelId: string;
}

/** Адрес участника внутри канала. По той же причине скаляром. */
interface MemberAddress extends ChannelAddress {
    memberId: string;
}

export interface ChannelBackend {
    /**
     * `userId` отвечает сразу за два: ключ своего же неотправленного в ящике (`backend/outbox.ts`:
     * без него не найти, ключ там `<userId>.<channelId>`) и сам факт входа — отдельного поля
     * для входа нет, потому что оно бы просто дублировало это же: кто не вошёл, у того userId
     * и не бывает (см. App.tsx, `auth.account?.userId ?? null`).
     *
     * Поэтому у необязательности здесь два разных смысла, и оба нужны. Не участник этого канала
     * (`null` — точно посторонний, либо чужой вошедший под собственным userId, но не с этого
     * рейда) получает вход, а не рейд: `members: []`, `messages: []`, `hasMoreMessages: false` —
     * до участников, ленты и брони мест не участник не доходит вовсе (см. firestore.rules,
     * isMember), и это не урезанный их вид, а прямое отсутствие. У самого `channel` в таком
     * ответе можно доверять только `title` и `closed` — ровно то, что отдаёт previewChannel;
     * остальные его поля (`slug`, `createdAt`, `owner`) бэкенд заполняет чем придётся, и ветки
     * App.tsx, куда попадает не участник, их и не читают. Не передан вовсе — вызвавшему сам факт
     * входа не важен (так зовут не из App.tsx, а из проверок, которым нужно самое состояние,
     * а не то, как его увидел бы кто-то конкретный): ответ как есть, только без подмешанного
     * ящика.
     */
    getChannel(request: ChannelAddress & { userId?: string | null }): Promise<ChannelSnapshot | null>;
    /** Разбор адреса из ссылки: по slug находим канал и дальше работаем с его channelId. */
    getChannelBySlug(request: { slug: string; userId?: string | null }): Promise<ChannelSnapshot | null>;

    createChannel(request: { channel: ChannelDraft }): Promise<{ channel: Channel }>;
    updateChannel(request: ChannelAddress & { channel: ChannelDraft }): Promise<{ channel: Channel }>;

    /**
     * Проверить код доступа закрытого канала — для экрана «Закрытая частота», ещё до формы
     * постановки в строй. Ничего не решает по-настоящему: это подсказка человеку, чтобы он
     * не успел заполнить форму корабля с неверным кодом, а не запирающая проверка — код
     * заново и по-настоящему сверяет join ниже. Неверный код — `channel-closed`
     * (см. shared/errors.ts); открытый канал эта проверка не отвергает никогда, каким бы code
     * ни был.
     */
    checkAccessCode(request: ChannelAddress & { code: string }): Promise<void>;

    /**
     * Встать на рейд. `code` нужен, только если канал закрыт (`channel.closed`) и это не первый
     * вход на него, — то же условие, что проверяет joinChannel на сервере (см.
     * functions/src/raid.ts): бэкенд сверяет код заново и здесь, а не полагается на то, что
     * проверка выше (checkAccessCode) уже прошла, — та проверка лишь подсказка, эта — решает.
     */
    join(request: ChannelAddress & { member: MemberDraft; code?: string }): Promise<{ member: Member }>;
    updateMember(request: MemberAddress & { member: MemberDraft }): Promise<{ member: Member }>;
    /**
     * Сняться с рейда. Вместе с уходом приходит новый курс — куда корабль пошёл: канал
     * не должен терять корабли молча, и в ленте об уходе говорится его же словами.
     *
     * Курс необязателен нарочно: уйти можно и не сказав ничего — так уходили до того, как
     * курс стали спрашивать, и записи тех уходов остаются законными.
     *
     * `nextOwnerId` называет преемника — им может быть только старший, и только когда
     * на рейде остаётся кто-то ещё: спрашивать выбор у рядового или у последнего не для чего,
     * там его либо некому передать, либо решение оставить некому. Пришёл, а на рейде такого
     * уже нет — бэкенд молча передаст старшинство по прежнему правилу, тому, кто дольше всех:
     * во вкладке к этому моменту мог устареть список.
     */
    leave(request: MemberAddress & { course?: string; nextOwnerId?: string }): Promise<void>;
    /**
     * Высадить чужой корабль с рейда. Адресует запрос тот, кто высаживает, — и это должен быть
     * старший на рейде (`channel.owner`), иначе `not-senior`. Кого высаживают, идёт ссылкой
     * в теле: это содержимое запроса, а не его адрес.
     *
     * Отдельным методом, а не флагом у `leave`: уйти самому и быть высаженным — разные события
     * и для правил (одно доступно каждому, другое одному), и для ленты.
     */
    kick(request: MemberAddress & { member: MemberRef }): Promise<void>;

    sendMessage(request: MemberAddress & { message: MessageDraft }): Promise<{ message: Message }>;

    /**
     * Отправить заново то, что не ушло. Тем же `messageId`, что и у неудачной попытки, —
     * поэтому двойника не будет: повтор попадает в ту же запись, а не заводит вторую
     * (см. docs/FIREBASE.md, «Повтор без двойников»). Текст неотправленного отправитель
     * не приносит заново — он берётся из ящика (`backend/outbox.ts`) по `message.messageId`.
     */
    retryMessage(request: MemberAddress & { message: MessageRef }): Promise<{ message: Message }>;

    /**
     * Выбросить неотправленное: человек передумал. Убирает запись из ящика и из ленты
     * этой (и только этой) вкладки. `memberId` в адресе не нужен — ящик неотправленного
     * общий у канала, а не у участника внутри него.
     *
     * Границу стоит знать: у настоящего бэкенда это отказ от ожидания, а не отмена записи.
     * Отправка в офлайне уже легла в собственную очередь Firestore (кеш на диске, см.
     * config/firebase.ts), отменять записи оттуда SDK не умеет вовсе, и когда связь
     * вернётся, сообщение всё-таки уйдёт и вернётся в ленту обычным message-added. Отказаться
     * от него насовсем можно, пока связи нет; у локального бэкенда, где очереди никакой нет,
     * — всегда. Кнопки на это в интерфейсе пока и не заведено (issue #69: метод — в контракт,
     * значок в ленте — только повтору).
     */
    discardMessage(request: ChannelAddress & { message: MessageRef }): Promise<void>;

    /**
     * Догрузить ленту выше уже показанного — на один экран, а не всю переписку разом
     * (см. `ChannelSnapshot.hasMoreMessages`).
     *
     * `before` называет сообщение, выше которого читаем: само оно уже показано и в ответ
     * не попадает. `limit` необязателен — умолчание то же, что и у первой страницы
     * (MESSAGE_PAGE, `config/network.ts`); полем, а не отдельной константой здесь, потому
     * что страница может понадобиться другого размера, даже если сегодня такого зовущего нет.
     *
     * Отвечает в естественном порядке чтения — старые сверху, — том же самом, в каком лежит
     * messages: результат подставляется перед ним без переворота.
     */
    loadOlderMessages(
        request: ChannelAddress & { before: MessageRef; limit?: number }
    ): Promise<{ messages: Message[]; hasMore: boolean }>;

    /**
     * Докуда участник дочитал разговор — своими глазами. Пишет только он сам, о себе:
     * `memberId` в адресе — это тот, чьё участие правится, и вызывающий обязан быть им же,
     * иначе `firestore.rules` откажет (правило — там, а не здесь: контракт лишь передаёт вызов).
     *
     * Дело хука `hooks/useUnread`, а не каждого места, что дочитало сообщение, — придержать
     * вызовы во времени: отметка не обязана поспевать за каждой репликой, а вот записывать
     * документ на каждую подряд, пока человек сидит в канале и болтает, — дорогая привычка
     * (см. `config/network.ts`, MARK_SEEN_THROTTLE).
     *
     * `sentAt` сообщения идёт сюда вместе с его номером и не выдумывается на месте: в отметку
     * ложится метка самого сообщения, а не время, когда его прочли (`Member.lastSeen`
     * объясняет, почему по-другому нельзя). Бэкенд её и сам бы не узнал, не сходив за
     * документом, — а звать чтение ради записи, которая идёт раз в несколько секунд, незачем.
     */
    markSeen(request: MemberAddress & { message: MessageRef & { sentAt: number } }): Promise<void>;

    /**
     * Сколько в канале сообщений позже отметки. Не перебором ленты — та с #68 приходит
     * страницей, а не разговором целиком, — а отдельным счётом на сервере (`getCountFromServer`
     * по `sentAt > after`): одно чтение вместо чтения всей страницы ради длины среза.
     *
     * Счёт нарочно не разбирает, что за сообщение попалось — своё, чужое, системное:
     * разбор по автору потребовал бы второго `!=`-условия в одном запросе с диапазоном
     * по времени, а Firestore пускает не больше одного на запрос; разбор по системности —
     * либо явного поля вместо нынешнего необязательного kind, либо составного индекса,
     * которого в проекте сегодня нет. `hooks/useUnread` зовёт этот метод только тогда,
     * когда сама отправка сообщений на экране недоступна (см. его комментарий), и там
     * это не потеря: своё сообщение в такой счёт попасть не может при всём желании.
     * Другому вызывающему, для которого это не так, отвечает он тем же, приблизительно.
     */
    countUnread(request: ChannelAddress & { after: number }): Promise<{ count: number }>;

    /**
     * Подписка на всё, что происходит в канале. Возвращает функцию отписки.
     * События приходят и от чужих вкладок, и от собственных действий этой вкладки —
     * UI не должен угадывать, кто сделал изменение, чтобы применить его.
     *
     * `userId` не обязателен, но нужен для двух вещей — и, как у getChannel, `null`
     * и «не передан» здесь тоже не одно и то же. Первая вещь — узнать в исходящем
     * `message-updated`/`message-removed` свою же запись из ящика неотправленного, заведённую
     * ещё до этого вызова, — например, отправленное перед самой перезагрузкой; без реального
     * id (что `null`, что «не передан») отказ и повтор такого сообщения подпиской замечены
     * не будут (хотя в самой ленте, через getChannel, оно всё равно останется видно). Вторая —
     * сам факт входа: явный `null` значит «точно посторонний», и такому не полагается вовсе
     * ничего живого — ни участников, ни ленты, ни даже самого канала (см. firestore.rules,
     * isMember на channels/{channelId} и его коллекциях): вызов возвращает рабочую отписку,
     * но onEvent не позовёт ни разу. Не передан вовсе — все подписки заводятся как обычно,
     * это тот же «вход вызвавшему не важен», что и у getChannel; а если вызвавший вошёл,
     * но случится так, что не с этого рейда, — подписки гаснут поодиночке, каждая на своём
     * permission-denied, как и при обычном чтении (см. errorStatus, firebaseBackend.ts).
     */
    subscribe(
        request: ChannelAddress & { userId?: string | null; onEvent: (event: ChannelEvent) => void }
    ): Unsubscribe;

    /**
     * Состояние связи с бэкендом — не с каналом, а с сервером вообще. Отдельно от подписки:
     * подписки может не быть (канал ещё не открыт), а знать, есть ли связь, надо и тогда.
     * Первый вызов `onChange` — сразу с текущим состоянием, дальше — по перемене.
     */
    watchConnection(request: { onChange: (connection: Connection) => void }): Unsubscribe;
}
