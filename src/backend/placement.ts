/**
 * Чужой корабль на рейде, каким его видит расстановка: где стоит и какой ширины. Размер
 * нужен ей не меньше места — помещаются ли двое на одной линии, решают именно борта.
 */
export type Standing = Pick<Member, 'shipKind' | 'place'>;

/**
 * Корабль на линии для счёта бортами: дальность, коридор и силуэт. Не `Standing`, потому что
 * считать приходится и то, чего на рейде ещё нет, — место, которое человеку только предлагают.
 */
interface Spot {
    slot: number;
    corridor: Corridor;
    kind: ShipKind;
}

const spotOf = (ship: Standing): Spot => ({
    slot: ship.place.slot,
    corridor: ship.place.corridor,
    kind: ship.shipKind,
});

/**
 * Поле по краям рейда, % его ширины. Рейд занимает не весь кадр, а воду между полями:
 * в них коридоры, в них же разброс внутри полосы, расхождение тесной пары и вместимость линии.
 * Число одно на все четыре счёта нарочно — иначе у рейда оказалось бы четыре разных края.
 *
 * Раньше поля не было вовсе: левая полоса начиналась на нуле, правая кончалась на сотне,
 * и корабль на боковом коридоре вставал бортом ровно на обрез. В кадре это читалось не стоянкой
 * у кромки, а корпусом, которому не хватило места: рейд — это вода вокруг кораблей, а у крайних
 * её с одной стороны не оставалось совсем.
 *
 * Размер подобран замером. Пара помещается на линию, пока оба корпуса да вода между ними
 * влезают в рейд, и поле этот рейд сужает: без поля пар 1361, с полем в 3% — 1314, и до 3.5%
 * это число уже не меняется. Взят верх этой полки: дальше, с 3.75%, пары снова начинают
 * теряться. Теряются они при этом только на двух ближних линиях, где корабль и так занимает
 * половину кадра; линии с нулевой по седьмую не теряют ни одной пары ни при каком поле
 * до 4%.
 *
 * В пикселях это 42px на десктопе и 17px на телефоне — и в том, что числа разные, вся суть:
 * поле отмерено рейдом, как и всё остальное на нём, поэтому сцена на любом экране выглядит
 * одинаково. Раньше на этом месте стояли 30px в стилях, и на телефоне они съедали втрое
 * большую долю кадра, чем на десктопе.
 *
 * Поле у носа при этом отмеряется не кромкой рейда, а кромкой окна: на телефоне рейд шире
 * кадра, и всё, что за кромкой, срезается (см. `edgesFor`).
 */
export const EDGE_MARGIN = 3.5;

/** Вода между полями, % ширины рейда: всё, что кораблям отведено. */
const RAID_WIDTH = 100 - 2 * EDGE_MARGIN;

/** Поля этого корабля по краям рейда, % ширины рейда: у левой кромки и у правой. */
interface Edges {
    from: number;
    to: number;
}

/**
 * Поля у носа и у кормы.
 *
 * `beyond` — насколько рейд уходит за кромку окна с каждой стороны, % ширины рейда. На узком
 * экране рейд шире кадра (см. `--raid-overhang`), и всё, что за кромкой, кадром срезается.
 * Корме это не беда, а скорее натуральнее: корабль виден не целиком, будто кадр его
 * не вмещает. А нос срезать нельзя совсем — это главная часть силуэта, и на нём же стоит
 * бортовой номер. Поэтому поле у носа отмеряется от настоящей кромки окна и остаётся тем
 * же самым полем в `EDGE_MARGIN`, каким было, когда рейд в кадр помещался; поле у кормы
 * на вылет тратится и, когда вылет его перекрывает, сходит на нет.
 *
 * Рейд помещается в кадр целиком (`beyond` = 0) — оба поля снова по `EDGE_MARGIN`,
 * и расстановка стоит ровно там же, где стояла.
 */
const edgesFor = (facing: Side, beyond: number): Edges => {
    const bow = EDGE_MARGIN + beyond;
    const stern = Math.max(0, EDGE_MARGIN - beyond);
    return facing === 'right' ? { from: stern, to: bow } : { from: bow, to: stern };
};

/**
 * Оси коридоров, долями воды между полями. На них стоят отметки мест — точки на воде и подписи
 * занятых стоянок, — и сходятся они к горизонту по перспективе, уже в стилях. Сам корабль
 * на оси не стоит: он разбросан внутри своей полосы (CORRIDOR_BOUNDS).
 *
 * Доли не совпадают с серединами полос (те пришлись бы на 1/6, 1/2 и 5/6): оси нарочно сведены
 * к середине кадра. Разметка — про выбор, и выглядеть она должна стройно, а полоса — про
 * стоянку, и стройности от неё никто не ждёт.
 */
const CORRIDOR_SHARES: Record<Corridor, number> = { left: 0.2, center: 0.5, right: 0.8 };

/** Оси коридоров, % ширины сцены. */
const CORRIDOR_CENTERS: Record<Corridor, number> = Object.fromEntries(
    CORRIDORS.map((corridor) => [corridor, EDGE_MARGIN + CORRIDOR_SHARES[corridor] * RAID_WIDTH])
) as Record<Corridor, number>;

/**
 * Границы коридоров, % ширины сцены. Вода между полями делится на три равные полосы,
 * и полоса — это всё, что кораблю отведено: внутри неё он стоит где угодно, лишь бы весь
 * корпус влез.
 */
const CORRIDOR_BOUNDS: Record<Corridor, { from: number; to: number }> = Object.fromEntries(
    CORRIDORS.map((corridor, index) => [
        corridor,
        {
            from: EDGE_MARGIN + (index * RAID_WIDTH) / CORRIDORS.length,
            to: EDGE_MARGIN + ((index + 1) * RAID_WIDTH) / CORRIDORS.length,
        },
    ])
) as Record<Corridor, { from: number; to: number }>;

/**
 * Ближе скольких слотов друг к другу два корабля в одном коридоре стоять не любят. Не запрет,
 * а склонность, и разница тут существенная. Запретом это было раньше — и один крупный корабль
 * выключал из рейда пять дальностей разом: свою и по две в каждую сторону. На десяти линиях
 * это половина рейда, отданная одному силуэту, а человеку, выбиравшему место сам, соседняя
 * линия просто не предлагалась, хотя ничего невозможного в ней нет.
 *
 * Теперь такое место — просто худшее из годных: расстановка берёт его последним, когда
 * свободных нигде не осталось (см. preferredBerths), а человеку оно предлагается наравне
 * с прочими — он видит кадр целиком и решает сам.
 *
 * Само число прежнее и означает прежнее: сосед по своей или соседней линии того же коридора
 * отличается по дальности на девятую часть перспективы, силуэты там почти одного размера
 * и почти на одном месте, и в кадре это читается наложением. Через три линии разница видна.
 */
const MIN_SLOT_GAP = 3;

/**
 * Сколько объектов стоит на одной дальности — считая остров. Двое, и это не про тесноту,
 * а про свободу выхода: у двоих на линии всегда есть по своему борту наружу, и уходя с рейда
 * каждый идёт в свою сторону, никого не задевая. Третий встал бы между ними и оказался заперт
 * с обеих сторон — ему пришлось бы проходить сквозь соседа.
 *
 * Остров тут такой же сосед, только неподвижный: он держит левый коридор дальних слотов,
 * и корабль там остаётся на линии один.
 *
 * Правило это про топологию, а fitsAlongside — про геометрию, и одно другого не заменяет: двое
 * помещаются на линию, только если и место есть, и борта расходятся.
 */
const SLOT_CAPACITY = 2;

/**
 * Сколько воды остаётся между бортами, долей корпуса. Меркой служит сам корабль, а не проценты
 * кадра: на дальней линии те же три процента — это половина корпуса, а на ближней едва
 * ли не швартовный конец. Седьмой части хватает, чтобы борта читались раздельно и на глаз
 * было видно, что это двое, а не один длинный силуэт.
 */
const BOARD_GAP = 0.15;

/**
 * Левый коридор упирается в остров: тот занимает левую часть кадра, а его берег стоит
 * примерно на дальности слота 0.7. Корабль на дальних слотах там либо оказывается прямо
 * на суше (замер: на слоте 0 под его ватерлинией земля), либо, будучи мелким и далёким,
 * рисуется поверх более близкого острова и читается выброшенным на берег.
 *
 * Поэтому левый коридор закрыт для дальних слотов. Начиная с ISLAND_FREE_SLOT корабль
 * заметно ближе острова и крупнее — перекрытие читается как «прошёл перед берегом»,
 * а это как раз то, что нужно. Сам порог живёт в types/channel.ts: про остров знает
 * не только расстановка, но и сцена, когда решает, в какую сторону кораблю уходить.
 */
const ISLAND_CORRIDOR: Corridor = 'left';

/**
 * Сколько слотов от «своей» дальности рассматриваем как равноценные. Не правило, а склонность:
 * из этого набора слот берётся случайно, поэтому крупный корабль встаёт где-то в дальней
 * половине рейда, а не строго на последнем слоте, и строй не выстраивается по росту.
 */
const SLOT_CHOICE = 4;

/**
 * Из скольких самых свободных мест выбираем в итоге. Рейд занимается как автобус: сначала
 * места подальше от всех, и только когда таких не осталось — те, что ближе к соседям.
 * Не одно самое дальнее, а несколько лучших: иначе расстановка стала бы алгоритмом,
 * который на одних и тех же кораблях каждый раз выдаёт одну и ту же картинку.
 */
const SPOT_CHOICE = 3;

/** Наибольшее расстояние между осями коридоров, % ширины сцены: от левого до правого. */
const CORRIDOR_SPAN = CORRIDOR_CENTERS.right - CORRIDOR_CENTERS.left;

/**
 * Куда тянет корабль этого размера: самый длинный — к дальнему краю рейда, самый мелкий —
 * к переднему плану. Так сцена уравновешивается сама: крупные не загораживают собой весь кадр,
 * а катера не теряются у горизонта точками.
 */
const preferredSlot = (kind: ShipKind): number => {
    const lengths = SHIP_KINDS.map((item) => SHIP_SPECS[item].length);
    const shortest = Math.min(...lengths);
    const longest = Math.max(...lengths);
    const size = (SHIP_SPECS[kind].length - shortest) / (longest - shortest);
    return Math.round((1 - size) * (SLOT_COUNT - 1));
};

const allSlots = (): number[] => [...new Array<number>(SLOT_COUNT)].map((_, index) => index);

/** Полширины корпуса на этой дальности, % ширины сцены. */
const hullHalf = (slot: number, kind: ShipKind): number => shipWidthPercent(slot, kind) / 2;

/**
 * Разброс: доля от 0 до 1 по участнику и его месту. Не случайность, а хеш, и это важно:
 * картинка обязана совпасть во всех вкладках до пикселя, а сходятся вкладки только на том,
 * что пришло с бэкенда. Кинь тут `Math.random`, и каждая вкладка расставила бы флот по-своему.
 *
 * FNV-1a — самая короткая перемешивающая функция, какая тут годится: у похожих строк
 * (а `memberId` у всех на одно лицо) числа выходят непохожими, и большего от неё не нужно.
 * В ключ входит и место: перешёл корабль на другую стоянку — встал на ней по-новому,
 * а не повторил прежний сдвиг.
 */
/* eslint-disable no-bitwise -- хеш только из побитовых действий и состоит: `^` перемешивает
   очередную букву, `>>>` снимает знак с итога. Другой записи у FNV-1a нет. */
const scatterShare = (seed: string): number => {
    let hash = 0x811c9dc5;
    for (let index = 0; index < seed.length; index += 1) {
        hash = Math.imul(hash ^ seed.charCodeAt(index), 0x01000193);
    }
    return (hash >>> 0) / 2 ** 32;
};
/* eslint-enable no-bitwise */

/** Не дать корпусу выйти в поле: середина корабля не ближе полуширины к кромке воды. */
const inFrame = (at: number, half: number, edges: Edges): number =>
    Math.min(Math.max(at, edges.from + half), 100 - edges.to - half);

/**
 * Где корабль стоит на своём месте, пока ему никто не мешает, % ширины сцены — серединой
 * корпуса. Внутри своей полосы он стоит где угодно, лишь бы весь корпус в неё влез: меряются
 * габариты, а не середина, — и оттого мелкому воли больше, чем крупному, как и должно быть.
 *
 * Не влез по ширине — крупный силуэт на ближней линии шире трети кадра — встаёт на ось
 * своего коридора, ту самую, на которой горит отметка места. Разброса ему не достаётся вовсе,
 * и это честно: разбрасывать нечего, вода вся под ним.
 */
const restingAt = (spot: Spot, seed: string, edges: Edges): number => {
    const half = hullHalf(spot.slot, spot.kind);
    const { from, to } = CORRIDOR_BOUNDS[spot.corridor];
    const [nearest, farthest] = [from + half, to - half];
    const at =
        nearest > farthest ? CORRIDOR_CENTERS[spot.corridor] : nearest + scatterShare(seed) * (farthest - nearest);
    return inFrame(at, half, edges);
};

/** Ключ разброса: участник и его место. Больше в нём ничего и нет — см. scatterShare. */
const scatterSeed = (ship: Standing & Pick<Member, 'memberId'>): string =>
    `${ship.memberId}:${ship.place.slot}:${ship.place.corridor}`;

/**
 * Сколько воды нужно этим двоим между серединами корпусов: полусумма ширин да немного воды
 * сверх того. Та же мерка, что и на глаз: борта не должны налезать друг на друга, и между
 * ними должно быть видно, что это двое, а не один длинный силуэт.
 */
const needApart = (oneHalf: number, otherHalf: number): number => (oneHalf + otherHalf) * (1 + BOARD_GAP);

/** Сколько кораблю осталось воды в эту сторону: до кромки рейда, и ни шагом дальше. */
const roomAside = (at: number, half: number, away: number, edges: Edges): number =>
    away > 0 ? 100 - edges.to - half - at : at - half - edges.from;

/**
 * Помещаются ли эти двое борт о борт.
 *
 * Мерка тут одна — кадр, и она же одна на все экраны: вся геометрия рейда — проценты ширины
 * сцены, ни одного пикселя. Сузился экран — корабль в треть кадра остался кораблём в треть
 * кадра, и пара, которую пустили на линию на широком окне, разойдётся и на узком. Расходятся корабли не внутри своих полос: тесному соседу уступают
 * и в чужую полосу, лишь бы разойтись бортами, — а вот в поле по краям не уступают, иначе
 * крайний встал бы бортом на обрез кадра. Значит, двое помещаются ровно тогда, когда
 * оба корпуса да вода между ними умещаются в рейд, то есть в кадр без полей.
 *
 * Правило это и расхождение (fleetLefts) — две стороны одного счёта, и сходятся они
 * не случайно: если борта в кадр умещаются, то, разведя корабли до самых кромок, сцена
 * всегда получит нужную воду между ними. Поэтому расстановка и не пускает на линию пару,
 * которую сцене потом не развести.
 *
 * Раньше на месте этого счёта стояли два числа на глазок, а потом — ширина коридора:
 * корабли разводились только внутри своих полос, и крупному отказывали там, где ему
 * не хватало пары процентов кадра, а взять их было откуда — из соседней полосы, куда
 * теперь и уступают.
 *
 * Вместимость линии при этом осталась на месте (SLOT_CAPACITY): размер решает, помещаются ли
 * двое, а не сколько их. Это разные вопросы — и когда счёт бортами заменил собой и вместимость
 * тоже, на дальних линиях стало по три объекта, остров да двое, и средний оказывался заперт
 * между ними (замер: 3.7% расстановок по пять кораблей).
 */
const fitsAlongside = (slot: number, kind: ShipKind, other: Standing): boolean => {
    const half = hullHalf(slot, kind);
    const otherHalf = hullHalf(other.place.slot, other.shipKind);
    return needApart(half, otherHalf) + half + otherHalf <= RAID_WIDTH;
};

/**
 * Коридоры, свободные для этого слота, в случайном порядке. Здесь только запреты — то, куда
 * встать нельзя вовсе, а не то, куда не хочется.
 *
 * Сначала линия целиком: если на ней уже стоят двое (или один да остров), она занята — сколько
 * бы воды между ними ни оставалось; если стоящему на ней не разойтись с новичком бортами, занята
 * тем более, и коридор тут ни при чём — расходятся они по всему кадру. Дальше по коридорам:
 * мимо идёт коридор соседа по этой же линии — там место попросту занято, точка на воде у них
 * была бы одна на двоих, — и остров, который держит свой коридор на дальних слотах: там суша.
 *
 * А вот теснота по дальности (MIN_SLOT_GAP) сюда не входит: соседняя линия того же коридора
 * не запрещена, она просто хуже прочих, и разбирается это при выборе (preferredBerths).
 *
 * Наружу торчит ради проверок: это сердце всех запретов рейда, и проверять его через
 * расстановку значило бы смотреть на ответ, в который случай подмешал ещё три правила.
 * Порядок в ответе случайный — сравнивать его надо составом, а не списком.
 */
export const freeCorridors = (slot: number, kind: ShipKind, taken: Standing[]): Corridor[] => {
    const island = slot < ISLAND_FREE_SLOT;
    const here = taken.filter((other) => other.place.slot === slot);
    if (here.length + (island ? 1 : 0) >= SLOT_CAPACITY) {
        return [];
    }
    if (here.some((other) => !fitsAlongside(slot, kind, other))) {
        return [];
    }
    const blocked = new Set(here.map((other) => other.place.corridor));
    if (island) {
        blocked.add(ISLAND_CORRIDOR);
    }
    return shuffled(CORRIDORS).filter((corridor) => !blocked.has(corridor));
};

/**
 * Тесно ли тут по дальности: стоит ли в этом же коридоре сосед ближе MIN_SLOT_GAP. Место
 * от этого не перестаёт быть годным — оно становится худшим из годных.
 */
const crowded = (slot: number, corridor: Corridor, taken: Standing[]): boolean =>
    taken.some((other) => other.place.corridor === corridor && Math.abs(other.place.slot - slot) < MIN_SLOT_GAP);

/**
 * Насколько место далеко от чужого корабля. Обе разницы приведены к долям своего размаха
 * и сложены: 0 — тот же слот и тот же коридор, 2 — противоположный угол рейда. Дальность
 * и ширина считаются наравне, потому что в кадре они и выглядят наравне: сосед через
 * два слота разнесён с тобой примерно так же, как сосед в другом коридоре.
 */
const distanceTo = (slot: number, corridor: Corridor, other: ShipPlacement): number =>
    Math.abs(slot - other.slot) / (SLOT_COUNT - 1) +
    Math.abs(CORRIDOR_CENTERS[corridor] - CORRIDOR_CENTERS[other.corridor]) / CORRIDOR_SPAN;

/** Насколько место свободно: расстояние до ближайшего соседа. Пустой рейд — свободно всё. */
const loneliness = (slot: number, corridor: Corridor, taken: Standing[]): number =>
    taken.length === 0 ? Infinity : Math.min(...taken.map((other) => distanceTo(slot, corridor, other.place)));

/**
 * Место на рейде целиком: дальность, коридор и точка в кадре. Точка — ось коридора: разметка
 * на воде стоит стройно, потому что показывает выбор, а не корпус. Сам корабль встанет
 * не строго на неё, а где-то в своей полосе (см. restingAt) — это положение внутри места,
 * а не другое место.
 */
export const berthAt = (slot: number, corridor: Corridor): Berth => ({
    slot,
    corridor,
    left: CORRIDOR_CENTERS[corridor],
});

/**
 * С какой стороны корабль заходит на рейд, когда курс ему не назначили. Тем, кто заходит
 * из формы, курс назначен всегда, и сторона считается от него (см. placeAt); сюда попадает
 * только состав, заведённый без человека, — демо-канал.
 *
 * На дальних слотах выбора нет: с той стороны остров, и корабль прошёл бы прямо по нему.
 *
 * Дальше решает сам коридор: в левый заходят слева, в правый — справа. Заходят носом вперёд,
 * значит вставший корабль смотрит внутрь кадра, а не наружу, — и это правило, а не склонность.
 * Кораблю, приткнувшемуся к левому краю кадра носом влево, смотреть не на что: за носом
 * у него обрез, а весь рейд за кормой.
 *
 * Выбор остаётся только у центрального коридора, и там сторона не честная монетка,
 * а противовес: чем больше кораблей уже пришло с одной стороны, тем вероятнее следующий
 * придёт с другой. Иначе рейд заполнялся бы в основном справа — дальние слоты вынужденно
 * правые, а крупные корабли тянутся именно туда.
 *
 * Перевес считается по квадратам, а не напрямую: перекос надо не смягчать, а выправлять.
 * Единица в каждой скобке — обычное сглаживание: на пустом рейде выходит ровно половина,
 * и правая сторона не запрещена никогда.
 */
const enterSide = (berth: Berth, taken: Standing[]): Side => {
    if (berth.slot < ISLAND_FREE_SLOT) {
        return otherSide(ISLAND_SIDE);
    }
    if (berth.corridor !== 'center') {
        return berth.corridor;
    }
    const fromLeft = (taken.filter((other) => other.place.enterFrom === 'left').length + 1) ** 2;
    const fromRight = (taken.filter((other) => other.place.enterFrom === 'right').length + 1) ** 2;
    return Math.random() < fromRight / (fromLeft + fromRight) ? 'left' : 'right';
};

/**
 * Место со стороной захода и курсом: откуда корабль придёт и куда будет смотреть носом.
 * Само место к этому моменту уже выбрано — человеком в форме или расстановкой.
 *
 * Ведёт тут курс, а не сторона: его человек выбирает в форме, и корабль обязан встать
 * именно так. Заход из курса и следует — заходят носом вперёд, то есть с противоположного
 * борта. Курса не назвали (демо-состав) — тогда наоборот, курс достаётся от стороны захода
 * и её противовеса.
 *
 * Дальние слоты — исключение: слева остров, и подойти оттуда нельзя ни при каком курсе.
 * Корабль с курсом на остров подходит справа задним ходом — это дороже и медленнее, но это
 * единственный способ выполнить приказ, не пройдя по суше.
 */
const placeAt = (berth: Berth, taken: Standing[], course?: Side): ShipPlacement => {
    const facing = course ?? otherSide(enterSide(berth, taken));
    const enterFrom = berth.slot < ISLAND_FREE_SLOT ? otherSide(ISLAND_SIDE) : otherSide(facing);
    return { ...berth, facing, enterFrom };
};

/**
 * Все свободные места рейда — то, что показывается овалами на воде. Предпочтений по размеру
 * тут нет: куда встать, человек решает сам, и предлагать ему половину рейда только потому,
 * что у него крупный корабль, незачем. А вот сам размер важен — от него зависит, куда этот
 * корабль вообще влезет, и, выбрав в форме другой силуэт, человек видит, как часть точек
 * на воде пропадает или появляется.
 *
 * Тесноты по дальности тут тоже нет: соседняя линия занятого коридора предлагается наравне
 * с прочими. Человек смотрит на весь кадр разом и видит, к кому встаёт, — решать за него,
 * что рядом с соседом ему не нравится, не нужно. Это разница между «нельзя» и «не хочется»:
 * первое обязано быть видно на воде, второе — забота расстановки, а не выбирающего.
 */
export const freeBerths = (kind: ShipKind, taken: Standing[]): Berth[] =>
    allSlots().flatMap((slot) => freeCorridors(slot, kind, taken).map((corridor) => berthAt(slot, corridor)));

/** Свободно ли это место для такого корабля. */
export const isBerthFree = (berth: Berth, kind: ShipKind, taken: Standing[]): boolean =>
    freeCorridors(berth.slot, kind, taken).includes(berth.corridor);

/** Корабль в кадре, каким его видит расхождение: где стоит, какой ширины и с каких пор. */
export type Anchored = Standing & Pick<Member, 'memberId' | 'joinedAt'>;

/**
 * Где корабль стоит сам по себе, % ширины рейда — серединой корпуса. Это его собственная точка
 * на рейде: разброс внутри полосы и ничего больше, соседи тут не в счёт.
 *
 * `beyond` — насколько рейд уходит за кромку кадра с каждой стороны (см. `edgesFor`).
 */
export const restingLeft = (ship: Anchored, beyond = 0): number =>
    restingAt(spotOf(ship), scatterSeed(ship), edgesFor(ship.place.facing, beyond));

/**
 * Разброс со знаком: −1…1. Тот же хеш, что и у разброса поперёк, только развёрнутый вокруг нуля —
 * отходить от своей линии корабль может в обе стороны, а не только к наблюдателю.
 */
const scatterSpread = (seed: string): number => scatterShare(seed) * 2 - 1;

/**
 * Насколько корабль отходит от своей линии по дальности, в долях расстояния между линиями.
 *
 * Линия — это стоянка, а не швартовная бочка: корабль стоит на ней, а не привязан к ней носом.
 * Пятая часть промежутка — предел, при котором строй читается живым, но линии ещё различимы;
 * больше — и рейд перестаёт выглядеть размеченным.
 *
 * Соседям это не мешает: на одной линии стоят самое большее двое, и разведены они бортами
 * (fleetLefts), а в своём коридоре ближайший сосед не ближе трёх линий (MIN_SLOT_GAP). Дальше
 * пятой части промежутка не отходит никто, значит и порядок «ближний перекрывает дальнего»
 * остаётся прежним: между линиями всё ещё больше половины промежутка.
 */
const DEPTH_SCATTER = 0.2;

/**
 * Наибольший разворот корпуса на стоянке, градусы.
 *
 * Стоящий флот смотрит строго вдоль кадра, и оттого читается построенным, а не стоящим
 * на якорях: настоящие корабли на рейде разворачивает ветром и течением, и ровно в линию
 * они не встают никогда. Полтора градуса — та мера, при которой это видно как жизнь, а не как
 * ошибка отрисовки: корпус перестаёт быть параллельным соседнему, но крена ещё не читается.
 *
 * Разворот здесь — поворот в плоскости кадра, а не сжатие силуэта. По-честному повёрнутый
 * к наблюдателю корпус укоротился бы, но силуэт у нас плоский, и сжатый борт читается
 * не как «корабль повернулся», а как «корабль стал короче».
 */
const YAW_DEGREES = 1.5;

/**
 * Насколько корабль отошёл от своей линии, в слотах: минус — дальше в море, плюс — ближе
 * к наблюдателю. Считается тем же хешем, что и разброс поперёк, но по своему ключу: разойдись
 * они — и корабль, отошедший вправо, всегда отходил бы ещё и вперёд.
 *
 * Концы рейда не выпускают: дальше нулевой линии корабль встал бы на горизонт, ближе
 * последней — ушёл бы под нижнюю кромку кадра.
 */
export const restingDrift = (ship: Anchored): number => {
    const drift = scatterSpread(`${scatterSeed(ship)}:drift`) * DEPTH_SCATTER;
    const slot = ship.place.slot;
    return Math.min(Math.max(slot + drift, 0), SLOT_COUNT - 1) - slot;
};

/** Насколько корпус развёрнут на стоянке, градусы. Знак — в какую сторону, см. YAW_DEGREES. */
export const restingYaw = (ship: Anchored): number => scatterSpread(`${scatterSeed(ship)}:yaw`) * YAW_DEGREES;

/**
 * Где корабли стоят в кадре, % ширины сцены — серединой корпуса, по участникам. Разброс
 * да расхождение с тесным соседом, и всё это одним счётом: сцене остаётся поставить корабль
 * туда, где ему тут насчитали.
 *
 * Это единственное, что рисуется не по сохранённому месту. Место остаётся тем, куда корабль
 * поставили, — а положение в кадре считает сцена. Хранить тут нечего: из одного и того же
 * состава всегда выходит одна и та же картинка, на любом экране и в любой вкладке, потому
 * что разброс идёт от хеша, а не от случая, и всё до единого числа тут — проценты кадра.
 *
 * Расхождение — резинка поверх разброса. Считается по парам на линии: больше двоих на неё
 * не встают, так что пара — это всё, что бывает. Первым уступает тот, кто мельче: ему и ходу
 * меньше, и в кадре это читается правильно — катер отошёл от корабля, а не корабль от катера.
 * Не хватило его хода — остаток добирает крупный. Уступать можно и в чужую полосу, а вот
 * в поле по краям нельзя: рейд кончается там, где начинается поле (см. edgesFor). Дальше кромки
 * и не понадобится — пару, которой не разойтись в рейде, расстановка на линию не пустит
 * (см. fitsAlongside).
 *
 * `beyond` — насколько рейд уходит за кромку кадра с каждой стороны: от него зависят поля,
 * и только они. Ни разброс, ни расхождение, ни то, кто кому уступает, от ширины окна
 * не меняются — иначе флот на телефоне стоял бы не так, как на десктопе.
 *
 * Держится всё это, как на резинке: ушёл сосед — и корабль вернулся на свою точку, никуда
 * при этом не переезжая, потому что место у него всё это время было своё.
 *
 * Считать сцене приходится не состав канала, а кадр: снявшийся с рейда корабль виден ещё
 * полминуты, и всё это время он занимает своё место — сосед, отошедший от него, обязан стоять
 * отжатым, а не идти обратно ему под корпус. Отсюда и `leaving`: это те, кто уже в пути.
 * Втроём на линии сходятся только из-за них — уходящий ещё в кадре, а его место уже занял
 * новичок, — и тогда счёт уступает уходящий: этим двоим стоять тут и дальше, а он всё равно
 * сейчас уйдёт. Разводить троих взаправду нечем: воды на линии на троих может и не быть,
 * а правило, которое живёт полминуты в году, не стоит того, чтобы ошибаться в нём молча.
 */
export const fleetLefts = (
    fleet: Anchored[],
    leaving: ReadonlySet<string> = new Set(),
    beyond = 0
): Record<string, number> => {
    const left: Record<string, number> = {};
    for (const ship of fleet) {
        left[ship.memberId] = restingLeft(ship, beyond);
    }
    for (const slot of new Set(fleet.map((ship) => ship.place.slot))) {
        const line = fleet.filter((ship) => ship.place.slot === slot);
        // Мельче — уступает первым; при равных силуэтах уступает тот, кто встал раньше:
        // это его резинку натянули, ему и отпускать.
        const here = (line.length > 2 ? line.filter((ship) => !leaving.has(ship.memberId)) : line).sort(
            (one, other) =>
                shipWidthPercent(one.place.slot, one.shipKind) - shipWidthPercent(other.place.slot, other.shipKind) ||
                one.joinedAt - other.joinedAt
        );
        if (here.length === 2) {
            const [small, big] = here;
            const smallHalf = hullHalf(small.place.slot, small.shipKind);
            const bigHalf = hullHalf(big.place.slot, big.shipKind);
            const short = needApart(smallHalf, bigHalf) - Math.abs(left[small.memberId] - left[big.memberId]);
            if (short > 0) {
                // Отходит каждый от соседа: кто стоит правее, тот и вправо. Встали ровно друг
                // на друга — расходятся хоть как-нибудь, лишь бы в разные стороны.
                const away = Math.sign(left[small.memberId] - left[big.memberId]) || 1;
                const bySmall = Math.min(
                    short,
                    roomAside(left[small.memberId], smallHalf, away, edgesFor(small.place.facing, beyond))
                );
                const byBig = Math.min(
                    short - bySmall,
                    roomAside(left[big.memberId], bigHalf, -away, edgesFor(big.place.facing, beyond))
                );
                left[small.memberId] += away * bySmall;
                left[big.memberId] -= away * byBig;
            }
        }
    }
    return left;
};

/**
 * Куда этот корабль может встать сам. В отличие от freeBerths — с оглядкой на дальность:
 * сначала отбираются слоты, ближайшие к «своей» части рейда, а потом раскладываются
 * по свободным коридорам.
 *
 * Теснота отсекается до всего остального, и отсекается начисто: пока на рейде есть хоть одно
 * место без близкого соседа по коридору, тесные не рассматриваются вовсе. Ступенькой, а не
 * прибавкой к счёту, — иначе крупный корабль, которого тянет к дальнему краю, выбирал бы
 * тесноту в «своей» части рейда вместо простора в чужой, и получалась бы та же стопка силуэтов
 * на соседних линиях, от которой всё и затевалось. Не осталось свободных — тесные снова в деле:
 * встать рядом можно, просто это последнее, что берётся.
 *
 * Наружу торчит ради проверок: тут собраны все склонности расстановки — размер, теснота,
 * простор, — и спрашивать про них `suggestBerth` значило бы выяснять, чем кончил случай,
 * вместо того чтобы смотреть, из чего он выбирал. Порядок в ответе случайный: сравнивать
 * его надо составом, а не списком.
 */
export const preferredBerths = (kind: ShipKind, taken: Standing[]): Berth[] => {
    const wanted = preferredSlot(kind);
    const free = allSlots().flatMap((slot) =>
        freeCorridors(slot, kind, taken).map((corridor) => berthAt(slot, corridor))
    );
    const roomy = free.filter((berth) => !crowded(berth.slot, berth.corridor, taken));
    const choice = roomy.length > 0 ? roomy : free;
    const slots = new Set(
        [...new Set(choice.map((berth) => berth.slot))]
            .sort((a, b) => Math.abs(a - wanted) - Math.abs(b - wanted))
            .slice(0, SLOT_CHOICE)
    );
    return choice.filter((berth) => slots.has(berth.slot));
};

/**
 * Место для корабля — как место в автобусе: сперва подальше от всех, и только когда таких
 * не осталось, поближе к соседям. Считается это одинаково для обоих случаев: свободные места
 * сортируются по расстоянию до ближайшего соседа, и выбор идёт из нескольких самых свободных.
 *
 * Случайность нужна: без неё расстановка превратилась бы в алгоритм, который на одном
 * и том же составе каждый раз рисует одну и ту же картинку.
 *
 * Наружу это нужно потому, что человек, ничего не трогавший в форме, тоже встаёт «сам»:
 * форма показывает ему выбранное место заранее, и брать его она обязана здесь. Иначе выходит
 * два разных случая на один вопрос — форма ставит равновероятно из всех свободных, а правила
 * (простор, размер, теснота) остаются лежать в расстановке и не работают ни для кого, кроме
 * демо-канала.
 */
export const suggestBerth = (kind: ShipKind, taken: Standing[]): Berth | null => {
    const berths = preferredBerths(kind, taken);
    if (berths.length === 0) {
        return null;
    }
    // Перемешиваем до сортировки: сортировка устойчива, поэтому одинаково свободные места
    // сохранят случайный порядок. Без этого на пустом рейде, где свободно всё, в набор
    // попадали бы три коридора одного и того же слота — и первый корабль всегда вставал бы
    // на одно и то же место.
    const roomiest = shuffled(berths)
        .sort((a, b) => loneliness(b.slot, b.corridor, taken) - loneliness(a.slot, a.corridor, taken))
        .slice(0, SPOT_CHOICE);
    return pick(roomiest);
};

/**
 * Ставит корабль на рейде. Место человек выбирает сам, но полагаться на этот выбор нельзя:
 * пока он раздумывал, туда мог встать кто-то другой, — и тогда корабль встаёт на случайное
 * свободное, как если бы места не выбирали вовсе.
 *
 * Возвращает null, если свободных мест нет: при пяти участниках на десять слотов это
 * невозможно, но проверка дешевле, чем разбирательство, если однажды станет возможно.
 */
export const placeShip = (kind: ShipKind, taken: Standing[], wanted?: Berth, course?: Side): ShipPlacement | null => {
    const berth = wanted && isBerthFree(wanted, kind, taken) ? wanted : suggestBerth(kind, taken);
    return berth && placeAt(berth, taken, course);
};
