import { expect } from '@playwright/test';

import {
    createChannel,
    join,
    newSkewedTab,
    newTab,
    openChannel,
    openShipForm,
    sceneReady,
    signIn,
    takes,
    test,
} from '@tests-firebase/helpers';

/**
 * Рассинхрон часов вкладки со «сервером» — issue #230. Жалоба: обновляешь страницу — корабль
 * соседа, только что тронувшийся с места, уже стоит на новом. Причина — не в самой доигровке
 * (`SeaScene.tsx`, `if (ready && seenIds.current === null)`), она сравнивает то, что записано,
 * с тем, что показывают часы; причина в том, чьи это часы. `manoeuvre.startedAt` ставят настоящие
 * часы Cloud Function (`functions/src/raid.ts`), а сравнивает их вкладка своими, ничем
 * с сервером не сверенными, — спешат они хоть на секунду-другую, и остаток короткого хода
 * съедается раньше срока.
 *
 * Местный набор (`tests/scene.spec.ts`) этого не ловит и не может: там «сервер» — localStorage
 * той же самой вкладки, и часам расходиться не с чем (см. коммит GH-78/#230 этой же ветки).
 * Здесь — настоящий Firestore за эмулятором на той же машине, что и браузер, так что рассинхрона
 * тоже не возникло бы само по себе. Он заведён нарочно: `newSkewedTab` до всякого кода вкладки
 * подкручивает её `Date.now()` вперёд на `CLOCK_SKEW_MS` — этого более чем достаточно, чтобы
 * без поправки (`clockOffsetMs`, `backend/clock.ts`) остаток любого хода из этого набора
 * казался таким вкладке уже прошедшим в тот же миг, когда сосед только тронулся.
 *
 * Заодно эта же проверка ловит и другую причину той же жалобы, найденную по пути: `draftToCall`
 * в `firebaseBackend.ts` отправлял на сервер черновик участника без поля `manoeuvre` вовсе —
 * оценку хода, которую считает вкладка (`manoeuvreOf` в `App.tsx`), обрубало ещё до вызова
 * функции, и `updateMember`/`joinChannel` (`functions/src/raid.ts`) просто нечего было
 * записывать. Местный набор этого тоже не ловил: `localBackend.ts` черновик на сервер
 * не сериализует, менять в нём попросту нечего.
 */

/**
 * 30 секунд — заведомо больше самого длинного хода в кадре на этой скорости времени
 * (60 реальных секунд, делённые на TIME_SCALE=10, — 6 секунд экранного времени, см.
 * SAIL_TIMEOUT). Без поправки на сдвиг такого хватит съесть остаток какого угодно манёвра
 * из этого набора мгновенно — ровно то поведение, которое и описывает жалоба.
 */
const CLOCK_SKEW_MS = 30_000;

test('доигровка чужого манёвра после перезагрузки переживает спешащие часы вкладки', async ({ browser }) => {
    // Долгого тут — два входа (WRITE_TIMEOUT + SAIL_TIMEOUT каждый) и полный манёвр соседа
    // через весь рейд, а следом перезагрузка и повторная доигровка. Не сравнение до/после
    // фикса (регресс, который правился бы этой проверкой, тут негде выключить), а прямая
    // проверка того, что сегодняшний код переживает сдвиг, которого раньше не измерял вовсе.
    takes(70);

    const slug = `clock-skew-${Date.now()}`;

    // Своя вкладка — та, что спешит. Часы сдвинуты заранее, до первого же захода: и запись
    // о собственном входе, и последующая перезагрузка идут уже по «быстрым» часам, как и было
    // бы у настоящего человека с неверно идущими системными часами.
    const mine = await newSkewedTab(browser, CLOCK_SKEW_MS);
    await signIn(mine, `clock-uid-mine-${Date.now()}`, 'Экипаж А');
    await createChannel(mine, 'Сверка часов', slug);
    // Мелкий и быстрый — чтобы у соседа ниже осталось побольше моря для самого долгого хода,
    // какой на рейде вообще бывает (см. выбор его силуэта и берегов ниже).
    await mine.getByText('Пограничный сторожевой катер', { exact: true }).click();
    await mine.locator('[data-berth="5-center"]').click();
    await join(mine, 'Альбатрос', '001');

    // Сосед — с обычными, ничем не сдвинутыми часами: он и распоряжается манёвром, а Cloud
    // Function пишет startedAt по своим часам, не по его и не по чужим.
    const theirs = await newTab(browser);
    await signIn(theirs, `clock-uid-theirs-${Date.now()}`, 'Экипаж Б');
    await openChannel(theirs, slug);
    // Гостя, в отличие от создателя канала, встречает закрытая форма — сперва её нужно открыть,
    // и только потом на ней появляются свободные места (см. join в tests-firebase/helpers.ts).
    await theirs.getByRole('button', { name: 'Встать на рейд' }).click();
    await expect(theirs.getByPlaceholder('Гром'), 'форма постановки в строй не открылась').toBeVisible();
    // Крупный и медленный, с самой дальней линии на самую ближнюю — самый долгий ход из
    // возможных на рейде: без запаса реальное время самой перезагрузки (настоящая сеть, а не
    // localStorage местного набора) съело бы его раньше, чем вкладка успела бы обновиться,
    // и проверка не отличала бы «поправка сработала» от «просто не успели заметить».
    await theirs.getByText('Малый ракетный корабль', { exact: true }).click();
    await theirs.locator('[data-berth="9-center"]').click();
    await join(theirs, 'Вымпел', '222');

    // Сосед трогается с места — полный ход через весь рейд, с дальней линии на ближнюю
    // (крайние места: SLOT_COUNT=10, линии — от 0 до 9).
    await openShipForm(theirs);
    await theirs.locator('[data-berth="0-center"]').click();
    await theirs.getByRole('button', { name: 'Готово' }).click();
    await expect(theirs.locator('[data-motion]'), 'сосед не тронулся с места').toHaveCount(1);

    // Перезагружаем ровно ту вкладку, чьи часы спешат, — сразу же, как только ход соседа стал
    // виден у него самого.
    await mine.reload({ waitUntil: 'domcontentloaded' });
    await sceneReady(mine);

    const lane = mine.locator('[data-motion]');
    await expect(
        lane,
        'после перезагрузки спешащей вкладки чужой корабль оказался сразу на новом месте — ' +
            'сдвиг часов съел остаток хода (issue #230)'
    ).toHaveCount(1);
    // Доигрывается манёвр с начала (уход со старого места), а не с конца.
    await expect(lane, 'манёвр доигрывается не с того колена').toHaveAttribute('data-motion', 'leaving');
    const delay = await lane.evaluate((node) => Number.parseFloat(getComputedStyle(node).transitionDelay));
    expect(delay, 'ход начался с начала, а не с середины').toBeLessThan(0);
});
