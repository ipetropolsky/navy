/**
 * Сдвиг часов этой вкладки относительно сервера — issue #230.
 *
 * Доигровка манёвра при перезагрузке (`SeaScene.tsx`, `manoeuvre.startedAt`) сравнивает
 * серверную метку старта хода с `Date.now()` читающей вкладки. `startedAt` ставят настоящие
 * часы Cloud Function (`functions/src/raid.ts`); часы вкладки с ними никто не сверяет. Спешат
 * они хоть на несколько секунд (некалиброванный NTP, проспавший ноутбук, VM) — остаток
 * короткого хода съедается раньше срока, и человек видит уже остановившийся корабль соседа,
 * который на самом деле ещё идёт.
 *
 * Лечится не подгонкой часов вкладки (нечем, да и не нужно — другой код от них не зависит),
 * а поправкой прямо в месте сравнения: `Date.now() + offsetMs` вместо голого `Date.now()`.
 * Сам сдвиг вкладка меряет по каждой свежей серверной метке, что приходит с документом
 * участника (см. `serverAt` в `functions/src/raid.ts`, `MemberDoc`): чем ближе к разнице между
 * тем, что показали часы сервера, и тем, что в тот же миг показали часы вкладки.
 */

/**
 * Оценка сдвига по одной серверной метке. `serverAtMillis` — во что резолвится `serverAt`
 * документа (мс эпохи); `null`, если запись ещё не подтверждена сервером (pending write —
 * `serverTimestamp()` до подтверждения читается как `null`, см. docs/FIREBASE.md, «Формы
 * документов») — сверяться тогда не с чем, и прежняя оценка остаётся в силе. `receivedAt` —
 * `Date.now()` этой же вкладки в миг получения снимка.
 *
 * Оценка разовая, а не среднее по многим меткам: часы или врут на постоянную величину
 * (обычный случай — рассинхрон NTP), или не врут вовсе, и усложнять расчёт сглаживанием
 * не за чем — на постоянном сдвиге оно ничего не улучшит, а на переменном (спящий ноутбук
 * проснулся с другими часами) только помешает угнаться за новым значением.
 */
export const clockOffset = (serverAtMillis: number | null, receivedAt: number): number | null =>
    serverAtMillis === null ? null : serverAtMillis - receivedAt;
