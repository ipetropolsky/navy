import { describe, expect, it } from 'vitest';

import { clockOffset } from '@/backend/clock';

/**
 * Чистый расчёт сдвига часов — и только он: сама подписка (кто зовёт эту функцию, по каким
 * снимкам и как хранит текущую оценку) — эффектная обвязка внутри firebaseBackend.ts, её место
 * в браузерном прогоне, как и у остальных эффектных хуков этого проекта (см. hooks/useUnread.ts,
 * hooks/useUnread.test.ts).
 */
describe('clockOffset', () => {
    it('серверная метка ещё не подтверждена (pending write) — сверяться не с чем', () => {
        expect(clockOffset(null, 1_000)).toBeNull();
    });

    it('часы вкладки и сервера совпадают — сдвиг нулевой', () => {
        expect(clockOffset(1_000, 1_000)).toBe(0);
    });

    it('часы вкладки спешат — сдвиг отрицательный, ровно на разницу', () => {
        // Сервер отметил документ в 1000, а вкладка получила снимок, когда её собственные
        // часы уже показывали 1015, — спешат на 15 мс, и поправка должна их настолько же
        // осадить.
        expect(clockOffset(1_000, 1_015)).toBe(-15);
    });

    it('часы вкладки отстают — сдвиг положительный', () => {
        expect(clockOffset(1_015, 1_000)).toBe(15);
    });
});
