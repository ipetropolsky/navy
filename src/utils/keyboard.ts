/**
 * Выехала ли экранная клавиатура — по фокусу в текстовом поле.
 *
 * Спросить об этом браузер нельзя: клавиатуру он не показывает никак. `visualViewport`
 * подсказывает косвенно — окно вдруг стало ниже, — но так же выглядит и появление панели
 * браузера, и поворот телефона, и уж точно так выглядит настольное окно, которое просто
 * потянули за край. Фокус в поле ввода честнее: клавиатура выезжает ровно тогда, когда
 * в поле собираются писать, и убирается, когда из него ушли.
 *
 * Список типов — только те, под которые браузер даёт буквенную клавиатуру. Кнопки,
 * переключатели и выбор цвета — тоже `input`, но никакой клавиатуры за ними нет.
 */
const TEXT_INPUT_TYPES = new Set(['text', 'search', 'email', 'url', 'tel', 'password', 'number']);

export const isTextField = (node: EventTarget | null): boolean => {
    if (node instanceof HTMLTextAreaElement) {
        return true;
    }
    return node instanceof HTMLInputElement && TEXT_INPUT_TYPES.has(node.type);
};
