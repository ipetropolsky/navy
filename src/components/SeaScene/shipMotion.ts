import { SCENE_SCALE_LENGTH, SHIP_SPRITES } from '@/components/ships/shipSprites';
import {
    ISLAND_FREE_SLOT,
    ISLAND_SIDE,
    SHIP_KINDS,
    SHIP_SPECS,
    ShipKind,
    ShipPlacement,
    otherSide,
    slotDepth,
} from '@/types/channel';

/**
 * Ход корабля по сцене: сколько ему идти, куда и как долго.
 *
 * Расстояния считаются в длинах корпуса, а не в пикселях и не в долях экрана: CSS-свойство
 * translate в процентах отсчитывается от собственной ширины элемента, то есть «120%» — это
 * ровно 1.2 длины корабля, и переводить ничего не нужно.
 *
 * А вот длительность считается через метры и узлы. Иначе никак: «длина корпуса в секунду»
 * у катера и у тральщика означает совершенно разную скорость, и корабли ходили бы по одному
 * морю в разных единицах. Сколько метров в кадре, знает мерка сцены; с какой скоростью идут
 * на рейде — константа ниже.
 */

/** Узел — морская миля в час. */
const KNOT_MPS = 1852 / 3600;

/*
 * Линейка сцены — SCENE_SCALE_LENGTH из shipSprites: сколько метров в единице масштаба.
 * Мерка нужна общая для всех: море одно, и катер не может идти по нему в других метрах,
 * чем тральщик. На ближнем плане получается кадр шириной около 140 м, у горизонта —
 * около 300 м: это и есть перспектива, выраженная в метрах.
 */

/**
 * Ход на рейде, узлов: у самого длинного корабля справочника и у самого короткого. Полный ход
 * тут ни при чём — маневрируют не им. Зато размер важен: катеру и разогнаться, и остановиться
 * проще, чем тяжёлому кораблю, и волны он разводит меньше, поэтому позволить себе может больше.
 *
 * Числа — стилизация, и это стоит знать. Настоящий манёвр на рейде идёт три-четыре узла,
 * но кадр здесь шириной около ста метров на переднем плане и около двухсот пятидесяти
 * у горизонта: на четырёх узлах корабль пересекал бы его две-четыре минуты, и смотреть на это
 * никто не станет. Взято примерно вдвое больше — так манёвр укладывается в те секунды,
 * что на него смотрят, и при этом остаётся неспешным.
 *
 * Это средняя по манёвру. В самый быстрый момент корабль идёт вдвое быстрее: он разгоняется
 * и тормозит, а кривая в стилях распределяет скорость внутри прогона (замер по самим кривым).
 */
const ROADSTEAD_KNOTS_LONGEST = 6;
const ROADSTEAD_KNOTS_SHORTEST = 10;

/** Ход на рейде у этого корабля: между двумя пределами по его длине. */
const roadsteadKnots = (kind: ShipKind): number => {
    const lengths = SHIP_KINDS.map((item) => SHIP_SPECS[item].length);
    const shortest = Math.min(...lengths);
    const longest = Math.max(...lengths);
    const size = (SHIP_SPECS[kind].length - shortest) / (longest - shortest);
    return ROADSTEAD_KNOTS_SHORTEST + (ROADSTEAD_KNOTS_LONGEST - ROADSTEAD_KNOTS_SHORTEST) * size;
};

/** Задним ходом корабль идёт медленнее переднего: винт и обводы работают не в свою сторону. */
const ASTERN_SPEED_RATIO = 0.7;

/**
 * Разгон и торможение, м/с². Одно число на все манёвры и на все корабли, и в этом весь смысл:
 * рывок глаз ловит не по скорости, а по тому, как быстро она набирается, и от длины хода
 * зависеть это не должно.
 *
 * Само по себе ускорение ничего не двигает — форму движения задаёт кривая в стилях, — оно
 * только ограничивает скорость короткого хода, см. ниже.
 */
const MANOEUVRE_ACCEL = 1;

/**
 * Средняя скорость прогона, м/с. Пока путь длинный, она упирается в ход на рейде: корабль
 * успевает разогнаться, идёт и тормозит. На коротком не успевает — он выходит на пик к середине
 * пути и оттуда сразу гасит ход, и настоящая скорость получается ниже заданной.
 *
 * Отсюда и формула. У кривых захода и ухода пик вдвое выше средней — ровно как у треугольного
 * профиля, где половину пути разгоняются, а половину тормозят; в таком профиле путь и ускорение
 * дают среднюю sqrt(a * s) / 2. Порог, после которого одно сменяется другим, считать отдельно
 * не нужно: до него верх берёт разгон, после — ход на рейде.
 *
 * Без этого короткий манёвр шёл бы с той же средней скоростью, что и заход через весь кадр,
 * только вчетверо резче: путь короче, скорость та же, а времени на разгон почти нет. Со стороны
 * это читается как дёрганая парковка, а не как манёвр.
 */
const sailSpeed = (metres: number, kind: ShipKind, astern: boolean): number => {
    const cruise = roadsteadKnots(kind) * KNOT_MPS;
    return Math.min(cruise, Math.sqrt(MANOEUVRE_ACCEL * metres) / 2) * (astern ? ASTERN_SPEED_RATIO : 1);
};

/**
 * Потолок длительности — и он же сейчас главный ограничитель. Кадр на переднем плане шириной
 * около ста метров, у горизонта — около двухсот пятидесяти, и на четырёх узлах корабль
 * проходил бы его несколько минут. Это честно, но смотреть на такое никто не станет: вошедший
 * не должен ждать своего корабля дольше, чем длится сама новость о нём.
 *
 * Так что настоящая скорость в кадре сейчас определяется этим числом, а не узлами: почти
 * каждый манёвр в потолок и упирается. Заодно потолок отменяет и предел разгона — упёршийся
 * в него корабль трогается резче, чем ему положено. Иначе никак: 30с — это про терпение
 * смотрящего, а оно кончается раньше любой физики.
 */
const MAX_SAIL_SECONDS = 30;

/**
 * Запас за кромкой кадра при заходе, % ширины сцены. Считать «ровно до кромки» нельзя:
 * место корабля в кадре ещё проходит через clamp — тот не даёт кораблю подойти к краю
 * вплотную, — и от расчётной точки настоящая отличается. Раньше из-за этого из-за края торчал
 * нос стоящего корабля, а трогался он уже на глазах: разгон был виден. Кламп теперь повторён
 * в расчёте, а запас остаётся на всё остальное — на отступ в пикселях и на будущие поправки.
 */
export const ENTER_GUARD = 20;

/**
 * Запас за кромкой при уходе, % ширины сцены. Целый кадр: корабль не тормозит у края,
 * а уходит и уходит, и пропасть из разметки должен заведомо после того, как скрылся.
 * Идёт он этот запас уже на полном ходу, поэтому и уходит времени немного.
 */
export const LEAVE_GUARD = 100;

/**
 * Ширина слота, % ширины сцены: столько занял бы самый длинный корабль справочника,
 * стоя на этой дальности. Числа общие для размера корабля и для мерки моря ниже: сделай их
 * больше, и корабли станут крупнее, а кадр — уже в метрах, что одно и то же.
 *
 * По-честному размер шёл бы за глубиной один в один — она и есть 1/D, — и дальний корабль
 * выходил бы в пять с половиной раз мельче ближнего: катер у горизонта стал бы точкой
 * в три десятка пикселей, в которой не разобрать ни силуэта, ни номера. Поэтому слагаемое: перспектива
 * держит основное, а постоянная часть не даёт дальнему краю выродиться. Поджато ровно
 * настолько, чтобы корабль всё ещё читался кораблём, — дальше уже начинается неправда,
 * и стоящий у горизонта корабль выглядит подвешенным над водой.
 */
const slotWidthPercent = (slot: number): number => 10 + slotDepth(slot) * 50;

export const shipWidthPercent = (slot: number, kind: ShipKind): number =>
    slotWidthPercent(slot) * SHIP_SPRITES[kind].scale;

/**
 * Ширина овала свободного места, % ширины сцены. Считается от той же ширины слота, что
 * и корабль, поэтому дальние места мельче ближних — овалы лежат на воде и подчиняются
 * той же перспективе. Доля заметно меньше единицы: овал — отметка места, а не обвод корпуса,
 * и в кадре он спорит и с соседними коридорами (те разнесены на треть кадра), и с соседними
 * линиями, которые перспектива сводит к горизонту тем теснее, чем они дальше.
 */
const BERTH_WIDTH_SHARE = 1 / 3;

export const berthWidthPercent = (slot: number): number => slotWidthPercent(slot) * BERTH_WIDTH_SHARE;

/** Сколько метров моря приходится на процент ширины кадра на этой дальности. */
const metresPerPercent = (slot: number): number => SCENE_SCALE_LENGTH / slotWidthPercent(slot);

/**
 * Отступ от края кадра, % ширины сцены: в стилях это @ship-edge-gap в пикселях, и в долях
 * он тем больше, чем уже экран. Взята оценка сверху — на самом узком телефоне: ошибиться
 * в эту сторону безопасно, корабль просто уйдёт чуть дальше за кромку.
 */
const EDGE_GAP_PERCENT = 10;

/**
 * Где корабль стоит на самом деле. Стили не дают ему подойти к краю кадра вплотную — иначе
 * он читался бы наехавшим на границу, — и настоящее место отличается от выбранного расстановкой.
 * Ход считается от настоящего: иначе заходящий корабль стартует не оттуда, откуда думает,
 * и из-за кромки торчит его нос.
 */
export const shownLeft = (leftPercent: number, widthPercent: number, zoom: number): number => {
    const safe = (widthPercent / 2) * zoom + EDGE_GAP_PERCENT;
    return Math.min(Math.max(leftPercent, safe), 100 - safe);
};

/**
 * Сколько кораблю идти от стоянки за край кадра, % ширины сцены. Считается в долях кадра,
 * а не в длинах корпуса: «уйти за кромку» — это про кадр, и пересчёт одного в другое только
 * добавлял ошибок. Запас за кромкой у захода и у ухода разный: заходящему нужно надёжно
 * спрятаться до старта, уходящему — уйти с концами.
 */
export const pathToEdge = (
    leftPercent: number,
    widthPercent: number,
    zoom: number,
    side: 'left' | 'right',
    guard: number
): number => {
    const span = side === 'left' ? leftPercent : 100 - leftPercent;
    return span + (widthPercent * zoom) / 2 + guard;
};

/**
 * Сколько секунд кораблю идти столько-то процентов кадра. Путь переводим в метры по мерке
 * сцены, скорость берём по размеру корабля и по длине пути. Задним ходом — дольше.
 *
 * Скорость здесь средняя по манёвру, а не мгновенная: корабль и так трогается с нуля и в ноль
 * приходит, поэтому «столько-то метров за столько-то секунд» — честная мерка, а как скорость
 * распределится внутри прогона, решает кривая в стилях.
 */
export const sailSeconds = (
    pathPercent: number,
    slot: number,
    kind: ShipKind,
    astern: boolean,
    /**
     * Во сколько раз корабли в кадре растянуты сверх расчётного размера — на телефоне это
     * MOBILE_SHIP_ZOOM. Корабль стал крупнее, а кадр остался тем же, значит в кадре стало
     * меньше метров: без поправки на узком экране флот ходил бы быстрее, чем на широком.
     */
    zoom = 1
): number => {
    const metres = (pathPercent * metresPerPercent(slot)) / zoom;
    return Math.min(metres / sailSpeed(metres, kind, astern), MAX_SAIL_SECONDS);
};

/**
 * Дифферент на ходу, градусов: у самого тихого манёвра и у самого быстрого. Идущий корабль
 * приподнимает ту оконечность, которой идёт вперёд, — он всходит на собственную волну,
 * а корма садится. Углы нарочно маленькие: на рейде корабль маневрирует, а не летит глиссером,
 * и разница со стоящим должна читаться, а не бросаться в глаза.
 */
const TRIM_MIN_DEG = 0.3;
const TRIM_MAX_DEG = 0.7;

/** Скорость, на которой дифферент выходит на предельный угол, м/с: самый быстрый манёвр справочника. */
const TRIM_FULL_MPS = ROADSTEAD_KNOTS_SHORTEST * KNOT_MPS;

/**
 * Дифферент на этом манёвре, градусов. Считается по настоящей скорости прогона — путь,
 * делённый на время, — а не по паспортной: длительность упирается в потолок, и упёршийся
 * в него корабль идёт быстрее, чем ему положено по размеру. Знак ставит компонент: угол
 * зависит от того, какой стороной корабль идёт вперёд, а не от того, куда смотрит нос.
 */
export const sailTrim = (pathPercent: number, seconds: number, slot: number, zoom = 1): number => {
    if (pathPercent <= 0 || seconds <= 0) {
        return 0;
    }
    const speed = (pathPercent * metresPerPercent(slot)) / zoom / seconds;
    return Math.min(TRIM_MIN_DEG + (TRIM_MAX_DEG - TRIM_MIN_DEG) * (speed / TRIM_FULL_MPS), TRIM_MAX_DEG);
};

/**
 * Проходит ли корабль сквозь остров, идя в эту сторону. Остров занимает левую часть кадра
 * и на дальних слотах стоит выше корабля по кадру — корабль нарисовался бы прямо на нём.
 * Ближе ISLAND_FREE_SLOT он проходит перед берегом, и это как раз нормально.
 */
export const crossesIsland = (slot: number, side: 'left' | 'right'): boolean =>
    side === ISLAND_SIDE && slot < ISLAND_FREE_SLOT;

/**
 * За сколько слотов чужой корабль ещё считается стоящим на дороге. Ровно за один:
 * на своей дальности корабль всегда один — два в одном слоте расстановка не поставит, —
 * поэтому речь только о соседней. Соседний слот отличается по глубине на девятую часть
 * всей перспективы: корабли там почти одного размера и почти на одной линии, и проход
 * сквозь такого соседа читается как столкновение. Через слот разница уже видна, и корабль
 * проходит перед соседом или за ним — это в кадре происходит постоянно и вопросов не вызывает.
 */
const NEIGHBOUR_REACH = 1;

/** Стоит ли на пути чужой корабль — на соседней дальности и с той стороны, куда идём. */
const shipInTheWay = (place: ShipPlacement, others: ShipPlacement[], side: 'left' | 'right'): boolean =>
    others.some(
        (other) =>
            Math.abs(other.slot - place.slot) <= NEIGHBOUR_REACH &&
            (side === 'left' ? other.left < place.left : other.left > place.left)
    );

/**
 * В какую сторону корабль уходит из кадра и задним ли ходом. Обычно — вперёд, куда смотрит
 * нос: разворачиваться посреди рейда незачем. Но если впереди остров или корабль на соседней
 * дальности, уходит задним ходом, кормой вперёд — медленнее, зато не по суше и не в чужой борт.
 *
 * Заперт с обеих сторон — пойдёт мимо соседа, но не на берег: с соседом разойтись можно,
 * с островом нет.
 */
export const leaveCourse = (
    place: ShipPlacement,
    others: ShipPlacement[]
): { side: 'left' | 'right'; astern: boolean } => {
    const back = otherSide(place.facing);
    const isClear = (side: 'left' | 'right'): boolean =>
        !crossesIsland(place.slot, side) && !shipInTheWay(place, others, side);
    const goBack = !isClear(place.facing) && (isClear(back) || crossesIsland(place.slot, place.facing));
    return { side: goBack ? back : place.facing, astern: goBack };
};
